# Scanlation credit / staff / front-matter fragments that OCR picks up from
# the first and last pages of almost every chapter. These are never story
# content and must never be spoken. Matched case-insensitively, each pattern
# consuming to end-of-line/segment.
_CJK_RE = re.compile(
    "[\u3000-\u303f\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff"
    "\uf900-\ufaff\uff00-\uffef\uac00-\ud7af]+"
)

_CREDIT_PATTERNS = [
    r"\b(?:translator|translation|translated by|editor|edited by|proofreader|proof[- ]?read(?:er|ing)?|"
    r"redraw(?:er)?|redrawer|typeset(?:ter|ting)?|cleaner|cleaning|quality check|qa\s*/?\s*qc|q\.?c\.?|"
    r"raw provider|scanlat(?:or|ion)|uploader|credits?)\s*[:\-—].*",
    r"\b(?:redice studio|d\s*&\s*c\s*webtoon|d\s*&\s*c\s*media|webtoon\s+translator|original (?:novel|work|story)|"
    r"art(?:ist|work)?\s*[:\-—]|story\s*[:\-—]|adapted by).*",
    r"\bto be continued\b\.*",
    r"\bnext (?:chapter|episode)\b.*",
    r"\bthanks for reading\b.*",
    r"\bplease (?:support|rate|comment|subscribe)\b.*",
]

# strong markers — a known studio / author name, or a "Role:" label — that
# alone-plus-one signals a credits card; plain words like "studio" only count
# as weak corroboration so a line of dialogue that happens to say "studio" and
# "editor" isn't blanked.
_CREDIT_BLOB_STRONG = re.compile(
    r"(?:\bredice\b|\bred\s*ice\b|\bdubu\b|\bchugong\b|\bh[-\s]?goon\b|\bd\s*&\s*c\b|"
    r"\b(?:translat\w*|editor|edited|proofread\w*|typeset\w*|scanlat\w*|redraw\w*|"
    r"cleaner|art|artwork|story|original\s+novel)\s*(?:[:·\-—]|\bby\b))",
    re.IGNORECASE,
)
_CREDIT_BLOB_WEAK = re.compile(
    r"(?:\bwebtoon\b|\bstudio\b|\bartist\b|\badaptation\b|\bproduction\b|"
    r"\beditor\b|\btranslat\w*|\bproofread\w*|\bto\s+be\s+continued\b|"
    r"\bthanks\s+for\s+reading\b)",
    re.IGNORECASE,
)


def _is_credits_blob(text: str) -> bool:
    """True when a panel's text is a title / staff-credits card rather than
    story dialogue: at least one STRONG marker (studio/author name or a
    'Role:' label) plus one more credit marker, in a short non-prose line."""
    if not text:
        return False
    strong = {m.group(0).lower() for m in _CREDIT_BLOB_STRONG.finditer(text)}
    if not strong:
        return False
    weak = {m.group(0).lower() for m in _CREDIT_BLOB_WEAK.finditer(text)}
    if len(strong) + len(weak) < 2:
        return False
    words = re.findall(r"[A-Za-z']+", text)
    # a credits card is short and mostly proper nouns / labels, not prose
    return len(words) <= 18


def _clean_source_text(text: str) -> str:
    """Strip scanlation credits / front-matter from raw OCR/transcription text
    BEFORE it is translated and rewritten.

    Real jobs read scanlation credits ("Translator: ... Editor: ...") and
    front/end-matter ("To Be Continued", studio names) aloud verbatim because
    each is a "SUCCESS" OCR result as far as the transcriber is concerned.
    None of it is story content.

    Sound effects / onomatopoeia are DELIBERATELY LEFT IN — in verbatim
    (no-narration) mode they are part of what the viewer expects to hear, and
    in narration mode the rewrite prompt handles them. Conservative by design:
    only removes whole spans matching a credit/front-matter pattern, never
    touches dialogue or captions.
    """
    if not text or not text.strip():
        return text or ""

    cleaned = text

    # Drop CJK / Hangul / Kana runs entirely (see _CJK_RE). On raw
    # scanlations the only non-Latin text OCR picks up is the original-
    # language credits page, copyright notice and publisher watermarks
    # (Tencent etc.) — never story content, and all read aloud mangled
    # in word-for-word mode.
    cleaned = _CJK_RE.sub(" ", cleaned)
    # If after that the panel is basically empty or was ALL credits markup,
    # bail early — it's a front-matter / watermark panel.
    if len(re.sub(r"[^A-Za-z]", "", cleaned)) < 3:
        return ""

    # Whole-panel title / staff-credits card, wherever it lands in the chunk
    # stream (webtoon hosts pad several lead-in images before the real title):
    # a cluster of production-credit keywords / known studio + author names is
    # never story content.
    if _is_credits_blob(cleaned):
        return ""

    for pat in _CREDIT_PATTERNS:
        cleaned = re.sub(pat, " ", cleaned, flags=re.IGNORECASE)

    # Common raw-site / copyright boilerplate that survives in English too.
    cleaned = re.sub(
        r"\b(?:all rights reserved|do not (?:re[- ]?upload|repost)|reproduction is prohibited|"
        r"for( the)? promotional use only|read (?:it )?(?:first |for free )?(?:on|at)\s+\S+|"
        r"official (?:release|translation)|join our discord)\b.*",
        " ", cleaned, flags=re.IGNORECASE)

    # Raw-aggregator site watermark stamped INTO a story panel (baozimh,
    # mangabuddy, etc. — often mid-caption, and OCR mangles the TLD:
    # "www.baozimh.con"). Excise just the URL/domain token, NOT the rest of
    # the line — the caption text around it is real story content.
    cleaned = re.sub(r"\bwww\.\S+", " ", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\bhttps?://\S+", " ", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\b[a-z][a-z0-9-]{2,}\.(?:com|net|org|con|c0m|xyz|top)\b(?=$|\s|[.,!?])",
                     " ", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(
        r"\b(?:baozimh|baozi\s*manhua|mangabuddy|manhuaplus|manhuafast|mangapark|"
        r"asurascans?|asuracomic|flamescans?|reaperscans?)\b",
        " ", cleaned, flags=re.IGNORECASE)

    # Collapse artefacts left by the removals.
    cleaned = re.sub(r"\(\s*\)", "", cleaned)              # emptied parens
    cleaned = re.sub(r"\(\s*$", "", cleaned)               # dangling open paren
    cleaned = re.sub(r"^\s*\)", "", cleaned)               # dangling close paren
    cleaned = re.sub(r"\s*[,;:]\s*(?=[,;:.])", "", cleaned)
    cleaned = re.sub(r"^[\s,;:.\-—)]+", "", cleaned)
    cleaned = re.sub(r"[\s,;:\-—(]+$", "", cleaned)
    cleaned = re.sub(r"\s{2,}", " ", cleaned).strip()

    # Garbled-logo / credits guard: a studio logo or a stylised credits
    # graphic OCRs as a scatter of short, vowel-less, non-word tokens
    # ("GARO SSTTNO F O FEHNEEADS A S S YMY"). If most tokens don't look
    # like real words and the whole thing is short, it isn't dialogue.
    toks = re.findall(r"[A-Za-z][A-Za-z'\-]*", cleaned)
    SHORT_WORDS = {"a", "i", "an", "as", "at", "be", "by", "do", "go", "he", "if",
                   "in", "is", "it", "me", "my", "no", "of", "oh", "ok", "on", "or",
                   "so", "to", "up", "us", "we", "ah", "hi", "ha", "ho", "uh", "um"}
    if len(toks) >= 3:
        def _wordish(t: str) -> bool:
            tl = t.lower()
            if tl in SHORT_WORDS:
                return True
            if not (2 <= len(tl) <= 16) or not re.search(r"[aeiou]", tl):
                return False
            # English almost never has 4+ consonants in a row
            return re.search(r"[bcdfghjklmnpqrstvwxz]{4,}", tl) is None
        ratio = sum(_wordish(t) for t in toks) / len(toks)
        if ratio < 0.62 and len(cleaned) < 100:
            return ""

    # A panel whose whole transcription is a bare number ("40" — a page
    # number bleeding into an art panel) carries no dialogue. Drop it so the
    # frame plays silent instead of the TTS solemnly intoning "forty".
    # (Sound effects and short interjections are NOT numbers, so they pass.)
    if re.fullmatch(r"[\W\d]*\d[\W\d]*", cleaned) and re.fullmatch(r"\d{1,4}", cleaned.strip(" .,!?-—:;\"'")):
        return ""
    return cleaned


# Faithfulness guard for LLM narration output. A small local model (and
# occasionally a large one) will "continue the story": invent character
# names, locations and whole events that never appeared in the source text.
# Seen in a real job — llama3.2:3b turned a Solo Leveling page into a scene
# about "Kaito the exile" and "Yuna the elder of the clan". When the rewrite
# fails these checks we discard it and fall back to the cleaned source text.
_NARRATION_MAX_EXPANSION = 2.3   # output words / source words ceiling
_NARRATION_MIN_RATIO = 0.35      # output words / source words floor (dropped content)
_COMMON_CAPITALIZED = {
    "I", "I'm", "I'll", "I've", "I'd", "The", "A", "An", "He", "She", "They", "We", "You",
    "It", "His", "Her", "Their", "My", "Your", "Our", "This", "That", "These", "Those",
    "But", "And", "Or", "So", "Then", "When", "Now", "Here", "There", "What", "Why", "How",
    "If", "As", "At", "In", "On", "Of", "To", "For", "With", "No", "Yes", "Not", "Boss",
    "God", "Sir", "Hey", "Oh", "Ah", "Hunter", "Hunters", "Gate", "Gates", "Dungeon", "Dungeons",
}


def _proper_nouns(text: str) -> set:
    """Capitalized tokens that are not sentence-initial and not common words —
    a cheap proxy for named entities (people/places)."""
    nouns = set()
    for sentence in re.split(r"(?<=[.!?])\s+", text):
        words = sentence.split()
        for i, w in enumerate(words):
            bare = w.strip(".,!?\"'();:—-")
            if i == 0:
                continue
            if bare and bare[0].isupper() and bare.lower() != bare and bare not in _COMMON_CAPITALIZED:
                nouns.add(bare.rstrip("'s").lower())
    return nouns


def _cleanup_preserves_words(source: str, output: str) -> bool:
    """Guard for narration_style='cleanup': the LLM may only reorder the
    panel's words and fix OCR splits — never translate or rewrite. Accept
    only if the output is essentially the same bag of words."""
    def toks(s: str) -> list:
        return re.findall(r"[a-z]{3,}", s.lower())
    src, out = toks(source), toks(output)
    if not out:
        return False
    if not src:
        return len(out) <= 6
    if not (0.55 <= len(out) / len(src) <= 1.5):
        return False
    src_set, out_set = set(src), set(out)
    kept = len(src_set & out_set) / len(src_set)          # how much of source survived
    added = len(out_set - src_set) / max(1, len(out_set))  # how much is brand new
    return kept >= 0.6 and added <= 0.35


def _narration_is_faithful(source: str, output: str, cache_tag: str) -> bool:
    src_words = source.split()
    out_words = output.split()
    if not out_words:
        return False
    if src_words:
        ratio = len(out_words) / len(src_words)
        if ratio > _NARRATION_MAX_EXPANSION:
            log.warning("[%s] narration rejected: %.1fx expansion over source (%d -> %d words)",
                        cache_tag, ratio, len(src_words), len(out_words))
            return False
        if ratio < _NARRATION_MIN_RATIO and len(src_words) > 12:
            log.warning("[%s] narration rejected: only %.0f%% of source retained",
                        cache_tag, ratio * 100)
            return False
    # A token only counts as "invented" if its lowercase stem appears NOWHERE
    # in the source (not just not-as-a-proper-noun). This tolerates the model
    # title-casing words that are lowercase in the source ("daily quest" ->
    # "Daily Quest", "level up" -> "Level Up") — extremely common with webtoon
    # UI text — while still catching genuinely new names like "Kaito"/"Yuna".
    source_stems = {w.strip(".,!?\"'();:—-").lower().rstrip("'s") for w in source.split()}
    invented = {
        n for n in (_proper_nouns(output) - _proper_nouns(source))
        if n not in source_stems and n not in {c.lower() for c in _COMMON_CAPITALIZED}
    }
    # allow a single incidental slip; two or more named entities absent from
    # the source means the model is fabricating.
    if len(invented) >= 2:
        log.warning("[%s] narration rejected: introduces names/places absent from source: %s",
                    cache_tag, sorted(invented))
        return False
    return True


def _strip_forbidden(text: str) -> str:
    cleaned = text
    for pat in FORBIDDEN_PATTERNS:
        cleaned = re.sub(pat, "", cleaned, flags=re.IGNORECASE | re.MULTILINE)
    # Markdown-ish emphasis the small models sometimes wrap sound effects in
    # ("*crash* *boom*") — the asterisks would be spoken/awkward. Keep the word.
    cleaned = re.sub(r"\*+([^*]+?)\*+", r"\1", cleaned)
    cleaned = cleaned.replace("*", "")
    # \s+ (not \s{2,}) — a LONE embedded newline/tab from OCR's per-line
    # region joining must also collapse to a single space. This matters for
    # --narration-provider none (verbatim mode): edge-tts's internal
    # sanitizer explicitly preserves \n/\t/\r (they're outside the control-
    # character ranges it strips), so a raw newline between OCR'd speech
    # bubbles previously survived all the way into the spoken narration,
    # producing an unnatural pause/break mid-panel instead of a clean space.
    return re.sub(r"\s+", " ", cleaned).strip()


_OBSERVER_GARBLE_RE = re.compile(r"[A-Za-z]{4,}")
_ENGLISH_WORDS: "Optional[set]" = None


def _english_words() -> set:
    global _ENGLISH_WORDS
    if _ENGLISH_WORDS is None:
        _ENGLISH_WORDS = set()
        for path in ("/usr/share/dict/american-english", "/usr/share/dict/words"):
            try:
                with open(path, encoding="utf-8", errors="ignore") as fh:
                    _ENGLISH_WORDS = {w.strip().lower() for w in fh if w.strip().isalpha()}
                break
            except OSError:
                continue
    return _ENGLISH_WORDS


_RARE_BIGRAMS = re.compile(
    r"yy|yg|gy|ty(?![aeiou])|yt|vk|kv|qx|xq|jq|zx|xz|wg|gw|dy(?![aeiou])|fk|kf|pk|kp|bk")


def _text_has_garble(text: str) -> bool:
    """Gate for the observer LLM call. Fires when a token looks like a genuine
    OCR misfire, OR when the line carries several non-dictionary non-name
    tokens (a badly-recognised panel). The observer's output guard rejects
    anything but spelling fixes, so a false positive here only costs a wasted
    LLM call — never a bad edit."""
    words = _english_words()
    common = {w.lower() for w in _COMMON_CAPITALIZED}
    unknowns = 0
    for tok in re.findall(r"[A-Za-z][A-Za-z']*", text):
        tl = tok.lower().strip("'")
        if len(tl) < 2 or tl in common or (words and tl in words):
            continue
        if len(tok) <= 4 and tok[:1].isupper() and not tok.isupper():
            continue                                      # "Wang", "Shen" — a name
        unknowns += 1
        if re.search(r"(.)\1\1", tl):
            continue
        if (not re.search(r"[aeiou]", tl)
                or re.search(r"[bcdfghjklmnpqrstvwxyz]{4,}", tl)
                or _RARE_BIGRAMS.search(tl)
                or (len(tl) >= 5 and len(set(tl)) <= 2)):
            return True
    return unknowns >= 3


def _observer_fix_ocr(cfg: "PipelineConfig", text: str, cache_tag: str) -> str:
    """Optional tiny-LLM 'observer' (ollama llama3.2:3b): repair garbled OCR
    tokens IN PLACE — spelling only, never rewording. Hard-guarded: the output
    is accepted only if it keeps the same length, word count and ~all of the
    original tokens, so the model physically cannot paraphrase, translate or
    invent. Any failure -> the original text, unchanged."""
    if not text or len(text) < 8 or not _text_has_garble(text):
        return text
    try:
        client, model, provider = _resolve_llm_client(cfg)
    except Exception:
        return text
    if client is None:
        return text
    sys_p = (
        "You are an OCR spell-checker for comic-book text. You are given one "
        "line transcribed from a comic panel; some words are mis-recognised "
        "(e.g. 'ANYYG YTYOL' -> 'ANYTHING YOU', 'dunngoeoon' -> 'dungeon'). "
        "Fix ONLY clearly garbled words to the real word they were meant to "
        "be. Keep EVERYTHING else exactly: same words, same order, same "
        "punctuation, same capitalisation, same sound effects. Do not add, "
        "remove, reorder, translate or rephrase anything. If a word is a name "
        "or you are unsure, leave it. Reply with the corrected line only."
    )
    try:
        r = client.chat.completions.create(
            model=model,
            messages=[{"role": "system", "content": sys_p},
                      {"role": "user", "content": text}],
            temperature=0.0,
            max_tokens=min(400, len(text) + 80),
            timeout=40,
        )
        out = (r.choices[0].message.content or "").strip().strip('"').strip()
    except Exception as e:
        log.info("[%s] observer unavailable (%s) — keeping raw OCR", cache_tag, e)
        return text
    out = re.sub(r"\s+", " ", out.splitlines()[0] if out else "").strip()
    if not out or "[" in out or "]" in out or "SYSTEM" in out.upper():
        return text

    in_toks = re.findall(r"[A-Za-z']+", text)
    out_toks = re.findall(r"[A-Za-z']+", out)
    if not in_toks or abs(len(out_toks) - len(in_toks)) > 1:
        return text          # word count must match (±1) — no rewording
    if len(out) > len(text) * 1.25 + 6:
        return text

    # the LLM may ONLY touch tokens the garble gate itself flagged. Every
    # other input token (real words, and — crucially — character NAMES, which
    # the model loves to "correct" into English words) must survive verbatim,
    # same casing. This makes a name→word substitution impossible.
    def _garbled(tok: str) -> bool:
        tl = tok.lower().strip("'")
        w = _english_words()
        if tl in {c.lower() for c in _COMMON_CAPITALIZED} or (w and tl in w):
            return False
        if len(tok) <= 4 and tok[:1].isupper():
            return False
        if re.search(r"(.)\1\1", tl):
            return False
        return (not re.search(r"[aeiou]", tl)
                or bool(re.search(r"[bcdfghjklmnpqrstvwxyz]{4,}", tl))
                or bool(_RARE_BIGRAMS.search(tl))
                or (len(tl) >= 5 and len(set(tl)) <= 2))

    protected = {t for t in in_toks if not _garbled(t)}
    out_set = set(out_toks)
    if any(t not in out_set for t in protected):
        return text          # a clean word / name went missing -> reject

    if out != text:
        log.info("[%s] observer fixed OCR: %r -> %r", cache_tag, text[:70], out[:70])
    return out


def rephrase_text(cfg: PipelineConfig, text: str, cache_tag: str, prev_tail: str) -> str:
    """Call an LLM to rewrite (already-English) text into narration, chained with
    prev_tail for continuity. Cached by cache_tag.
    Provider selection (cfg.narration_provider):
      - auto: prefer OpenAI if key set, else Groq if key set, else none
      - openai/groq/none: explicit
    Any API error falls back to the raw text verbatim."""
    out_path = cfg.temp_scripts_dir / f"{cache_tag}.txt"
    if out_path.exists():
        log.info("[%s] narration script already exists — skipping rewrite", cache_tag)
        return out_path.read_text(encoding="utf-8")

    if not text:
        log.warning("[%s] no text available, writing empty placeholder script", cache_tag)
        out_path.write_text("", encoding="utf-8")
        return ""

    # Strip scanlation credits / front-matter / non-Latin watermarks before
    # anything else — noise in every downstream path. `text` from here on is
    # the cleaned source.
    text = _clean_source_text(text)
    if not text.strip():
        log.info("[%s] source was entirely credits/watermark noise — empty narration", cache_tag)
        out_path.write_text("", encoding="utf-8")
        return ""

    style = getattr(cfg, "narration_style", "verbatim")

    # verbatim: the OCR's own words, in the OCR's own order, nothing added.
    # No LLM, no translation — regardless of narration_provider.
    if style == "verbatim":
        narration = _strip_forbidden(text)
        if getattr(cfg, "observer", False):
            narration = _observer_fix_ocr(cfg, narration, cache_tag)
        out_path.write_text(narration, encoding="utf-8")
        return narration

    # Resolve which provider + key + base_url + model to actually use.
    provider = cfg.narration_provider
    openai_key = cfg.openai_api_key or os.environ.get("OPENAI_API_KEY")
    # cleanup needs an LLM even if the caller passed provider=none.
    if provider in ("auto", "none") and style == "cleanup":
        provider = "auto"
    if provider == "auto":
        if openai_key:
            provider = "openai"
        elif cfg.groq_api_key:
            provider = "groq"
        elif os.environ.get("OLLAMA_BASE_URL") or os.path.exists("/usr/local/bin/ollama") or os.path.exists("/usr/bin/ollama"):
            provider = "ollama"
        else:
            provider = "none"

    if provider == "none":
        log.warning(
            "[%s] [RAW/VERBATIM MODE ACTIVE] narration provider=none — using raw text verbatim without recap narration. "
            "If production recap narration is required, configure an upstream LLM provider.",
            cache_tag,
        )
        narration = _strip_forbidden(text)
        out_path.write_text(narration, encoding="utf-8")
        return narration

    from openai import OpenAI

    if provider == "ollama":
        # Ollama exposes an OpenAI-compatible API at localhost:11434/v1
        ollama_url = os.environ.get("OLLAMA_BASE_URL", "http://localhost:11434") + "/v1"
        ollama_model = os.environ.get("OLLAMA_TEXT_MODEL", "llama3.2:3b")
        log.info("[%s] using Ollama narration: %s at %s", cache_tag, ollama_model, ollama_url)
        try:
            client = OpenAI(api_key="ollama", base_url=ollama_url)
            model = cfg.narration_model or ollama_model
        except Exception as e:
            log.warning("[%s] Ollama client creation failed (%s) — falling back to verbatim", cache_tag, e)
            narration = _strip_forbidden(text)
            out_path.write_text(narration, encoding="utf-8")
            return narration
    elif provider == "openai":
        if not openai_key:
            log.error("[%s] narration provider=openai but no OPENAI_API_KEY — falling back to verbatim", cache_tag)
            narration = _strip_forbidden(text)
            out_path.write_text(narration, encoding="utf-8")
            return narration
        client = OpenAI(api_key=openai_key)
        model = cfg.narration_model or cfg.openai_model
    elif provider == "groq":
        if not cfg.groq_api_key:
            log.error("[%s] narration provider=groq but no GROQ_API_KEY — falling back to verbatim", cache_tag)
            narration = _strip_forbidden(text)
            out_path.write_text(narration, encoding="utf-8")
            return narration
        client = OpenAI(api_key=cfg.groq_api_key, base_url=GROQ_BASE_URL)
        model = cfg.narration_model or cfg.groq_model
    else:
        narration = _strip_forbidden(text)
        out_path.write_text(narration, encoding="utf-8")
        return narration

    if style == "cleanup":
        sys_prompt = CLEANUP_SYSTEM_PROMPT
        user_prompt = f"RAW OCR OF ONE PANEL:\n{text}"
        temperature = 0.1
    else:  # recap
        sys_prompt = SYSTEM_PROMPT
        # prev_tail is tone/tense continuity ONLY — framed as "already told,
        # don't reuse" so the model can't snowball an earlier invented name.
        user_prompt = (
            "Rewrite the SOURCE TEXT below into recap narration. Use only what it "
            f"contains.\n\nSOURCE TEXT:\n{text}"
        )
        if prev_tail:
            user_prompt = (
                f"[For tone/tense continuity only — already narrated, do NOT repeat or "
                f"build on its specifics]\n...{prev_tail}\n\n" + user_prompt
            )
        temperature = 0.45

    try:
        resp = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": sys_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=temperature,
            timeout=90,
        )
        raw_out = (resp.choices[0].message.content or "").strip()
        candidate = _strip_forbidden(raw_out)
        if style == "cleanup":
            # strip bracketed tags the small model likes to inject ("[SYSTEM]")
            # unless that exact tag was in the source
            for tag in set(re.findall(r"\[[A-Za-z ]{2,12}\]", candidate)):
                if tag.lower() not in text.lower():
                    candidate = candidate.replace(tag, " ")
            candidate = re.sub(r"\s{2,}", " ", candidate).strip()
        ok = bool(candidate) and (
            _cleanup_preserves_words(text, candidate) if style == "cleanup"
            else _narration_is_faithful(text, candidate, cache_tag)
        )
        if ok:
            narration = candidate
        else:
            narration = _strip_forbidden(text)
            log.info("[%s] LLM %s output rejected — using raw OCR words", cache_tag, style)
    except Exception as e:
        log.warning("[%s] narration API call failed via %s (%s) — using raw OCR words", cache_tag, provider, e)
        narration = _strip_forbidden(text)

    out_path.write_text(narration, encoding="utf-8")
    log.info("[%s] narration script written via %s/%s (%d chars)", cache_tag, provider, model, len(narration))
    return narration


def last_sentences(text: str, n: int = 2) -> str:
    sentences = re.split(r"(?<=[.!?])\s+", text.strip())
    sentences = [s for s in sentences if s]
    return " ".join(sentences[-n:])


def split_into_segments(text: str, n: int) -> List[str]:
    """Split narration text into n roughly-equal word chunks, one per frame,
    so every sliced image gets its own narration segment for tight sync.
    If there are fewer words than frames, trailing frames get an empty
    segment and simply hold silently for SILENT_FRAME_DURATION."""
    words = text.split()
    if n <= 0:
        return []
    if not words:
        return [""] * n

    segments: List[str] = []
    idx = 0
    total = len(words)
    for i in range(n):
        remaining_slots = n - i
        remaining_words = total - idx
        if remaining_words <= 0:
            segments.append("")
            continue
        seg_len = max(1, round(remaining_words / remaining_slots))
        segments.append(" ".join(words[idx: idx + seg_len]))
        idx += seg_len
    return segments


# ---------------------------------------------------------------------------
# 4. LOCAL-FIRST PRODUCTION TEXT-TO-SPEECH (Piper -> Piper retry -> eSpeak NG)
# ---------------------------------------------------------------------------
# NOTE: narration used to be synthesized one tiny word-chunk at a time (one
# edge-tts call per sliced frame) and then concatenated. edge-tts inserts a
# short natural pause at the start/end of every call it makes, so stitching
# dozens of these clips back-to-back produced an audible "stop" after every
# few words. Fixed by synthesizing each *panel's* full narration as a single
# continuous speech clip, then using the actual word-level timestamps from
# that one clip to divide it across frames — no re-synthesis, no seams.

def get_audio_duration(path: Path) -> float:
    """Probe an audio file's duration in seconds via ffprobe."""
    result = subprocess.run(
        [
            "ffprobe", "-v", "error", "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1", str(path),
        ],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
    )
    try:
        return float(result.stdout.strip())
    except ValueError:
        raise RuntimeError(f"ffprobe could not read duration of {path}: {result.stderr}")


def _generate_silence(path: Path, duration: float) -> None:
    # Output as WAV (not MP3) to avoid encoder delay/padding that causes
    # sync drift when concatenated. WAV is raw PCM — sample-accurate.
    run_ffmpeg(
        [
            "ffmpeg", "-y", "-f", "lavfi",
            "-i", f"anullsrc=r={AUDIO_SAMPLE_RATE}:cl=mono",
            "-t", f"{duration:.3f}",
            "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "1",
            str(path),
        ]
    )


def _audio_qa(path: Path, allow_silence: bool = False) -> bool:
    if not path.exists() or path.stat().st_size < 44:
        return False
    try:
        duration = get_audio_duration(path)
        if duration <= 0.05:
            return False
        if allow_silence:
            return True
        result = subprocess.run([
            "ffmpeg", "-hide_banner", "-i", str(path), "-af", "volumedetect", "-f", "null", "-",
        ], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=30)
        probe = result.stderr + result.stdout
        m = re.search(r"max_volume:\s*(-?\d+(?:\.\d+)?) dB", probe)
        return bool(m and float(m.group(1)) > -50.0)
    except Exception:
        return False


def _synthesize_with_espeak(text: str, out_wav: Path) -> None:
    espeak = shutil.which("espeak-ng") or shutil.which("espeak")
    if not espeak:
        raise RuntimeError("espeak-ng binary unavailable")
    result = subprocess.run([espeak, "-w", str(out_wav), text], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=120)
    if result.returncode != 0:
        raise RuntimeError(f"espeak-ng failed: {result.stderr[-200:]}")


def _synthesize_with_piper(text: str, out_wav: Path) -> None:
    piper = shutil.which("piper")
    model = os.environ.get("PIPER_VOICE_MODEL", "en_US-ryan-high.onnx")
    if not piper:
        raise RuntimeError("piper binary unavailable")
    # If model is a relative path or filename, let piper resolve it unless explicitly missing as an absolute path
    if Path(model).is_absolute() and not Path(model).exists():
        raise RuntimeError(f"piper voice model unavailable: {model}")
    # Deliberately NOT `with subprocess.Popen(...) as proc:` here -- verified
    # directly with an isolated timing test that Popen's context-manager
    # __exit__ calls its own unconditional (untimed) wait() while
    # propagating a TimeoutExpired raised inside the block, which blocks
    # until the child actually exits on its own instead of the requested
    # timeout: a `sleep 10` process with `communicate(timeout=1)` measured
    # at 10.00s end-to-end through the with-statement, vs 1.00s with the
    # explicit try/except/kill pattern below. That means this function's
    # 120s cap was not actually enforced -- a slow or stuck Piper
    # synthesis (long RAW/VERBATIM-mode text under CPU load competing
    # with rendering/OCR is exactly the realistic trigger) could hang far
    # past 120s instead of failing over to eSpeak as
    # synthesize_segment_audio's cascade intends, which is a real,
    # plausible contributor to narration going missing or a whole job
    # stalling on one segment.
    proc = subprocess.Popen(
        [piper, "--model", model, "--output_file", str(out_wav)],
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
    )
    try:
        _out, err = proc.communicate(text, timeout=120)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.communicate()  # reap the killed process so it doesn't linger as a zombie
        raise RuntimeError("piper timed out after 120s")
    if proc.returncode != 0:
        raise RuntimeError(f"piper failed: {err[-200:]}")


def _srt_to_vtt(srt_content: str) -> str:
    """Convert SRT subtitle content to WebVTT format."""
    lines = ["WEBVTT", ""]
    for line in srt_content.splitlines():
        # Convert comma to dot in timestamps: 00:00:01,234 -> 00:00:01.234
        if "-->" in line:
            lines.append(line.replace(",", "."))
        else:
            lines.append(line)
    return "\n".join(lines)


def _normalize_case_for_tts(text: str) -> str:
    """Convert shouty ALL-CAPS comic lettering to normal sentence case
    before handing text to a TTS engine.

    Comic/manhwa lettering is drawn in all-caps by convention -- a purely
    visual/stylistic choice by the letterer, carrying no more semantic
    weight than the specific font used -- but production neural TTS
    engines do not treat it as mere styling. Microsoft's own documentation
    on Azure/Edge neural voices (the same voice family this pipeline's
    primary engine, edge-tts, uses) explicitly confirms capitalization
    changes text-normalization and pronunciation behavior. Feeding raw
    all-caps OCR text straight to TTS is exactly the out-of-distribution
    input neural TTS models were never trained on (their training
    transcripts are ordinary mixed-case text) -- the documented cause of
    unnatural, shouty, or inconsistently-pronounced narration.

    This can't perfectly recover "proper" capitalization -- comic
    lettering doesn't preserve the original case distinction at all, so a
    name like "JINWOO" and a word like "STOP" are visually identical --
    but sentence case is still a strict improvement over leaving text
    all-caps, and is the standard mitigation this class of problem gets
    in practice.

    Leaves already-mixed-case text (e.g. from an upstream narration LLM
    rewrite, when one is configured) completely untouched -- only
    triggers when the text is actually shouty in the first place.
    """
    stripped = text.strip()
    if not stripped:
        return stripped
    letters = [c for c in stripped if c.isalpha()]
    if not letters:
        return stripped
    upper_ratio = sum(1 for c in letters if c.isupper()) / len(letters)
    if upper_ratio < 0.8:
        return stripped

    lowered = stripped.lower()
    parts = re.split(r'([.!?]+\s*)', lowered)
    rebuilt = []
    capitalize_next = True
    for part in parts:
        if not part:
            continue
        if capitalize_next and part[0].isalpha():
            part = part[0].upper() + part[1:]
            capitalize_next = False
        if re.fullmatch(r'[.!?]+\s*', part):
            capitalize_next = True
        rebuilt.append(part)
    result = "".join(rebuilt)
    # Standalone "i" -> "I" is a basic English capitalization rule
    # regardless of sentence position; cheap and worth restoring.
    result = re.sub(r'\bi\b', 'I', result)
    return result


def _prewarm_segment_audio(cfg: "PipelineConfig", chapter: "Chapter", segments: list) -> None:
    """Fill the per-segment audio cache in parallel. Each segment's synthesis
    is independent and network-I/O-bound (edge-tts), so a small thread pool
    collapses the per-chapter TTS wall time. Best-effort: any failure here is
    ignored — the sequential renderer re-runs that segment (and handles the
    Piper/eSpeak/silence cascade) exactly as before."""
    from concurrent.futures import ThreadPoolExecutor
    todo = []
    for seg in segments:
        tag, text = seg[0], (seg[1] or "").strip()
        if not text:
            continue
        cached = cfg.temp_audio_dir / chapter.tag / f"{tag}.wav"
        if cached.exists():
            continue
        todo.append((tag, text))
    if len(todo) < 2:
        return
    workers = max(2, min(int(os.environ.get("RECAP_TTS_WORKERS", "4")), len(todo)))

    def _one(item):
        try:
            synthesize_segment_audio(cfg, chapter, item[0], item[1])
        except Exception:
            pass

    t0 = time.time()
    with ThreadPoolExecutor(max_workers=workers) as ex:
        list(ex.map(_one, todo))
    log.info("[%s] pre-synthesised %d segments in %.1fs (%d-way)", chapter.tag, len(todo), time.time() - t0, workers)


def synthesize_segment_audio(cfg: PipelineConfig, chapter: Chapter, tag: str, text: str) -> tuple:
    """Generate atomic segment audio with Edge-TTS (primary), Piper ONNX (fallback), eSpeak NG (tertiary fallback).
    Also exports matching .vtt / .srt timing markers alongside Edge-TTS audio outputs for caption syncing.

    Returns (audio_path, tts_failed, word_boundaries). word_boundaries is a
    list of {"text", "start", "end"} dicts (seconds, relative to this
    segment's own audio) when edge-tts succeeded and provided per-word
    timing data -- see split_frame_timings, which uses this in place of
    an estimated proportional word-count split when it's available and
    trustworthy. None for every other path (cache hit, silent segment,
    Piper/eSpeak fallback -- neither provides word-level timestamps),
    in which case callers fall back to the pre-existing estimate.
    """
    seg_audio_dir = cfg.temp_audio_dir / chapter.tag
    seg_audio_dir.mkdir(parents=True, exist_ok=True)
    final_path = seg_audio_dir / f"{tag}.wav"
    text = text.strip()
    text = _normalize_case_for_tts(text)
    if final_path.exists() and _audio_qa(final_path, allow_silence=not text):
        return final_path, False, None

    final_path.unlink(missing_ok=True)
    tmp_path = seg_audio_dir / f"{tag}.tmp.wav"
    tmp_path.unlink(missing_ok=True)

    if not text:
        _generate_silence(tmp_path, SILENT_FRAME_DURATION)
        if not _audio_qa(tmp_path, allow_silence=True):
            tmp_path.unlink(missing_ok=True)
            raise RuntimeError(f"silent audio QA failed for {tag}")
        os.replace(tmp_path, final_path)
        return final_path, False, None

    failures = []

    import asyncio
    import edge_tts

    voice = cfg.voice or "en-US-ChristopherNeural"
    raw_path = seg_audio_dir / f"{tag}_raw.mp3"
    srt_path = seg_audio_dir / f"{tag}.srt"
    vtt_path = seg_audio_dir / f"{tag}.vtt"
    word_boundaries = []  # type: list

    async def _run_edge_tts():
        communicate = edge_tts.Communicate(text, voice, rate="+5%")
        submaker = edge_tts.SubMaker()
        with open(raw_path, "wb") as f:
            async for chunk in communicate.stream():
                if chunk["type"] == "audio":
                    f.write(chunk["data"])
                elif chunk["type"] in ("WordBoundary", "SentenceBoundary"):
                    submaker.feed(chunk)
                    if chunk["type"] == "WordBoundary":
                        # offset/duration are in 100-nanosecond ticks (the
                        # Windows/.NET "ticks" convention edge-tts's
                        # underlying service uses) -- confirmed against
                        # the package's own docs ("converts 100-nanosecond
                        # ticks into SRT-compliant timestamps"), not
                        # assumed. /1e7 converts to seconds.
                        word_boundaries.append({
                            "text": chunk["text"],
                            "start": chunk["offset"] / 1e7,
                            "end": (chunk["offset"] + chunk["duration"]) / 1e7,
                        })
        srt_text = submaker.get_srt()
        if srt_text:
            srt_path.write_text(srt_text, encoding="utf-8")
            vtt_path.write_text(_srt_to_vtt(srt_text), encoding="utf-8")

    try:
        asyncio.run(_run_edge_tts())
        if not raw_path.exists() or raw_path.stat().st_size < 100:
            raise RuntimeError("edge-tts produced empty or invalid audio file")
        raw_dur = get_audio_duration(raw_path)
        fade_out_start = max(0.0, raw_dur - SEGMENT_FADE_OUT)
        seg_af = f"afade=t=in:st=0:d={SEGMENT_FADE_IN},afade=t=out:st={fade_out_start:.3f}:d={SEGMENT_FADE_OUT}"
        run_ffmpeg(["ffmpeg", "-y", "-i", str(raw_path), "-af", seg_af, "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "1", str(tmp_path)])
        if not _audio_qa(tmp_path, allow_silence=False):
            raise RuntimeError("edge-tts output failed audio QA")
        os.replace(tmp_path, final_path)
        return final_path, False, (word_boundaries or None)
    except Exception as e:
        failures.append(f"edge-tts: {e}")
        log.warning("[%s] edge-tts failed for segment %s (%s) — attempting Piper ONNX fallback", chapter.tag, tag, e)
    finally:
        raw_path.unlink(missing_ok=True)

    # Fallback 1: Piper ONNX
    tmp_path.unlink(missing_ok=True)
    try:
        _synthesize_with_piper(text, tmp_path)
        if _audio_qa(tmp_path, allow_silence=False):
            os.replace(tmp_path, final_path)
            log.info("[%s] Piper ONNX fallback succeeded for segment %s", chapter.tag, tag)
            return final_path, False, None
        raise RuntimeError("piper output failed audio QA")
    except Exception as e:
        failures.append(f"piper: {e}")
        log.warning("[%s] Piper ONNX fallback failed for segment %s (%s) — attempting eSpeak NG fallback", chapter.tag, tag, e)

    # Fallback 2: eSpeak NG
    tmp_path.unlink(missing_ok=True)
    try:
        _synthesize_with_espeak(text, tmp_path)
        if _audio_qa(tmp_path, allow_silence=False):
            os.replace(tmp_path, final_path)
            log.info("[%s] eSpeak NG fallback succeeded for segment %s", chapter.tag, tag)
            return final_path, False, None
        raise RuntimeError("espeak output failed audio QA")
    except Exception as e:
        failures.append(f"espeak: {e}")
        log.warning("[%s] All TTS engines failed for segment %s (%s) — using silence fallback", chapter.tag, tag, " | ".join(failures))

    # Ultimate fallback in legacy mode: generate silence
    _generate_silence(tmp_path, SILENT_FRAME_DURATION)
    os.replace(tmp_path, final_path)
    return final_path, True, None

def build_chapter_audio_track(
    cfg: PipelineConfig, chapter: Chapter, segment_audio_paths: List[Path],
    narration_expected: bool = True,
) -> Path:
    """Concatenate per-segment (per-panel) audio clips into one continuous
    chapter audio track, then apply loudness normalization.
    Because each input clip is now a full continuous utterance (not a lone
    word), the only joins left are the natural breath-like gaps between
    panels/scenes — not mid-sentence chops. Resumable.

    `narration_expected` should reflect whether ANY segment in this chapter
    actually had real dialogue to narrate (the caller's `tts_attempted > 0`
    count) — NOT just whether `segment_audio_paths` is non-empty, which it
    always is even for a chapter with zero dialogue (every silent segment
    still produces a real silence WAV). Passing that wrong signal would make
    audio_qa's silent-audio check reject a legitimately quiet chapter's
    audio track as a QA failure."""
    out_path = cfg.temp_audio_dir / f"{chapter.tag}.mp3"  # final output still MP3 (re-encoded from WAV, so no padding issues)
    if out_path.exists():
        log.info("[%s] chapter audio track already assembled — skipping", chapter.tag)
        return out_path

    concat_list = cfg.temp_audio_dir / f"{chapter.tag}_audio_concat.txt"
    with concat_list.open("w", encoding="utf-8") as f:
        for p in segment_audio_paths:
            f.write(f"file '{p.resolve().as_posix()}'\n")

    # First: raw concat (stream copy). WAV files have no encoder delay/padding,
    # so concatenation with -c copy is sample-accurate — no sync drift.
    # Output MUST be WAV (not MP3) because -c copy can't put PCM into an MP3
    # container without re-encoding. The loudnorm step below re-encodes to MP3.
    raw_path = cfg.temp_audio_dir / f"{chapter.tag}_raw.wav"
    run_ffmpeg(
        [
            "ffmpeg", "-y", "-f", "concat", "-safe", "0",
            "-i", str(concat_list),
            "-c", "copy",
            "-f", "wav",
            str(raw_path),
        ]
    )

    # Second: audio post-processing — gentle loudness normalization only.
    #
    # PREVIOUSLY this chain used acompressor(attack=5ms,makeup=+2dB) + bass(+2dB)
    # + loudnorm. The compressor's 5ms attack combined with +2dB makeup gain
    # exaggerated the attack transient of every spoken phrase, producing an
    # audible "pop" at the onset of each narration segment. The bass boost
    # added a low-frequency "thump" on top. Both have been REMOVED.
    #
    # Per-segment fade-in/fade-out (applied in synthesize_segment_audio) now
    # eliminates click artifacts at clip boundaries, so all we need here is
    # smooth loudness normalization to keep volume consistent across chapters.
    #
    # loudnorm: EBU R128 normalization to TARGET_LOUDNESS_LUFS.
    #
    # NOTE: if a chapter has no narration at all (every segment fell back to
    # silence — narration.json entries all empty, or narrative rewrite
    # returned nothing), raw_path is pure digital silence end-to-end.
    # loudnorm's gain boost on an absolutely-zero signal trips a real
    # libmp3lame bug (psymodel.c calc_energy: Assertion 'el >= 0' failed,
    # verified locally), which crashes ffmpeg outright. There's nothing to
    # normalize in silence anyway, so on that failure we just copy
    # the raw (silent) track through untouched instead of crashing the job.
    #
    # Like render_chapter/merge_chapters, this writes to a .tmp path first
    # and only promotes to `out_path` (the resume-checked path above) after
    # audio_qa passes — a process killed mid-loudnorm-encode used to be able
    # to leave a truncated MP3 sitting directly at `out_path`, which a
    # resumed run would then treat as "already assembled" and feed straight
    # into render_chapter's video mux.
    tmp_path = cfg.temp_audio_dir / f"{chapter.tag}.mp3.tmp"
    tmp_path.unlink(missing_ok=True)
    af = f"loudnorm=I={TARGET_LOUDNESS_LUFS}:TP=-1.5:LRA=11"
    try:
        run_ffmpeg(
            [
                "ffmpeg", "-y", "-i", str(raw_path),
                "-af", af,
                "-ar", str(AUDIO_SAMPLE_RATE), "-b:a", AUDIO_BITRATE, "-ac", "2",
                "-f", "mp3",
                str(tmp_path),
            ]
        )
    except RuntimeError as e:
        log.warning(
            "[%s] audio post-processing failed (%s) — falling back to raw (unprocessed) audio track",
            chapter.tag, e,
        )
        tmp_path.unlink(missing_ok=True)
        run_ffmpeg(["ffmpeg", "-y", "-i", str(raw_path), "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "2", "-f", "mp3", str(tmp_path)])

    qa = audio_qa(tmp_path, narration_expected=narration_expected)
    if not qa.ok:
        quarantine_dir = cfg.temp_audio_dir / "quarantine"
        quarantine_dir.mkdir(exist_ok=True)
        bad_path = quarantine_dir / f"{chapter.tag}.{int(time.time())}.{qa.reason}.bad"
        try:
            tmp_path.rename(bad_path)
        except OSError:
            tmp_path.unlink(missing_ok=True)
        raw_path.unlink(missing_ok=True)
        raise RuntimeError(f"[{chapter.tag}] chapter audio track failed QA ({qa.reason}) — see {bad_path}")

    atomic_promote(tmp_path, out_path)
    raw_path.unlink(missing_ok=True)
    log.info("[%s] assembled + post-processed chapter audio (loudnorm) -> %s", chapter.tag, out_path.name)
    return out_path


