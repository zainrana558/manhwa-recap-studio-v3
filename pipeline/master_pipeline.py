# ---------------------------------------------------------------------------
# 2a. BUBBLE-SAFE GUTTER DETECTION
#
# Guarantee: a horizontal cut is only ever placed on a row that is 100%
# free of "content" (art, line-work, text glyphs, bubble borders) across
# the ENTIRE width of the page, measured on a lightly-dilated content mask.
# Dilation bridges anti-aliasing gaps in bubble outlines and the small gaps
# between individual glyphs/letters so a bubble or text line is always seen
# as one solid blob — it is structurally impossible for a cut chosen this
# way to slice through the middle of a bubble, a line of text, or artwork,
# because any row that touches such a blob anywhere along its width is
# disqualified as a cut candidate.
# ---------------------------------------------------------------------------

def _get_text_detector():
    """Lazily load and cache the comic text/bubble detector (RT-DETR-v2,
    see TEXT_DETECTOR_MODEL_ID above). Loaded at most once per process;
    returns (None, None) cheaply on every subsequent call if it's missing
    or fails to load, so callers can unconditionally check the return
    value rather than needing their own separate "is this available"
    flag. Returns (model, image_processor) since RT-DETR-v2 inference via
    transformers needs both."""
    global _text_detector_model, _text_detector_processor, _text_detector_load_attempted
    if _text_detector_load_attempted:
        return _text_detector_model, _text_detector_processor
    _text_detector_load_attempted = True
    if not TEXT_DETECTOR_LOCAL_DIR.exists():
        log.info("Comic text/bubble detector not found at %s — skipping (pixel-only mask still applies)", TEXT_DETECTOR_LOCAL_DIR)
        return None, None
    try:
        from transformers import RTDetrImageProcessor, RTDetrV2ForObjectDetection
        _text_detector_processor = RTDetrImageProcessor.from_pretrained(str(TEXT_DETECTOR_LOCAL_DIR))
        _text_detector_model = RTDetrV2ForObjectDetection.from_pretrained(str(TEXT_DETECTOR_LOCAL_DIR))
        _text_detector_model.eval()
        log.info("Loaded comic text/bubble detector from %s", TEXT_DETECTOR_LOCAL_DIR)
    except Exception as exc:
        log.warning("Failed to load comic text/bubble detector (%s) — continuing without it", exc)
        _text_detector_model = None
        _text_detector_processor = None
    return _text_detector_model, _text_detector_processor


def _get_text_detector_onnx():
    """The small INT8 RT-DETR-v2 ONNX (TEXT_DETECTOR_ONNX_PATH). onnxruntime
    only, no torch. (None) if absent / fails."""
    global _text_detector_onnx, _text_detector_onnx_attempted
    if _text_detector_onnx_attempted:
        return _text_detector_onnx
    _text_detector_onnx_attempted = True
    if not TEXT_DETECTOR_ONNX_PATH.exists():
        return None
    try:
        import onnxruntime as ort
        _text_detector_onnx = ort.InferenceSession(
            str(TEXT_DETECTOR_ONNX_PATH), providers=["CPUExecutionProvider"])
        log.info("Loaded comic text/bubble detector (INT8 ONNX) from %s", TEXT_DETECTOR_ONNX_PATH)
    except Exception as exc:  # pragma: no cover
        log.warning("text/bubble ONNX load failed (%s) — falling back to torch path", exc)
        _text_detector_onnx = None
    return _text_detector_onnx


def _detect_text_boxes_raw(img_gray) -> List[tuple]:
    """Run the text/bubble detector on ONE image as-is (no tall-image
    splitting -- see _detect_text_boxes for that), returning only its
    text_bubble and text_free class detections (both represent real,
    readable text; text_free specifically covers caption/narration boxes
    outside any speech bubble, which a plain bubble-only detector
    wouldn't distinguish from the empty bubble class) as (x1,y1,x2,y2)
    boxes in the image's own pixel coordinates. Empty list if the model
    is unavailable or detects nothing.
    """
    sess = _get_text_detector_onnx()
    if sess is not None:
        try:
            rgb = cv2.cvtColor(img_gray, cv2.COLOR_GRAY2RGB) if img_gray.ndim == 2 else img_gray
            h, w = rgb.shape[:2]
            S = TEXT_DETECTOR_ONNX_INPUT
            x = cv2.resize(rgb, (S, S)).transpose(2, 0, 1)[None].astype(np.float32) / 255.0
            labels, boxes, scores = sess.run(
                None, {"images": x, "orig_target_sizes": np.array([[h, w]], dtype=np.int64)})
            out = []
            for lab, box, sc in zip(labels[0], boxes[0], scores[0]):
                if float(sc) < 0.35 or int(lab) not in (1, 2):   # 1=text_bubble 2=text_free
                    continue
                x1, y1, x2, y2 = (int(round(float(v))) for v in box)
                if x2 - x1 >= 4 and y2 - y1 >= 4:
                    out.append((max(0, x1), max(0, y1), min(w, x2), min(h, y2)))
            return out
        except Exception as exc:  # pragma: no cover
            log.warning("text/bubble ONNX inference failed (%s) — trying torch path", exc)
    model, processor = _get_text_detector()
    if model is None:
        return []
    try:
        import torch
        from PIL import Image as PILImage
        img_rgb = cv2.cvtColor(img_gray, cv2.COLOR_GRAY2RGB) if img_gray.ndim == 2 else img_gray
        pil_img = PILImage.fromarray(img_rgb)
        inputs = processor(images=pil_img, return_tensors="pt")
        with torch.no_grad():
            outputs = model(**inputs)
        results = processor.post_process_object_detection(
            outputs, target_sizes=torch.tensor([(pil_img.height, pil_img.width)]), threshold=0.3,
        )
        boxes = []
        for result in results:
            for label_id, box in zip(result["labels"], result["boxes"]):
                label = int(label_id.item())
                if label not in (1, 2):  # 1=text_bubble, 2=text_free
                    continue
                x1, y1, x2, y2 = [round(float(v)) for v in box.tolist()]
                boxes.append((x1, y1, x2, y2))
        return boxes
    except Exception as exc:
        log.warning("Text/bubble detection failed (%s) — continuing with pixel-only mask", exc)
        return []


def _detect_text_boxes(img_gray) -> List[tuple]:
    """Run text/bubble detection on `img_gray`, splitting it into
    overlapping vertical bands first if it's unusually tall.

    Directly mirrors this model's own training preprocessing
    ("Tall Webtoons were split vertically", per its model card) rather
    than feeding it a single extreme-aspect-ratio image its training
    distribution didn't contain examples of -- a real, tall vertical
    manhwa page (or a merged multi-panel crop) fed in whole is out of
    distribution for a detector trained on pre-split, more reasonably-
    proportioned bands, which is a very plausible reason detections were
    still missing important text on this pipeline's actual webtoon
    content even after switching to a webtoon-inclusive model.

    Bands overlap by 20% of the band height so a text box that would
    otherwise straddle a band boundary is fully visible in at least one
    band. Detections from each band are offset back into the original
    image's coordinates and merged, de-duplicating boxes that show up
    in more than one overlapping band (by simple bounding-box containment
    rather than a full NMS pass -- adequate here since overlapping bands
    of the same source image produce near-identical, not just similar,
    duplicate detections).
    """
    h, w = img_gray.shape[:2]
    # Content cache — the same page is text-detected up to 3x per run
    # (_detect_page_panels enrichment, _compose_canvas, _should_scroll_fragment).
    # A cheap subsampled digest keys them together. Bounded to the last 64 pages.
    try:
        _k = (w, h, hash(img_gray[::37, ::37].tobytes()))
        _c = _detect_text_boxes._cache
        if _k in _c:
            return _c[_k]
    except Exception:
        _k = None

    if w == 0 or h / max(1, w) <= TALL_IMAGE_SPLIT_ASPECT_RATIO:
        _r = _detect_text_boxes_raw(img_gray)
        if _k is not None:
            _detect_text_boxes._cache[_k] = _r
        return _r

    band_h = w * TALL_IMAGE_SPLIT_ASPECT_RATIO
    overlap = band_h * 0.2
    step = band_h - overlap
    all_boxes = []  # type: List[tuple]
    y = 0.0
    while y < h:
        band_top = int(y)
        band_bot = int(min(h, y + band_h))
        band = img_gray[band_top:band_bot, :]
        for (x1, y1, x2, y2) in _detect_text_boxes_raw(band):
            all_boxes.append((x1, y1 + band_top, x2, y2 + band_top))
        if band_bot >= h:
            break
        y += step

    # De-duplicate: drop any box that's near-fully contained within an
    # already-kept box from an earlier (overlapping) band.
    deduped = []  # type: List[tuple]
    for box in all_boxes:
        x1, y1, x2, y2 = box
        area = max(1, (x2 - x1) * (y2 - y1))
        is_dup = False
        for kx1, ky1, kx2, ky2 in deduped:
            ix1, iy1 = max(x1, kx1), max(y1, ky1)
            ix2, iy2 = min(x2, kx2), min(y2, ky2)
            if ix2 > ix1 and iy2 > iy1:
                inter = (ix2 - ix1) * (iy2 - iy1)
                if inter / area > 0.8:
                    is_dup = True
                    break
        if not is_dup:
            deduped.append(box)
    if _k is not None:
        _c = _detect_text_boxes._cache
        _c[_k] = deduped
        if len(_c) > 64:
            _c.pop(next(iter(_c)))
    return deduped


_detect_text_boxes._cache = {}


def _add_text_boxes_to_mask(mask, img_gray) -> "np.ndarray":
    """Fill each detected text box into `mask` as a solid rectangle.

    This is what actually fixes multi-line captions getting sliced into
    single-line fragments: _build_dilated_content_mask's pixel threshold
    correctly protects a single line of ink, but the white space *between*
    two lines of the same caption box reads identically to a real
    inter-panel gutter, since there's no concept of "these separate lines
    belong to one logical block" at the pixel level. Filling in the
    model's own text bounding box turns the whole caption -- gaps
    included -- into one solid, connected blob, so the existing
    _check_bubble_union/gutter-scan logic (unchanged) naturally treats it
    as one indivisible unit. A small inward margin is trimmed off each
    box edge so an over-generous detection box doesn't accidentally
    swallow a genuine gutter running right alongside it.
    """
    text_boxes = _detect_text_boxes(img_gray)
    if not text_boxes:
        return mask
    h, w = mask.shape[:2]
    margin = 2
    for (x1, y1, x2, y2) in text_boxes:
        x1 = max(0, x1 + margin)
        y1 = max(0, y1 + margin)
        x2 = min(w, x2 - margin)
        y2 = min(h, y2 - margin)
        if x2 > x1 and y2 > y1:
            mask[y1:y2, x1:x2] = 255
    return mask


def _build_dilated_content_mask(img_gray, dark_thresh: int = 200) -> "np.ndarray":
    """Binary mask (255 = content) of everything that isn't near-white
    background, lightly dilated/closed so speech-bubble outlines, thin text
    strokes, and screentone dots merge into solid blobs instead of leaving
    tiny gaps that a naive row-scan could mistake for a safe gutter."""
    _, mask = cv2.threshold(img_gray, dark_thresh, 255, cv2.THRESH_BINARY_INV)
    # Bridge small horizontal gaps (letter spacing, bubble outline breaks)
    # without merging across a real gutter — kernel stays modest vertically.
    close_kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 5))
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, close_kernel, iterations=1)
    mask = cv2.dilate(mask, np.ones((3, 3), np.uint8), iterations=1)
    return mask


def _label_content_components(mask) -> List[tuple]:
    """Connected components of a content mask → list of (y1, y2, x1, x2, area)
    bounding boxes, used to sanity-check that no cut straddles a real blob
    (bubble, text line, character, etc.)."""
    n, _labels, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
    comps = []
    for i in range(1, n):
        x, y, w, h, area = stats[i]
        if area < 6:
            continue
        comps.append((int(y), int(y + h), int(x), int(x + w), int(area)))
    return comps


def _detect_panels_gutter_aware(img_gray) -> List[tuple]:
    """Bubble-safe panel detector for webtoon-style tall strips.

    Unlike percentage/variance-based gutter heuristics, a row is only ever
    classified as a valid cut if it is checked across N independent
    width-slices of the DILATED content mask and is completely empty in
    every one of them. This is a strictly stronger guarantee than "mostly
    white" — a bubble tail, a caption box, or a stray character sitting in
    an otherwise-white gap will keep that row (and the whole band around it,
    once merged with neighbours) out of consideration.

    Returns list of (x1, y1, x2, y2) tuples, full page width, sorted by y.
    """
    h, w = img_gray.shape
    if h < 10 or w < 10:
        return [(0, 0, w, h)]

    mask = _build_dilated_content_mask(img_gray)
    mask = _add_text_boxes_to_mask(mask, img_gray)
    components = _label_content_components(mask)

    n_slices = 8
    slice_w = max(1, w // n_slices)
    row_has_any_content = np.any(mask > 0, axis=1)
    is_gutter_row = np.zeros(h, dtype=bool)
    for y in range(h):
        if not row_has_any_content[y]:
            is_gutter_row[y] = True
            continue
        clear = True
        for s in range(n_slices):
            x0 = s * slice_w
            x1 = w if s == n_slices - 1 else (s + 1) * slice_w
            if np.any(mask[y, x0:x1] > 0):
                clear = False
                break
        is_gutter_row[y] = clear

    # Smooth to reject single-row noise (e.g. one stray dead pixel briefly
    # flipping a row to "gutter" inside dense artwork), but never smooth
    # enough to let a real gutter get swallowed.
    is_gutter_row = cv2.blur(
        is_gutter_row.astype(np.float32).reshape(-1, 1), (5, 1)
    ).flatten() > 0.6

    min_band_h = max(12, h // 350)
    bands: List[tuple] = []
    run_start = None
    for i, g in enumerate(is_gutter_row):
        if g and run_start is None:
            run_start = i
        elif not g and run_start is not None:
            if i - run_start >= min_band_h:
                bands.append((run_start, i))
            run_start = None
    if run_start is not None and h - run_start >= min_band_h:
        bands.append((run_start, h))

    if not bands:
        return [(0, 0, w, h)]

    # Cut at the safest row within each band — the row farthest from any
    # component that comes close to (but, by construction, never crosses)
    # the band's edges — then double-checked against every component so a
    # cut can never land inside a bbox that happens to graze the band.
    cut_points: List[int] = []
    for (s, e) in bands:
        cut = (s + e) // 2
        for (cy1, cy2, _cx1, _cx2, area) in components:
            if area < 40 or cy2 <= s or cy1 >= e:
                continue
            top_gap, bot_gap = cy1 - s, e - cy2
            if top_gap > bot_gap and top_gap > 4:
                cut = min(cut, s + max(2, top_gap // 2))
            elif bot_gap > 4:
                cut = max(cut, e - max(2, bot_gap // 2))
        cut_points.append(cut)

    boundaries = [0] + cut_points + [h]
    min_panel_h = max(30, h // 100)
    raw_panels = []
    for i in range(len(boundaries) - 1):
        top, bot = boundaries[i], boundaries[i + 1]
        if bot - top >= min_panel_h:
            raw_panels.append((0, top, w, bot))

    content_panels = [p for p in raw_panels if np.any(mask[p[1]:p[3], :] > 0)]
    if not content_panels:
        return [(0, 0, w, h)]

    # Merge runs of small adjacent fragments (e.g. a caption strip that got
    # isolated by a thin gutter) so they read as one coherent frame.
    merged = [list(content_panels[0])]
    for (x1, y1, x2, y2) in content_panels[1:]:
        prev = merged[-1]
        if (y2 - y1) < 150 and (prev[3] - prev[1]) < 200:
            prev[2], prev[3] = x2, y2
        else:
            merged.append([x1, y1, x2, y2])

    return [(p[0], p[1], p[2], p[3]) for p in merged if (p[3] - p[1]) >= min_panel_h]


def _check_bubble_union(mask, cut_y: int, img_shape: tuple) -> int:
    """Bubble Union Check:
    If a horizontal cut line intersects a content blob (speech bubble, text glyph, ascender, descender, or sound effect tail),
    move the cut line below (or above) the entire speech bubble component to keep dialogue intact in a single frame.
    """
    h, w = img_shape[:2]
    cut_y = max(0, min(h - 1, cut_y))
    if not np.any(mask[cut_y, :] > 0):
        return cut_y

    # Label connected components directly on binary mask
    n_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(mask, connectivity=8)
    intersected_bottoms = []
    intersected_tops = []
    for i in range(1, n_labels):
        cy1 = stats[i, cv2.CC_STAT_TOP]
        ch = stats[i, cv2.CC_STAT_HEIGHT]
        cy2 = cy1 + ch
        area = stats[i, cv2.CC_STAT_AREA]
        if area < 6:
            continue
        if cy1 <= cut_y < cy2:
            intersected_bottoms.append(cy2)
            intersected_tops.append(cy1)

    if intersected_bottoms:
        # Move cut line below the max bottom of intersected speech bubbles
        target_y = max(intersected_bottoms) + 5
        if target_y < h:
            return target_y
        # If moving below exceeds image height, move above the min top
        target_y = max(0, min(intersected_tops) - 5)
        return target_y

    return cut_y


def _apply_dynamic_padding(panel_box: tuple, mask, img_shape: tuple, padding_px: int = 30) -> tuple:
    """Minimum Vertical Padding & Speech Bubble Protection:
    When a panel slice contains text contours or speech bubbles near its top or bottom borders,
    automatically expand the slice bounding box by 30 pixels vertically (clamped to image height).
    """
    x1, y1, w, h = panel_box
    img_h, img_w = img_shape[:2]
    y2 = y1 + h

    # Check top boundary region (y1 to y1 + padding_px)
    top_region = mask[max(0, y1):min(img_h, y1 + padding_px), max(0, x1):min(img_w, x1 + w)]
    # Check bottom boundary region (y2 - padding_px to y2)
    bot_region = mask[max(0, y2 - padding_px):min(img_h, y2), max(0, x1):min(img_w, x1 + w)]

    new_y1 = y1
    new_y2 = y2

    if np.any(top_region > 0):
        new_y1 = max(0, y1 - padding_px)
    if np.any(bot_region > 0):
        new_y2 = min(img_h, y2 + padding_px)

    return (x1, new_y1, w, new_y2 - new_y1)


def _snap_cut_to_safe_row(mask, y: int, window: int = 24) -> int:
    """Nudge a candidate horizontal edge to the nearest row that is
    completely clear of content across the full width, within +/- window
    px. Applied as a final safety net to panel boxes from ANY detector
    (YOLO, contour, gutter-aware) so an edge can never clip a bubble tail
    or a line of text even if the upstream detector placed it a few pixels
    off. Returns the original y if no safe row is found nearby (better to
    keep the original box than snap arbitrarily far away)."""
    h = mask.shape[0]
    y = max(0, min(h - 1, y))

    # Perform Bubble Union check if cut intersects speech bubble
    y = _check_bubble_union(mask, y, (h, mask.shape[1]))

    if not np.any(mask[y, :] > 0):
        return y
    for d in range(1, window + 1):
        for cand in (y + d, y - d):  # Prefer moving down below text
            if 0 <= cand < h and not np.any(mask[cand, :] > 0):
                return cand
    return y


def _detect_panels_for_page(img_gray) -> tuple:
    """Top-level panel detector for one source page/strip image.

    Webtoon/manhwa raws are dominated by tall, single-column strips — for
    those, the bubble-safe gutter-aware detector gives the strongest
    guarantee (cuts can never cross a content pixel). For roughly
    page-shaped images (traditional multi-panel grid layouts), fall back to
    the existing YOLO/contour auto-detector, which understands multi-column
    layouts that a pure horizontal-gutter scan can't.

    Returns (panels, method_name) where panels is a list of (x, y, w, h)
    tuples and method_name is one of "gutter_aware", "yolo", "contour", or
    "whole_page" — identifying which detector actually produced the result,
    so callers can log an accurate summary instead of assuming one method
    ran for the whole chapter.
    """
    h, w = img_gray.shape
    if h / max(w, 1) > 1.3:
        strip_panels = _detect_panels_gutter_aware(img_gray)
        if strip_panels:
            return ([(x1, y1, x2 - x1, y2 - y1) for (x1, y1, x2, y2) in strip_panels], "gutter_aware")
    panels, method = _detect_panels_auto(img_gray)
    return panels, method


def _is_blank_crop(arr_gray) -> bool:
    """Check if a cropped panel image is blank (no real content).

    A panel is considered blank if it's nearly uniform — e.g. pure white,
    pure black, or a flat color with no artwork. We use pixel standard
    deviation: a real manga/manhwa panel has lots of detail (lines, shading,
    text) so its std is high (>15). Blank panels have std < 8.

    Also catches near-white panels (mean > 245 AND std < 15) which are the
    most common blank type in webtoons (white gutters caught as "panels").
    """
    if arr_gray is None or arr_gray.size == 0:
        return True
    mean_val = float(np.mean(arr_gray))
    std_val = float(np.std(arr_gray))
    # Very low std = uniform/blank regardless of color.
    if std_val < 8.0:
        return True
    # Near-white with low detail = blank white panel.
    if mean_val > 245.0 and std_val < 15.0:
        return True
    return False


def _looks_like_credits_panel(arr_rgb) -> bool:
    """A publisher / scanlation credits or translator's-note panel: a mostly
    white page carrying only rows of small text and NO artwork. Defined by
    what it lacks — colour and drawn art — so it catches the block whatever
    language the credits are in (these raw scans stamp the staff list in
    Chinese, which an English OCR head then can't even flag as text).

    Conservative on purpose: story panels in this genre are always coloured
    and/or full of linework, so the "bright + greyscale + a little ink"
    signature is specific to a text box. Used only on the first/last pages
    of a chapter, where front/back-matter lives.
    """
    if arr_rgb is None or getattr(arr_rgb, "size", 0) < 900:
        return False
    g = cv2.cvtColor(arr_rgb, cv2.COLOR_RGB2GRAY)
    bright = float((g >= 228).mean())          # page is mostly white
    ink = float((g < 110).mean())              # a little dark text
    hsv = cv2.cvtColor(arr_rgb, cv2.COLOR_RGB2HSV)
    sat = float(hsv[..., 1].mean())            # ~0 => no colour art
    edges = cv2.Canny(g, 60, 160)
    edge_frac = float((edges > 0).mean())      # art/linework => many edges
    if not (bright >= 0.72 and sat <= 12.0):
        return False
    # small greyscale credits block: a little ink, few edges
    if 0.003 <= ink <= 0.16 and edge_frac <= 0.08:
        return True
    # BOLD credits card ("Translator: … / Editor: …" in big type): more ink
    # and edges, but the ink still forms a HANDFUL of clean horizontal text
    # rows on white — no filled artwork region anywhere.
    if ink <= 0.34 and edge_frac <= 0.16:
        row_ink = (g < 110).mean(axis=1)
        inked_rows = row_ink >= 0.02
        bands, run = 0, 0
        for v in inked_rows:
            if v:
                run += 1
            else:
                if run:
                    bands += 1
                run = 0
        if run:
            bands += 1
        # a real drawn panel fills a big contiguous vertical region with ink;
        # a credits card is <= ~12 slim text bands and never densely inked
        if 1 <= bands <= 12 and float(inked_rows.mean()) <= 0.55:
            return True
    return False


def _is_lines_only_crop(arr_gray) -> bool:
    """Check if a cropped panel contains ONLY lines/borders (no text, no art).

    These are panels that have some content (so they pass the blank check) but
    the content is just thin lines, borders, dividers, or frame outlines — no
    actual text or artwork. These should be removed from the video because they
    add no narrative value.

    Detection method: analyze connected components of dark pixels.
    - TEXT = many small, non-elongated components (characters)
    - ART = large components with high pixel area (artwork, shading)
    - LINES = medium components that are very elongated (high aspect ratio)

    A panel is "lines only" if it has NO text-like components AND NO art-like
    components, but DOES have line-like components.

    Returns True if the panel should be REMOVED (lines/borders only).
    """
    if arr_gray is None or arr_gray.size == 0:
        return False  # let _is_blank_crop handle empty

    h, w = arr_gray.shape
    if h < 5 or w < 5:
        return False

    # Threshold to find dark pixels (content)
    _, binary = cv2.threshold(arr_gray, 180, 255, cv2.THRESH_BINARY_INV)
    n_labels, labels, stats, _ = cv2.connectedComponentsWithStats(binary, connectivity=8)

    if n_labels <= 1:
        return False  # no content at all (blank check handles this)

    text_components = 0
    art_components = 0
    line_components = 0

    for i in range(1, n_labels):
        area = int(stats[i, cv2.CC_STAT_AREA])
        cw = int(stats[i, cv2.CC_STAT_WIDTH])
        ch = int(stats[i, cv2.CC_STAT_HEIGHT])
        min_dim = max(1, min(cw, ch))
        max_dim = max(cw, ch)
        aspect = max_dim / min_dim

        # Skip tiny noise (< 5px)
        if area < 5:
            continue

        # TEXT-like: small area, low aspect ratio (roughly square = characters)
        # Characters are typically 5-500px and aspect < 3.5
        if area < 600 and aspect < 3.5:
            text_components += 1
        # ART-like: large area (big artwork blobs, shading regions)
        elif area > 1500:
            art_components += 1
        # LINE-like: very elongated (aspect > 4) — borders, dividers, frame outlines
        elif aspect > 4.0:
            line_components += 1
        else:
            # Medium, non-elongated — could be text or small art, count as text
            if area < 600:
                text_components += 1

    # The panel is "lines only" if it has line-like components but
    # NO text and NO art. We require at least 1 line component to classify
    # as lines-only (otherwise it's just a sparse panel).
    has_text = text_components >= 8  # need at least 8 char-like blobs for real text
    has_art = art_components >= 1
    has_lines = line_components >= 1

    return has_lines and not has_text and not has_art


def _is_featureless_vfx(arr_gray) -> bool:
    """Check if a panel slice candidate is a featureless background, visual effect,
    gradient, speed line, ice shard, or light aura region lacking character faces,
    dialogue bubbles, or structural story focal points.

    Detection criteria:
    - Structural contour density (Canny edges)
    - Presence of text glyphs (small bounded edge components) or distinct story focal points
    """
    if arr_gray is None or arr_gray.size == 0:
        return True

    h, w = arr_gray.shape
    if h < 20 or w < 20:
        return True

    edges = cv2.Canny(arr_gray, 50, 150)
    edge_density = float(np.count_nonzero(edges)) / float(arr_gray.size)

    # Analyze connected components of Canny edge contours
    n_labels, labels, stats, _ = cv2.connectedComponentsWithStats(edges, connectivity=8)

    text_components = 0
    substantive_contours = 0

    for i in range(1, n_labels):
        area = int(stats[i, cv2.CC_STAT_AREA])
        cw = int(stats[i, cv2.CC_STAT_WIDTH])
        ch = int(stats[i, cv2.CC_STAT_HEIGHT])

        if area < 10:
            continue
        # Text characters in edge domain are small bounded glyph components (e.g. 5 <= cw, ch <= 60)
        if 5 <= cw <= 60 and 5 <= ch <= 60 and area >= 15:
            text_components += 1
        elif area > 800 and (cw > 80 or ch > 80):
            substantive_contours += 1

    # Featureless visual effects (ice shards, speed lines, light aura) have < 4 text glyphs and low substantive contours
    if text_components < 4 and substantive_contours == 0:
        return True
    if text_components < 4 and edge_density < 0.02:
        return True

    return False


def _crops_are_near_duplicate(arr_gray_a, arr_gray_b, corr_thresh: float = 0.985) -> bool:
    """Cheap perceptual check for whether two panel crops are near-identical.

    Catches a single panel that a gutter cut has spuriously sliced into two
    (or more) near-duplicate pieces — e.g. a bright VFX/light-aura band
    inside one continuous panel getting misread as an inter-panel gutter —
    which otherwise ships as two adjacent frames showing what looks like
    the same panel twice, each padded out to MIN_FRAME_DURATION regardless
    of how little unique content (or narration) it actually has.

    Downsamples both crops to a small fixed size and compares via
    normalized cross-correlation, which is robust to the crops' differing
    source dimensions and tolerant of the minor rescale artifacts that
    fixed-size downsampling introduces.
    """
    if arr_gray_a is None or arr_gray_b is None or arr_gray_a.size == 0 or arr_gray_b.size == 0:
        return False
    small_a = cv2.resize(arr_gray_a, (32, 32), interpolation=cv2.INTER_AREA).astype(np.float32)
    small_b = cv2.resize(arr_gray_b, (32, 32), interpolation=cv2.INTER_AREA).astype(np.float32)
    a = small_a - small_a.mean()
    b = small_b - small_b.mean()
    denom = float(np.sqrt((a * a).sum()) * np.sqrt((b * b).sum()))
    if denom < 1e-6:
        # Both crops are essentially flat/uniform — treat as duplicate only
        # if they're also close in brightness (two different flat colors,
        # e.g. one white gutter fragment and one black panel, are not the
        # same content).
        return bool(abs(float(small_a.mean()) - float(small_b.mean())) < 3.0)
    corr = float((a * b).sum() / denom)
    return corr >= corr_thresh


def _clean_panel_boundary_edges(arr_rgb, arr_gray, max_scan_px: int = 15):
    """Clean panel boundary edge fragments (dual-panel overlap bug fix).

    Enhances horizontal gutter detection by looking for continuous black/white pixel rows
    or distinct edge color transitions between adjacent panels. Trims stray top/bottom edge fragments
    from adjacent panels (such as fire panel top bleed) before finalizing slice output.
    """
    h, w = arr_gray.shape
    if h < 30 or w < 30:
        return arr_rgb, arr_gray

    # Scan top rows for stray edge fragments from previous panel
    top_trim = 0
    for y in range(min(max_scan_px, h // 4)):
        row = arr_gray[y, :]
        mean_v = float(np.mean(row))
        # Continuous black border row (<10) or white gutter row (>245)
        if mean_v > 245 or mean_v < 10:
            top_trim = y + 1
        else:
            break

    # Scan bottom rows for stray edge fragments from next panel
    bot_trim = h
    for y in range(h - 1, max(h - max_scan_px - 1, h - h // 4), -1):
        row = arr_gray[y, :]
        mean_v = float(np.mean(row))
        if mean_v > 245 or mean_v < 10:
            bot_trim = y
        else:
            break

    if top_trim > 0 or bot_trim < h:
        if (bot_trim - top_trim) >= 20:
            arr_rgb = arr_rgb[top_trim:bot_trim, :]
            arr_gray = arr_gray[top_trim:bot_trim, :]

    return arr_rgb, arr_gray


def _detect_panels_yolo(img_gray) -> List[tuple]:
    """Detect panels using YOLOv5/v8 comic panel detection model.

    Uses a pretrained YOLO model (mosesb/best-comic-panel-detection) that
    was trained specifically on comic/manga panels. This is more accurate
    than CV-based detection for pages with complex layouts, splash panels,
    and non-rectangular panel shapes.

    Falls back gracefully if the model or torch is unavailable.

    Returns list of (x, y, w, h) tuples sorted by y position.
    """
    try:
        from ultralytics import YOLO
    except ImportError:
        return []

    model_path = str(Path(__file__).parent / "models" / "comic-panel-yolo" / "best.pt")
    if not Path(model_path).exists():
        log.info("Comic panel YOLO model not found at %s — falling back to CV/contour detection", model_path)
        return []

    try:
        model = YOLO(model_path)
        # Convert grayscale to 3-channel for YOLO (it expects BGR)
        if img_gray.ndim == 2:
            img_bgr = cv2.cvtColor(img_gray, cv2.COLOR_GRAY2BGR)
        else:
            img_bgr = img_gray

        results = model.predict(img_bgr, conf=0.25, iou=0.45, verbose=False)
        if not results or results[0].boxes is None:
            return []

        h, w = img_gray.shape[:2]
        page_area = w * h
        panels = []
        for box in results[0].boxes:
            x1, y1, x2, y2 = box.xyxy[0].cpu().numpy()
            x1, y1, x2, y2 = int(x1), int(y1), int(x2), int(y2)
            bw, bh = x2 - x1, y2 - y1
            area = bw * bh
            # Filter: min 2% area, max 98% area (looser than CV)
            if area < 0.02 * page_area or area > 0.98 * page_area:
                continue
            # Expand by 10px margin to avoid tight crops that clip artwork
            margin = 10
            x1 = max(0, x1 - margin)
            y1 = max(0, y1 - margin)
            bw = min(w - x1, bw + 2 * margin)
            bh = min(h - y1, bh + 2 * margin)
            panels.append((x1, y1, bw, bh))

        # NMS to remove near-duplicates (keep insets)
        panels = _suppress_nested(panels, iou_thresh=0.65)
        panels = _order_panels_reading_order(panels)
        return panels
    except Exception as e:
        log.warning("YOLO panel detection failed: %s", e)
        return []


def _order_panels_reading_order(panels: List[tuple]) -> List[tuple]:
    """Order panel boxes (x, y, w, h) into natural top-to-bottom,
    left-to-right reading order for LTR-read manhwa/comic grid pages.

    A naive sort purely by top-y coordinate (p[1], p[0]) breaks whenever
    panels in the same visual row are staggered or have different heights
    — extremely common in dynamic comic layouts with diagonal panel cuts
    or a tall splash panel next to two stacked smaller ones. That naive
    sort can place a panel from the NEXT row before the second panel of
    the CURRENT row, silently narrating story events out of order. This
    clusters panels into rows by vertical overlap first, then sorts each
    row left-to-right, before ordering rows top-to-bottom.
    """
    if not panels:
        return panels

    remaining = sorted(panels, key=lambda p: p[1])
    rows: List[List[tuple]] = []
    for p in remaining:
        x, y, w, h = p
        y2 = y + h
        placed = False
        for row in rows:
            ry1 = min(rp[1] for rp in row)
            ry2 = max(rp[1] + rp[3] for rp in row)
            overlap = min(y2, ry2) - max(y, ry1)
            min_h = min(h, ry2 - ry1)
            if min_h > 0 and overlap / min_h > 0.4:
                row.append(p)
                placed = True
                break
        if not placed:
            rows.append([p])

    rows.sort(key=lambda row: min(rp[1] for rp in row))
    ordered: List[tuple] = []
    for row in rows:
        row.sort(key=lambda rp: rp[0])
        ordered.extend(row)
    return ordered


def _detect_panels_auto(img_gray) -> tuple:
    """Auto-mode panel detection: run YOLO first, fall back to CV if weak.

    This is the cbxy "auto" engine approach:
    1. Run YOLO (most accurate for complex layouts)
    2. If YOLO returns 0 panels or 1 panel covering ≥70% of page (weak),
       run CV detection and use whichever produced more panels.
    3. If CV also looks weak, use the whole page as one panel.

    Returns (panels, method_name): panels is a list of (x, y, w, h) tuples;
    method_name is "yolo", "contour", or "whole_page" — whichever actually
    produced the returned panels.
    """
    h, w = img_gray.shape
    page_area = w * h

    # Try YOLO first
    yolo_panels = _detect_panels_yolo(img_gray)

    # Check if YOLO looks weak
    yolo_weak = (
        len(yolo_panels) == 0
        or (len(yolo_panels) == 1 and yolo_panels[0][2] * yolo_panels[0][3] >= 0.70 * page_area)
    )

    if not yolo_weak and len(yolo_panels) >= 2:
        # YOLO found multiple panels — use it
        log.debug("YOLO detected %d panels (strong)", len(yolo_panels))
        return yolo_panels, "yolo"

    # YOLO was weak — try CV
    cv_panels = _detect_panels_contour(img_gray)

    # Use whichever found more panels
    if len(cv_panels) > len(yolo_panels):
        log.debug("CV fallback: %d panels (YOLO found %d)", len(cv_panels), len(yolo_panels))
        return cv_panels, "contour"

    # Both weak — use whole page
    if not yolo_panels and not cv_panels:
        return [(0, 0, w, h)], "whole_page"

    if yolo_panels:
        return yolo_panels, "yolo"
    return cv_panels, "contour"


def _suppress_nested(panels: List[tuple], iou_thresh: float = 0.55) -> List[tuple]:
    """Drop boxes mostly contained in a larger panel (from cbxy).

    Greedy by descending area: a candidate is dropped if >=55% of its
    own area is contained in an already-kept larger panel. This removes
    speech bubbles and small insets that survived the area filter.
    """
    if not panels:
        return panels

    kept: List[tuple] = []
    by_area = sorted(panels, key=lambda p: p[2] * p[3], reverse=True)
    for candidate in by_area:
        cx, cy, cw, ch = candidate
        cx2, cy2 = cx + cw, cy + ch
        is_nested = False
        for kept_panel in kept:
            kx, ky, kw, kh = kept_panel
            kx2, ky2 = kx + kw, ky + kh
            # Compute containment: fraction of candidate inside kept_panel
            ix1 = max(cx, kx)
            iy1 = max(cy, ky)
            ix2 = min(cx2, kx2)
            iy2 = min(cy2, ky2)
            if ix2 <= ix1 or iy2 <= iy1:
                continue
            inter = (ix2 - ix1) * (iy2 - iy1)
            candidate_area = max(cw * ch, 1)
            if inter / candidate_area >= iou_thresh:
                is_nested = True
                break
        if not is_nested:
            kept.append(candidate)
    return kept


THIN_STRIP_MAX_HEIGHT_FRAC = 0.10  # a detected box shorter than this fraction of the
# page height AND much wider than it is tall is almost always a detached
# caption/onomatopoeia strip, not a real panel. On its own it renders as a
# near-empty blur-fill frame (a sliver of text blown up to fill 1080p) and
# still eats a MIN_FRAME_DURATION slot in the timeline.
THIN_STRIP_MIN_ASPECT = 4.0


def _consolidate_panel_boxes(boxes: List[tuple], page_w: int, page_h: int,
                             max_boxes: int) -> List[tuple]:
    """Post-process the per-page merged panel boxes before canvas composition.

    Two problems this fixes, both seen in real jobs:
      1. Detached thin text strips (a caption or a "BOOM"/"POW" sound-effect
         band that the detector split off from its panel) get emitted as
         standalone frames — each one is a sliver of text upscaled onto a
         1920x1080 blur-fill canvas, and each one still occupies a full
         narrated-frame time slot. Merge every such strip into the panel it
         is vertically adjacent to (previous if any, else next).
      2. Over-segmentation: a busy page detected as many small panels turns
         one source page into 6-10 frames, and the
         `len(frames) * MIN_FRAME_DURATION` audio floor then pads a short
         caption out to 15-25s of mostly-silent video. Enforce
         MAX_FRAMES_PER_PANEL (previously a defined-but-unused constant) by
         repeatedly merging the vertically-adjacent pair with the smallest
         combined area until the page is within budget.

    Boxes are assumed to already be in reading order (top-to-bottom for the
    single-column webtoon strips this pipeline targets). Returns a new list
    of (x, y, w, h) boxes, order preserved.
    """
    if not boxes:
        return boxes

    def _union(a, b):
        ax, ay, aw, ah = a
        bx, by, bw, bh = b
        x1, y1 = min(ax, bx), min(ay, by)
        x2, y2 = max(ax + aw, bx + bw), max(ay + ah, by + bh)
        return (x1, y1, x2 - x1, y2 - y1)

    work = list(boxes)

    # Pass 1: fold thin strips into a neighbour.
    consolidated: List[tuple] = []
    for box in work:
        _, _, bw, bh = box
        is_thin_strip = (
            bh < page_h * THIN_STRIP_MAX_HEIGHT_FRAC
            and bw >= bh * THIN_STRIP_MIN_ASPECT
        )
        if is_thin_strip and consolidated:
            consolidated[-1] = _union(consolidated[-1], box)
        elif is_thin_strip:
            consolidated.append(box)  # first box; may be merged forward below
        else:
            if consolidated:
                _, _, pw, ph = consolidated[-1]
                if ph < page_h * THIN_STRIP_MAX_HEIGHT_FRAC and pw >= ph * THIN_STRIP_MIN_ASPECT:
                    # previous kept box was itself an unmergeable leading strip
                    consolidated[-1] = _union(consolidated[-1], box)
                    continue
            consolidated.append(box)

    # Pass 2: enforce the per-page frame budget by merging adjacent pairs.
    while len(consolidated) > max_boxes:
        best_i, best_area = 0, None
        for i in range(len(consolidated) - 1):
            merged = _union(consolidated[i], consolidated[i + 1])
            area = merged[2] * merged[3]
            if best_area is None or area < best_area:
                best_area, best_i = area, i
        consolidated[best_i] = _union(consolidated[best_i], consolidated[best_i + 1])
        del consolidated[best_i + 1]

    return consolidated


def _detect_panels_contour(img_gray) -> List[tuple]:
    """Detect panels using improved contour-based detection (CV fallback).

    This is the CV fallback used when YOLO is unavailable or returns weak
    results. Combines techniques from comic-manga-narrator + cbxy.
    """
    h, w = img_gray.shape
    page_area = w * h

    # Step 1: threshold (gutters are white ≥200, panels are dark <200)
    _, binary = cv2.threshold(img_gray, 200, 255, cv2.THRESH_BINARY)

    # Step 2: morphological close to bridge text/art gaps within panels
    # Invert so panels are white blobs on black background
    panels_mask = cv2.bitwise_not(binary)
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (5, 5))
    panels_mask = cv2.morphologyEx(panels_mask, cv2.MORPH_CLOSE, kernel, iterations=2)

    # Step 3: flood-fill from 4 corners to mark page background (cbxy technique)
    # This prevents the entire page from being detected as one giant panel
    gutters = binary.copy()
    ff_mask = np.zeros((h + 2, w + 2), np.uint8)
    for seed in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
        if gutters[seed[1], seed[0]] > 0:
            cv2.floodFill(gutters, ff_mask, seed, 128)

    # Step 4: subtract background
    background = gutters == 128
    content = panels_mask.copy()
    content[background] = 0

    # Step 5: find external contours
    contours, _ = cv2.findContours(content, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    # Step 6-7: filter by area, dimensions, and aspect ratio
    panels = []
    for cnt in contours:
        area = cv2.contourArea(cnt)
        if area < 0.03 * page_area or area > 0.85 * page_area:
            continue
        x, y, bw, bh = cv2.boundingRect(cnt)
        # Reject thin slivers (cbxy thresholds)
        if bw < 0.08 * w or bh < 0.05 * h:
            continue
        ar = bw / max(bh, 1)
        if ar > 8.0 or ar < 0.15:
            continue
        # Small margin expansion
        margin = 5
        x = max(0, x - margin)
        y = max(0, y - margin)
        bw = min(w - x, bw + 2 * margin)
        bh = min(h - y, bh + 2 * margin)
        panels.append((x, y, bw, bh))

    # Step 8: nested suppression (cbxy technique)
    panels = _suppress_nested(panels, iou_thresh=0.55)

    # Step 9: weak detection fallback (cbxy heuristic)
    # If 0 panels or 1 panel covering ≥70% of page, use whole page
    if not panels:
        return [(0, 0, w, h)]
    if len(panels) == 1 and panels[0][2] * panels[0][3] >= 0.70 * page_area:
        return [(0, 0, w, h)]

    # Sort into natural reading order: rows by vertical overlap (handles
    # staggered/diagonal layouts), then left-to-right within each row.
    panels = _order_panels_reading_order(panels)
    return panels


