# Reference-style page framing (default). The recap videos this pipeline
# targets (e.g. the "Asura Chronicles" style) do NOT chop each page into
# individual bubble-sized panels — that produces frames that are just a
# strip of text blown up over a blur. Instead each on-screen view is a
# whole comic panel (or a short vertical run of panels) with its speech
# bubbles intact, contain-fit onto the canvas over a blurred copy of
# itself. This mode reproduces that: one frame per source page, splitting
# small, and always cutting on a gutter row so a bubble is never sliced.
# Set RECAP_FRAME_MODE=panel to fall back to the old per-panel slicer.
PANEL_MIN_AREA_FRAC = 0.010   # a component smaller than this fraction of the
                              # page is a stray mark / floating SFX, not a panel
PANEL_BUBBLE_AREA_FRAC = 0.045  # a component below this AND with a bright (white)
                              # interior is a speech bubble that overflowed its
                              # panel's border — reattach it to the nearest panel


def _get_panel_yolo():
    global _panel_yolo_session, _panel_yolo_load_attempted
    if _panel_yolo_load_attempted:
        return _panel_yolo_session
    _panel_yolo_load_attempted = True
    if not PANEL_YOLO_PATH.exists():
        log.info("Manga panel YOLO not found at %s — using flood-fill panel detection", PANEL_YOLO_PATH)
        return None
    try:
        import onnxruntime as ort
        _panel_yolo_session = ort.InferenceSession(
            str(PANEL_YOLO_PATH), providers=["CPUExecutionProvider"]
        )
        log.info("Loaded manga panel detector (YOLO26n) from %s", PANEL_YOLO_PATH)
    except Exception as e:  # pragma: no cover
        log.warning("panel YOLO load failed (%s) — using flood-fill fallback", e)
        _panel_yolo_session = None
    return _panel_yolo_session


def _yolo_detect_page(img_rgb, panel_conf: float = 0.20, text_conf: float = 0.25):
    """Run the Manga109-trained YOLO on a page. Returns (panels, texts) as
    lists of (x1, y1, x2, y2, score) in the page's own pixels, or (None, None)
    if the model isn't available."""
    sess = _get_panel_yolo()
    if sess is None:
        return None, None
    from PIL import Image
    W, H = img_rgb.size
    S = PANEL_YOLO_INPUT
    scale = min(S / W, S / H)
    nw, nh = int(round(W * scale)), int(round(H * scale))
    ox, oy = (S - nw) // 2, (S - nh) // 2
    canvas = Image.new("RGB", (S, S), (114, 114, 114))
    canvas.paste(img_rgb.resize((nw, nh), Image.BILINEAR), (ox, oy))
    x = np.asarray(canvas, dtype=np.float32).transpose(2, 0, 1)[None] / 255.0
    try:
        out = sess.run(None, {sess.get_inputs()[0].name: x})[0][0]  # (N, 6)
    except Exception as e:  # pragma: no cover
        log.warning("panel YOLO inference failed (%s)", e)
        return None, None
    panels, texts = [], []
    for row in out:
        x1, y1, x2, y2, sc, cl = float(row[0]), float(row[1]), float(row[2]), float(row[3]), float(row[4]), int(round(row[5]))
        bx1 = max(0.0, (x1 - ox) / scale); by1 = max(0.0, (y1 - oy) / scale)
        bx2 = min(float(W), (x2 - ox) / scale); by2 = min(float(H), (y2 - oy) / scale)
        if bx2 - bx1 < 4 or by2 - by1 < 4:
            continue
        if cl == 0 and sc >= panel_conf:
            panels.append((bx1, by1, bx2, by2, sc))
        elif cl == 1 and sc >= text_conf:
            texts.append((bx1, by1, bx2, by2, sc))
    return panels, texts


def _split_borderless_column(box, gray, texts) -> "List[list]":
    """Split one tall panel box into the individual webtoon beats stacked
    inside it.

    Borderless webtoon hosts serve a chapter as fixed-height chunk images and
    every panel is full-width with a generous light (occasionally flat-black)
    gutter between them; the border-trained YOLO detector collapses a whole
    column of stacked panels into one giant box. This finds those internal
    gutters — full-width bands of near-uniform page background — cuts there,
    trims each sub-panel to its OWN content (so half a blank gutter never
    rides along as dead space), and folds only genuinely tiny caption strips
    into a neighbour. A lone speech bubble is fused with the panel it
    introduces ONLY when it sits right against it — a bubble separated from
    every panel by a wide blank gap is kept as its own beat instead of
    dragging a far-away panel up into one long strip.

    A box not much taller than it is wide, or with no clean internal gutter,
    is returned unchanged. A gutter a YOLO text box straddles is never cut.
    """
    x1, y1, x2, y2 = (int(v) for v in box)
    W = max(1, x2 - x1)
    H = y2 - y1
    if H <= 1.35 * W or H < 320:
        return [list(box)]
    col = gray[max(0, y1):y2, max(0, x1):x2]
    if col.size == 0 or col.shape[0] < 120:
        return [list(box)]
    ci = col.astype(np.int16)
    Hc = col.shape[0]

    # "text on black" dramatic column vs normal light page — the gutter (and
    # the definition of 'ink') is inverted between the two.
    dark_page = float((col <= 40).mean()) > 0.45

    row_std = col.std(axis=1)
    dark_frac = (col <= 26).mean(axis=1)
    if dark_page:
        bg = 0.0
        # gutter row: a near-uniform full-width near-black band
        quiet = (dark_frac >= 0.90) & (row_std <= 20)
    else:
        # Robust page-background tone — median of the brightest ~30% of
        # pixels. Works for pure white, cream scanlations and grey paper
        # alike (the old fixed ">= 232" test silently failed on every
        # slightly-off-white source).
        flat = ci.ravel()
        bright_vals = flat[flat >= np.percentile(flat, 70)]
        bg = float(np.median(bright_vals)) if bright_vals.size else 245.0
        near_bg = (np.abs(ci - bg) <= 16).mean(axis=1)
        # a genuine inter-panel gutter is a clean full-width background band.
        # bg-tone (above) is what makes this robust on off-white sources; the
        # fraction stays fairly tight so a bright sky / white shirt inside a
        # panel doesn't read as a cut.
        quiet = ((near_bg >= 0.945) & (row_std <= 18)) | ((dark_frac >= 0.955) & (row_std <= 15))

    def _ink_rows(sub):
        """boolean per-row: does this row carry drawn content?"""
        si = sub.astype(np.int16)
        if dark_page:
            return (si > 55).mean(axis=1) > 0.010
        r = (np.abs(si - bg) > 22).mean(axis=1) > 0.010
        if r.sum() < 8:
            r = (si <= max(30.0, bg - 45)).mean(axis=1) > 0.05
        return r

    bands, i, n = [], 0, len(quiet)
    while i < n:
        if not quiet[i]:
            i += 1
            continue
        j = i
        while j < n and quiet[j]:
            j += 1
        if j - i >= 26:          # a real inter-panel gap is a generous band
            bands.append([i, j])
        i = j
    if not bands:
        return [list(box)]

    def _text_straddles(row_y):
        for (tx1, ty1, tx2, ty2, _s) in (texts or []):
            if ty1 < row_y - 3 and ty2 > row_y + 3 and min(tx2, x2) - max(tx1, x1) > 0.2 * W:
                return True
        return False

    # Content segments live BETWEEN the gutter bands. A fat gutter (>= 60px)
    # is dropped whole — its blank rows belong to no beat; a thin one is split
    # at its midpoint so each side keeps a small natural margin.
    spans, prev = [], 0
    for (a, b) in bands:
        lo, hi = (a, b) if b - a >= 60 else ((a + b) // 2, (a + b) // 2)
        if _text_straddles(y1 + (lo + hi) // 2):
            continue
        spans.append((prev, lo))
        prev = hi
    spans.append((prev, Hc))

    # text/bubble boxes overlapping this column, in column-local y (ints)
    col_texts = []
    for (tx1, ty1, tx2, ty2, _s) in (texts or []):
        if min(tx2, x2) - max(tx1, x1) > 0.12 * W:
            col_texts.append((int(ty1) - y1, int(ty2) - y1))

    def _snap_out_to_text(t0, t1):
        """grow [t0,t1] so it never bisects a speech bubble the detector saw."""
        for (a, b) in col_texts:
            if b <= t0 or a >= t1:
                continue                       # text box entirely outside — fine
            if a < t0:
                t0 = int(a) - 4
            if b > t1:
                t1 = int(b) + 4
        return int(t0), int(t1)

    def _trim_span(lo, hi):
        sub = ci[lo:hi]
        if sub.shape[0] < 8:
            return None
        rr = np.where(_ink_rows(sub))[0]
        if rr.size < 8:
            return None
        # generous padding so a bubble's faint rounded top/bottom isn't shaved
        t0 = int(rr[0]) - 12
        t1 = int(rr[-1]) + 13
        t0, t1 = _snap_out_to_text(lo + t0, lo + t1)
        t0 = max(0, t0)
        t1 = min(Hc, t1)
        return [x1, y1 + t0, x2, y1 + t1]

    segs = [s for s in (_trim_span(lo, hi) for (lo, hi) in spans) if s is not None]
    if len(segs) <= 1:
        return [list(box)]
    # de-overlap: two segments the text-snap pushed into each other are one beat
    segs.sort(key=lambda s: s[1])
    merged = [segs[0]]
    for s in segs[1:]:
        if s[1] < merged[-1][3] - 6:
            merged[-1][3] = max(merged[-1][3], s[3])
        else:
            merged.append(s)
    segs = merged
    if len(segs) <= 1:
        return [list(box)]

    def _is_thin_strip(s):
        h = s[3] - s[1]
        return h < 0.42 * W and h < 360

    def _is_lone_bubble(s):
        sg = gray[max(0, s[1]):s[3], max(0, s[0]):s[2]].astype(np.int16)
        if sg.size == 0:
            return False
        h, w = sg.shape
        if h > 0.62 * W or h > 470:         # a tall segment is never "just a bubble"
            return False
        ink = np.abs(sg - bg) > 40
        rr = np.where(ink.mean(axis=1) > 0.02)[0]
        cc = np.where(ink.mean(axis=0) > 0.02)[0]
        if rr.size == 0 or cc.size == 0:
            return False
        span_v = (rr[-1] - rr[0]) / max(1, h)
        cx = (cc[0] + cc[-1]) / 2.0 / max(1, w)
        fill = float(ink[rr[0]:rr[-1] + 1, cc[0]:cc[-1] + 1].mean())
        # ink confined to a compact, roughly-centred block = a speech balloon
        return span_v <= 0.9 and 0.18 <= cx <= 0.82 and fill >= 0.10

    def _ink_area(s):
        sg = gray[max(0, s[1]):s[3], max(0, s[0]):s[2]].astype(np.int16)
        if sg.size == 0:
            return 0.0
        return float((np.abs(sg - bg) > 40).mean()) if not dark_page else float((sg > 55).mean())

    # A short sub-panel (a caption strip, a lone bubble, a sliver of art) reads
    # better fused with the panel it sits next to than held as its own beat —
    # UNLESS it carries real text and is a long way from any panel (then it is
    # a deliberate standalone caption). This is the same "fuse downward"
    # behaviour as before the rewrite; the bg-tone fix above is what stopped
    # the giant slivers, not aggressive splitting.
    def _fold_pass(segs):
        changed = True
        while changed and len(segs) > 1:
            changed = False
            for k, s in enumerate(segs):
                if not (_is_thin_strip(s) or _is_lone_bubble(s)):
                    continue
                cand = []
                if k + 1 < len(segs):
                    cand.append((k + 1, segs[k + 1][1] - s[3]))
                if k - 1 >= 0:
                    cand.append((k - 1, s[1] - segs[k - 1][3]))
                if not cand:
                    continue
                j, gap = min(cand, key=lambda t: t[1])
                if gap > 1.0 * W:
                    # far from anything: keep only a real caption block, else
                    # it's scan noise / a stray mark — drop it
                    if _ink_area(s) < 0.045:
                        del segs[k]
                        changed = True
                        break
                    continue
                lo, hi = min(k, j), max(k, j)
                segs[lo] = [x1, min(segs[lo][1], segs[hi][1]), x2, max(segs[lo][3], segs[hi][3])]
                del segs[hi]
                changed = True
                break
        # any segment still shorter than ~0.42x width folds into its nearest
        # neighbour (no beat is worth a thin strip)
        changed = True
        while changed and len(segs) > 1:
            changed = False
            segs.sort(key=lambda s: s[1])
            for k, s in enumerate(segs):
                if (s[3] - s[1]) >= 0.42 * W:
                    continue
                j = k + 1 if k == 0 else (k - 1 if k == len(segs) - 1 else
                                          (k - 1 if (s[1] - segs[k - 1][3]) <= (segs[k + 1][1] - s[3]) else k + 1))
                lo, hi = min(k, j), max(k, j)
                segs[lo] = [x1, min(segs[lo][1], segs[hi][1]), x2, max(segs[lo][3], segs[hi][3])]
                del segs[hi]
                changed = True
                break
        return segs

    segs = _fold_pass(segs)

    # Text-cluster pass: a tall segment with no clean gutter but two or more
    # vertically-separated blocks of dialogue (a webtoon "conversation" page —
    # bubbles scattered over one continuous background) is really that many
    # beats. Cut in the clear gap BETWEEN bubble clusters (never through one).
    # This is what stops a whole page of dialogue landing on one 16-second
    # static frame.
    col_tb = sorted(((a, b) for (a, b) in ((int(t[1]) - y1, int(t[3]) - y1)
                     for t in (texts or []) if min(t[2], x2) - max(t[0], x1) > 0.12 * W)
                     if 0 <= a < Hc and 0 < b <= Hc + 40), key=lambda p: p[0])
    if col_tb and len(segs) < 40:
        clustered: "List[list]" = []
        for s in segs:
            sh = s[3] - s[1]
            # a compact single panel (roughly square or wider) is one beat even
            # with two bubbles; only look to split something meaningfully tall.
            if sh <= 1.15 * W:
                clustered.append(s)
                continue
            local = [(a, b) for (a, b) in col_tb if a >= s[1] - y1 - 8 and b <= s[3] - y1 + 8]
            if len(local) < 2:
                clustered.append(s)
                continue
            # group boxes into clusters (a clear vertical gap between them)
            groups = [[local[0]]]
            for (a, b) in local[1:]:
                if a - groups[-1][-1][1] > max(38, 0.09 * W):
                    groups.append([(a, b)])
                else:
                    groups[-1].append((a, b))
            if len(groups) < 2:
                clustered.append(s)
                continue
            cuts = [s[1]]
            for g0, g1 in zip(groups, groups[1:]):
                gap_lo = y1 + max(gg[1] for gg in g0)
                gap_hi = y1 + min(gg[0] for gg in g1)
                # the gap must be genuinely clear of any text box (not just of
                # THESE two groups' boxes) before we cut in it
                if (gap_hi - gap_lo >= 28
                        and not any(tb_a < gap_hi - 4 and tb_b > gap_lo + 4 for (tb_a, tb_b) in col_tb)):
                    cuts.append((gap_lo + gap_hi) // 2)
            cuts.append(s[3])
            cuts = sorted(set(cuts))
            if len(cuts) > 2:
                for c0, c1 in zip(cuts, cuts[1:]):
                    if c1 - c0 >= 28:
                        # trim each sub-beat to its own content so the fold
                        # pass below can recognise a caption-only slice
                        t = _trim_span(int(c0) - y1, int(c1) - y1)
                        clustered.append(t if t is not None else [s[0], c0, s[2], c1])
            else:
                clustered.append(s)
        segs = _fold_pass(clustered)   # fuse any caption-only slice into its panel

    # Second pass: a segment still MUCH taller than wide probably holds two
    # beats the uniform-gutter test was too strict to see. Cut it once at its
    # widest internal low-ink band — but only when that band is unambiguous
    # (real content well clear on both sides, no text across it).
    out: "List[list]" = []
    for s in segs:
        sh, sw = s[3] - s[1], s[2] - s[0]
        if sh <= 2.8 * sw or sh < 240:
            out.append(s)
            continue
        sub = gray[max(0, s[1]):s[3], max(0, s[0]):s[2]]
        ink = _ink_rows(sub)
        low = ~ink
        m0, m1 = int(0.12 * sub.shape[0]), int(0.88 * sub.shape[0])
        best, i = None, m0
        while i < m1:
            if low[i]:
                j = i
                while j < m1 and low[j]:
                    j += 1
                if best is None or (j - i) > (best[1] - best[0]):
                    best = (i, j)
                i = j
            else:
                i += 1
        # only accept the cut when real content sits on BOTH sides of the gap
        if (best and (best[1] - best[0]) >= 16
                and ink[:best[0]].sum() >= 12 and ink[best[1]:].sum() >= 12
                and not _text_straddles(s[1] + (best[0] + best[1]) // 2)):
            mid = s[1] + (best[0] + best[1]) // 2
            out.append([s[0], s[1], s[2], mid])
            out.append([s[0], mid, s[2], s[3]])
        else:
            out.append(s)
    return out


def _detect_page_panels(img_rgb) -> "List[tuple]":
    """Detect the comic panels on a page, in reading order, as (x1,y1,x2,y2).

    Primary: a YOLO26-nano panel+text detector fine-tuned on Manga109-s
    (see PANEL_YOLO_PATH). Each detected text box is attached to the panel it
    overlaps most (nearest if it overlaps none), and the emitted panel region
    is the union of the panel box with its text boxes — so a speech bubble
    that overflows the panel border into the gutter is still fully inside the
    frame. Panels are ordered by recursive XY-cut (top-to-bottom, and left
    bubble/panel first for side-by-side layouts). Every panel is kept as its
    own frame — no merging.

    Fallback (model file absent / inference fails): white-background flood
    fill + connected components.
    """
    W, H = img_rgb.size

    panels_y, texts_y = _yolo_detect_page(img_rgb)
    if panels_y is not None and (panels_y or texts_y):
        pg_area = float(W * H)
        # Enrich the text boxes with the RT-DETR comic text/bubble detector
        # (webtoon-trained, far better recall than the Manga109 YOLO's text
        # class). These drive every "never cut through a bubble" guard
        # downstream (_split_borderless_column, the contiguity merge's
        # _text_bridges, the seam stitch) and let the splitter cut BETWEEN
        # bubble clusters where there is no clean gutter.
        if os.environ.get("RECAP_TEXT_DET_SPLIT", "1").lower() not in ("0", "false", "no"):
            try:
                _tb = _detect_text_boxes(cv2.cvtColor(np.array(img_rgb), cv2.COLOR_RGB2GRAY))
                _existing = list(texts_y or [])
                for (tx1, ty1, tx2, ty2) in _tb:
                    if not any(min(tx2, e[2]) - max(tx1, e[0]) > 0 and
                               min(ty2, e[3]) - max(ty1, e[1]) > 0.5 * (ty2 - ty1)
                               for e in _existing):
                        _existing.append((int(tx1), int(ty1), int(tx2), int(ty2), 0.9))
                texts_y = _existing
            except Exception as _e:  # pragma: no cover
                log.debug("text-detector enrichment skipped (%s)", _e)
        # drop detector noise: a box too small to be a panel, or a thin
        # sliver that's really just a promoted text box (NOT a merge — these
        # are false positives, never real panels).
        panels_y = [
            b for b in panels_y
            if (b[2] - b[0]) * (b[3] - b[1]) > 0.025 * pg_area
            and (b[3] - b[1]) > 0.07 * H
            # a short box hugging the page top/bottom edge is a header /
            # footer / publisher watermark strip, not a story panel
            and not ((b[3] - b[1]) < 0.11 * H and (b[1] < 0.02 * H or b[3] > 0.98 * H))
        ]
        # drop panels almost entirely contained in a bigger one (nested inset
        # misfires) — keep the larger.
        panels_y.sort(key=lambda b: (b[2] - b[0]) * (b[3] - b[1]), reverse=True)
        kept = []
        for (x1, y1, x2, y2, sc) in panels_y:
            a = (x2 - x1) * (y2 - y1)
            nested = False
            for (kx1, ky1, kx2, ky2) in kept:
                ix = max(0.0, min(x2, kx2) - max(x1, kx1))
                iy = max(0.0, min(y2, ky2) - max(y1, ky1))
                if a > 0 and (ix * iy) / a > 0.80:
                    nested = True
                    break
            if not nested:
                # grow the tight border-hugging box a touch so an adjacent
                # bubble edge / border line isn't clipped
                gx, gy = 0.012 * W, 0.010 * H
                kept.append([max(0.0, x1 - gx), max(0.0, y1 - gy),
                             min(float(W), x2 + gx), min(float(H), y2 + gy)])

        _gray = cv2.cvtColor(np.array(img_rgb), cv2.COLOR_RGB2GRAY)
        yolo_boxes = [list(b) for b in kept]   # snapshot before gap-fill

        # 1) fill vertical spans the border-trained model left uncovered
        #    (full-bleed / borderless panels). Candidate boxes only — step 2
        #    decides new-panel vs continuation.
        row_ink = (_gray < 238).mean(axis=1)
        dark_row = (_gray < 205).mean(axis=1)
        covered = np.zeros(H, dtype=bool)
        for (x1, y1, x2, y2) in kept:
            covered[max(0, int(y1)):min(H, int(y2))] = True
        y = 0
        while y < H:
            if covered[y]:
                y += 1
                continue
            y0 = y
            while y < H and not covered[y]:
                y += 1
            nz = np.where(row_ink[y0:y] >= 0.05)[0]
            if not nz.size or (nz[-1] - nz[0]) < 0.05 * H:
                continue
            t0, t1 = y0 + int(nz[0]), y0 + int(nz[-1]) + 1
            if dark_row[t0:t1].mean() < 0.05:
                continue
            cols = (_gray[t0:t1] < 238).mean(axis=0)
            cnz = np.where(cols >= 0.02)[0]
            cx0, cx1 = (int(cnz[0]), int(cnz[-1]) + 1) if cnz.size else (0, W)
            kept.append([float(cx0), float(t0), float(cx1), float(t1)])

        # 2) CONTIGUITY MERGE — run on the still-TIGHT boxes (before bubbles
        #    are folded in and make panels overlap). Two vertically-adjacent
        #    boxes are the SAME panel unless a true gutter separates them: a
        #    horizontal band that reaches the page background (flood-filled
        #    from the edges — a bright spot INSIDE a panel does not count, and
        #    a speech bubble sitting in the gutter leaves most of the row as
        #    background so it still reads as a gutter). Full-bleed panels the
        #    model split, and gap-fill fragments, are glued back whole. No max
        #    height — a long panel is shown long, never cut through its art.
        white = (_gray >= 244).astype(np.uint8) * 255
        ff = white.copy()
        ffm = np.zeros((H + 2, W + 2), np.uint8)
        st = max(1, W // 24)
        for sx in range(0, W, st):
            for sy in (0, H - 1):
                if white[sy, sx]:
                    cv2.floodFill(ff, ffm, (sx, sy), 128)
        for sy in range(0, H, st):
            for sx in (0, W - 1):
                if white[sy, sx]:
                    cv2.floodFill(ff, ffm, (sx, sy), 128)
        bg_row = (ff == 128).mean(axis=1)
        # dark-mode webtoon pages (Solo Leveling's intro etc.) have NO white
        # to flood-fill — their gutters are flat black bands. Treat a row that
        # is almost entirely near-black with near-zero variance as background
        # too, so stacked "text on black" beats still separate.
        _dark_gutter = ((_gray <= 24).mean(axis=1) >= 0.95) & (_gray.std(axis=1) <= 14)
        bg_row = np.maximum(bg_row, _dark_gutter.astype(np.float32))

        def _text_bridges(a, b):
            # a speech bubble that straddles the boundary between two panels
            # ties them into one frame — splitting there would cut the bubble
            bl, bh = min(a[3], b[3]), max(a[1], b[1])
            mid = (a[3] + b[1]) / 2.0
            for (tx1, ty1, tx2, ty2, _s) in (texts_y or []):
                if ty1 < mid - 4 and ty2 > mid + 4:      # crosses the seam
                    if min(tx2, max(a[2], b[2])) - max(tx1, min(a[0], b[0])) > 0:
                        return True
            return False

        def _clean_gutter(a, b):
            # a CLEAN gutter = a full-width run of page background between the
            # two boxes with nothing (not even a bubble) crossing it. Only
            # then are the panels genuinely separate beats.
            c0 = int((a[1] + a[3]) / 2.0)
            c1 = int((b[1] + b[3]) / 2.0)
            lo, hi = min(c0, c1), max(c0, c1)
            if hi - lo < 4:
                return False
            return bool(float(bg_row[lo:hi].max()) >= 0.80)

        changed = True
        while changed and len(kept) > 1:
            changed = False
            kept.sort(key=lambda b: b[1])
            for i in range(len(kept) - 1):
                a, b = kept[i], kept[i + 1]
                x_ov = min(a[2], b[2]) - max(a[0], b[0])
                if x_ov < 0.25 * min(a[2] - a[0], b[2] - b[0]):
                    continue
                far = a[3] < b[1] - 0.22 * H
                merge = (not far and not _clean_gutter(a, b)) or _text_bridges(a, b)
                if merge:
                    kept[i] = [min(a[0], b[0]), min(a[1], b[1]),
                               max(a[2], b[2]), max(a[3], b[3])]
                    del kept[i + 1]
                    changed = True
                    break

        # 3) attach each text box to the panel it overlaps most (nearest if it
        #    overlaps none) — the emitted panel is the UNION of the panel box
        #    and its text boxes, so a bubble that overflows the border into the
        #    gutter is still wholly inside the frame.
        for (tx1, ty1, tx2, ty2, _s) in (texts_y or []):
            ta = max(1.0, (tx2 - tx1) * (ty2 - ty1))
            tcx = (tx1 + tx2) / 2.0
            best, best_ov = None, 0.0
            for i, (x1, y1, x2, y2) in enumerate(kept):
                ix = max(0.0, min(tx2, x2) - max(tx1, x1))
                iy = max(0.0, min(ty2, y2) - max(ty1, y1))
                ov = (ix * iy) / ta
                if ov > best_ov:
                    best, best_ov = i, ov
            if best is None or best_ov < 0.08:
                # No overlap: attach to the nearest panel DIRECTLY above or
                # below whose x-range contains the bubble's centre and which
                # has no other panel between it and the bubble. A bubble is
                # often placed well outside its panel's border.
                best, bd = None, 1e18
                for i, (x1, y1, x2, y2) in enumerate(kept):
                    if not (x1 - 0.03 * W <= tcx <= x2 + 0.03 * W):
                        continue
                    if ty1 >= y2:            # bubble below panel i
                        gap = ty1 - y2
                        blocked = any(k != i and kept[k][3] > y2 + 2 and kept[k][1] < ty1 - 2
                                      and kept[k][0] - 0.03 * W <= tcx <= kept[k][2] + 0.03 * W
                                      for k in range(len(kept)))
                    elif ty2 <= y1:          # bubble above panel i
                        gap = y1 - ty2
                        blocked = any(k != i and kept[k][1] < y1 - 2 and kept[k][3] > ty2 + 2
                                      and kept[k][0] - 0.03 * W <= tcx <= kept[k][2] + 0.03 * W
                                      for k in range(len(kept)))
                    else:
                        gap, blocked = 0.0, False
                    if not blocked and gap < bd:
                        best, bd = i, gap
                if best is None or bd > 0.22 * H:
                    continue
            b = kept[best]
            b[0], b[1] = min(b[0], tx1), min(b[1], ty1)
            b[2], b[3] = max(b[2], tx2), max(b[3], ty2)

        # 4) final tidy of thin bubble/text-only strips (NOT panels): a short,
        #    low-art-density box is an overflow bubble or a page-edge bleed /
        #    publisher watermark, never a story panel. Fold it into the
        #    vertically-nearest real panel; drop it only if there is none.
        def _yolo_backed(bx):
            a = max(1.0, (bx[2] - bx[0]) * (bx[3] - bx[1]))
            for (yx1, yy1, yx2, yy2) in yolo_boxes:
                ix = max(0.0, min(bx[2], yx2) - max(bx[0], yx1))
                iy = max(0.0, min(bx[3], yy2) - max(bx[1], yy1))
                if (ix * iy) / a > 0.55:
                    return True
            return False

        # A box is a real panel if the model saw it AND it's tall enough to
        # be a beat, OR (gap-fill origin) it's a genuine full-bleed panel the
        # model missed. A short full-width box — a floating dialogue bubble, a
        # gutter fragment, a bleed strip — is folded into its neighbour so
        # the bubble rides along with a panel and no beat is wasted on it.
        real, strips = [], []
        for b in kept:
            hfrac = (b[3] - b[1]) / H
            if hfrac < 0.15:
                strips.append(b)
            elif _yolo_backed(b) or hfrac >= 0.26:
                real.append(b)
            else:
                strips.append(b)
        if not real and kept:
            real = [max(kept, key=lambda b: (b[2] - b[0]) * (b[3] - b[1]))]
            strips = [b for b in kept if b is not real[0]]
        for s in strips:
            scy = (s[1] + s[3]) / 2.0
            host, hd = None, 1e18
            for r in real:
                if s[2] < r[0] - 0.05 * W or s[0] > r[2] + 0.05 * W:
                    continue
                d = 0.0 if r[1] <= scy <= r[3] else min(abs(scy - r[1]), abs(scy - r[3]))
                if d < hd:
                    host, hd = r, d
            if host is not None and hd < 0.28 * H:
                host[0], host[1] = min(host[0], s[0]), min(host[1], s[1])
                host[2], host[3] = max(host[2], s[2]), max(host[3], s[3])
            # else: dropped (edge bleed / watermark with no panel to belong to)
        kept = real

        # 5) BORDERLESS-WEBTOON SPLIT — the YOLO detector (trained on
        #    bordered print manga) collapses a tall webtoon column of
        #    full-width stacked panels into one giant box. Break any box
        #    much taller than it is wide at its internal clean gutter rows
        #    (a full-width band of page background between two panels).
        if kept:
            split_kept = []
            for b in kept:
                split_kept.extend(_split_borderless_column(b, _gray, texts_y))
            kept = split_kept

        if kept:
            ordered = _reading_order_boxes([tuple(b) for b in kept])
            return [(int(x1), int(y1), int(x2), int(y2)) for (x1, y1, x2, y2) in ordered]

    # ---- fallback: white-background flood fill ----
    arr = np.array(img_rgb)
    gray = cv2.cvtColor(arr, cv2.COLOR_RGB2GRAY)
    h, w = gray.shape
    page_area = float(h * w)

    white = (gray >= 244).astype(np.uint8)
    ff = (white * 255).astype(np.uint8)
    ff_mask = np.zeros((h + 2, w + 2), np.uint8)
    step = max(1, w // 24)
    seeds = [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]
    seeds += [(x, 0) for x in range(0, w, step)] + [(x, h - 1) for x in range(0, w, step)]
    seeds += [(0, y) for y in range(0, h, step)] + [(w - 1, y) for y in range(0, h, step)]
    for (sx, sy) in seeds:
        if 0 <= sx < w and 0 <= sy < h and ff[sy, sx] == 255:
            cv2.floodFill(ff, ff_mask, (sx, sy), 128)
    background = (ff == 128)

    panel_mask = np.where(background, 0, 255).astype(np.uint8)
    # solidify panels (bridge internal white bubbles / gaps to their panel)
    # without merging across a normal inter-panel gutter
    panel_mask = cv2.morphologyEx(
        panel_mask, cv2.MORPH_CLOSE,
        cv2.getStructuringElement(cv2.MORPH_RECT, (max(9, w // 90), max(9, h // 160))),
        iterations=1,
    )

    n, labels, stats, _ = cv2.connectedComponentsWithStats(panel_mask, connectivity=8)
    panels, bubbles = [], []
    for i in range(1, n):
        x, y, bw, bh, area = stats[i]
        if area < 24:
            continue
        box = (int(x), int(y), int(x + bw), int(y + bh))
        frac = area / page_area
        if frac >= PANEL_MIN_AREA_FRAC and bw > 0.18 * w and bh > 0.03 * h:
            panels.append(box)
        elif frac < PANEL_BUBBLE_AREA_FRAC:
            comp = (labels[y:y + bh, x:x + bw] == i)
            if comp.any() and gray[y:y + bh, x:x + bw][comp].mean() > 150:
                bubbles.append(box)

    if not panels:
        return [(0, 0, w, h)]

    # reattach overflow bubbles to the nearest panel (vertically)
    for (bx1, by1, bx2, by2) in bubbles:
        bcy = (by1 + by2) / 2.0
        best, best_d = None, 1e18
        for idx, (px1, py1, px2, py2) in enumerate(panels):
            if bx2 < px1 - w * 0.05 or bx1 > px2 + w * 0.05:
                continue
            d = (py1 - bcy) if bcy < py1 else (bcy - py2 if bcy > py2 else 0.0)
            d = abs(d) - (0.5 if bcy < py1 else 0.0)  # tie -> panel below
            if d < best_d:
                best, best_d = idx, d
        if best is not None and best_d < h * 0.08:
            px1, py1, px2, py2 = panels[best]
            panels[best] = (min(px1, bx1), min(py1, by1), max(px2, bx2), max(py2, by2))

    # merge panels that heavily overlap (a bubble bridged two detections)
    panels.sort(key=lambda b: (b[1], b[0]))
    merged: List[tuple] = []
    for b in panels:
        placed = False
        for j, m in enumerate(merged):
            ix = max(0, min(b[2], m[2]) - max(b[0], m[0]))
            iy = max(0, min(b[3], m[3]) - max(b[1], m[1]))
            inter = ix * iy
            amin = min((b[2] - b[0]) * (b[3] - b[1]), (m[2] - m[0]) * (m[3] - m[1]))
            if amin > 0 and inter / amin > 0.45:
                merged[j] = (min(b[0], m[0]), min(b[1], m[1]), max(b[2], m[2]), max(b[3], m[3]))
                placed = True
                break
        if not placed:
            merged.append(tuple(b))

    # Refine: a big bubble that spilled across a gutter can still bridge two
    # panels into one blob. Split any tall box at an internal "gutter row" —
    # a row that is mostly page background even though a bubble pokes through
    # part of its width.
    bg_row_frac = background.mean(axis=1)  # per-row fraction that is background
    refined: List[tuple] = []
    for (x1, y1, x2, y2) in merged:
        stack = [(y1, y2)]
        while stack:
            a, b = stack.pop()
            if (b - a) < h * 0.10 or (b - a) < (x2 - x1) * 1.15:
                refined.append((x1, a, x2, b))
                continue
            m0 = a + int((b - a) * 0.14)
            m1 = b - int((b - a) * 0.14)
            band = bg_row_frac[m0:m1]
            if band.size and band.max() > 0.62:
                cut = m0 + int(np.argmax(band))
                # widen to the middle of the contiguous gutter run
                lo = hi = cut
                while lo > m0 and bg_row_frac[lo] > 0.55:
                    lo -= 1
                while hi < m1 and bg_row_frac[hi] > 0.55:
                    hi += 1
                cut = (lo + hi) // 2
                stack.append((cut, b))
                stack.append((a, cut))
            else:
                refined.append((x1, a, x2, b))

    refined = [box for box in refined
               if (box[3] - box[1]) > h * 0.03 and
               not _is_blank_crop(gray[box[1]:box[3], box[0]:box[2]])]
    if not refined:
        refined = merged

    ordered = _reading_order_boxes([(x1, y1, x2, y2) for (x1, y1, x2, y2) in refined])
    return [(int(x1), int(y1), int(x2), int(y2)) for (x1, y1, x2, y2) in ordered]


def _reading_order_boxes(boxes: "List[tuple]") -> "List[tuple]":
    """Order (x1,y1,x2,y2) panel boxes into LTR reading order via a recursive
    XY-cut: split on the widest gap NO box crosses — horizontally first
    (rows), then vertically (side-by-side panels, left first). Handles
    staggered / diagonal layouts a plain (y,x) sort gets wrong."""
    if len(boxes) <= 1:
        return list(boxes)

    def _split(bs, depth=0):
        if len(bs) <= 1 or depth > 60:
            return sorted(bs, key=lambda b: (b[1], b[0]))
        # horizontal cut
        ys = sorted(bs, key=lambda b: b[1])
        cur = ys[0][3]
        gap, at = 0.0, None
        for b in ys[1:]:
            g = b[1] - cur
            if g > gap:
                gap, at = g, (cur + b[1]) / 2.0
            cur = max(cur, b[3])
        if at is not None and gap > 1.0:
            top = [b for b in bs if (b[1] + b[3]) / 2.0 < at]
            bot = [b for b in bs if (b[1] + b[3]) / 2.0 >= at]
            if top and bot:
                return _split(top, depth + 1) + _split(bot, depth + 1)
        # vertical cut
        xs = sorted(bs, key=lambda b: b[0])
        cur = xs[0][2]
        gap, at = 0.0, None
        for b in xs[1:]:
            g = b[0] - cur
            if g > gap:
                gap, at = g, (cur + b[0]) / 2.0
            cur = max(cur, b[2])
        if at is not None and gap > 1.0:
            left = [b for b in bs if (b[0] + b[2]) / 2.0 < at]
            right = [b for b in bs if (b[0] + b[2]) / 2.0 >= at]
            if left and right:
                return _split(left, depth + 1) + _split(right, depth + 1)
        return sorted(bs, key=lambda b: (b[1], b[0]))

    return _split(list(boxes))


def _pages_are_webtoon_chunks(page_paths: "List[Path]") -> bool:
    """True when the 'pages' are really one long vertical webtoon strip that
    the source host sliced into fixed-height chunks at ARBITRARY pixel rows
    (not panel/scene boundaries). Signature: uniform width, and a good share
    of page-to-page seams land in the middle of artwork (ink on both sides of
    the seam) instead of on a white gutter. Gates the seam-stitch in
    _frame_pages_reference_style — a properly paginated comic never needs it."""
    from PIL import Image
    if len(page_paths) < 3:
        return False
    widths, seam_hits, seams = [], 0, 0
    prev_bottom = None
    for p in page_paths:
        try:
            with Image.open(p) as im:
                g = np.asarray(im.convert("L"))
        except Exception:
            return False
        widths.append(g.shape[1])
        top_ink = float((g[:6] < 235).mean())
        if prev_bottom is not None:
            seams += 1
            # both sides of the seam carry ink => the cut is mid-artwork
            if prev_bottom > 0.05 and top_ink > 0.05:
                seam_hits += 1
        prev_bottom = float((g[-6:] < 235).mean())
    if max(widths) - min(widths) > 3:
        return False
    return seams > 0 and seam_hits / seams >= 0.34


def _seam_is_midart(bottom_gray: "np.ndarray", top_gray: "np.ndarray") -> bool:
    """A page boundary that cuts THROUGH artwork — ink right up to the bottom
    edge of page N and the top edge of page N+1, with no white gutter band.
    A panel straddling such a seam is physically split between the two files
    and per-page detection can only ever show half of it."""
    b = float((bottom_gray[-6:] < 235).mean())
    t = float((top_gray[:6] < 235).mean())
    # a clean gutter shows as a run of near-white rows at the edge
    b_white = int(np.argmax((bottom_gray[::-1] >= 243).mean(axis=1) < 0.97)) if bottom_gray.size else 99
    t_white = int(np.argmax((top_gray >= 243).mean(axis=1) < 0.97)) if top_gray.size else 99
    return b > 0.05 and t > 0.05 and b_white < 4 and t_white < 4


def _frame_pages_reference_style(cfg: "PipelineConfig", chapter: "Chapter",
                                 out_dir: Path) -> List["FrameEntry"]:
    """Reference-style framing: detect the real comic panels on every page
    (see _detect_page_panels) and emit ONE frame per panel, contain-fit over
    a blurred backdrop — matching the reference recap (one whole panel with
    its bubbles per on-screen beat, in reading order).

    Webtoon hosts slice a chapter into fixed-height chunk 'pages' at arbitrary
    pixel rows, so a panel often straddles a mid-artwork seam and is split
    across two files. When the bottom panel of page N and the top panel of
    page N+1 are both flush with that shared edge and the seam cuts through
    art, the two halves are stitched and emitted as ONE frame — never cut."""
    from PIL import Image

    # 1. detect panels on every page, note which touch the top/bottom edge
    pages = []   # (page_idx, name, rgb_ndarray, gray_ndarray, [ (box, clip_top, clip_bot) ])
    total = len(chapter.panel_paths)
    for page_idx, page_path in enumerate(chapter.panel_paths):
        try:
            with Image.open(page_path) as im:
                rgb = np.array(im.convert("RGB"))
        except Exception as exc:
            log.warning("[%s] skipping unreadable page %s: %s", chapter.tag, page_path.name, exc)
            continue
        h, w = rgb.shape[:2]
        gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
        dets = []
        for (x1, y1, x2, y2) in _detect_page_panels(Image.fromarray(rgb)):
            dets.append(((int(x1), int(y1), int(x2), int(y2)),
                         y1 <= 0.012 * h, y2 >= 0.988 * h))
        pages.append([page_idx, page_path.name, rgb, gray, dets])

    seam_stitch = (os.environ.get("RECAP_SEAM_STITCH", "1").lower() not in ("0", "false", "no")
                   and _pages_are_webtoon_chunks(chapter.panel_paths))

    entries: List[FrameEntry] = []
    counter = 0

    def _emit(crop_rgb, page_idx, page_name):
        nonlocal counter
        # drop dead margin the detector/stitch left on the crop edges
        g = cv2.cvtColor(crop_rgb, cv2.COLOR_RGB2GRAY)
        ri = np.where((g < 234).mean(axis=1) >= 0.02)[0]
        ci = np.where((g < 234).mean(axis=0) >= 0.02)[0]
        if ri.size >= 4 and ci.size >= 4:
            crop_rgb = crop_rgb[ri[0]:ri[-1] + 1, ci[0]:ci[-1] + 1]
        arr_gray = cv2.cvtColor(crop_rgb, cv2.COLOR_RGB2GRAY)
        if _is_blank_crop(arr_gray) or crop_rgb.shape[0] < 24 or crop_rgb.shape[1] < 24:
            return
        if (page_idx <= 1 or page_idx >= total - 2) and _looks_like_credits_panel(crop_rgb):
            log.info("[%s] skipped credits / notes panel on page %d", chapter.tag, page_idx + 1)
            return
        fp = out_dir / f"frame_{counter:05d}.jpg"
        _compose_canvas(Image.fromarray(crop_rgb)).save(fp, quality=92)
        # OCR reads this tight raw-pixel crop, NOT the composed canvas: the
        # canvas contain-fits a tall panel to a small centred strip and rings
        # it with a blurred copy of itself, both of which wreck recognition.
        # (deleted again by _ocr_frames_into_narration_json once OCR has run)
        ocr_path = ""
        if _OCR_FRAMES_ENABLED:
            ocr_fp = out_dir / f"frame_{counter:05d}_ocr.jpg"
            try:
                oc = crop_rgb
                if max(oc.shape[:2]) < 1500:   # upscale small crops for the detector
                    s = 1500 / max(oc.shape[:2])
                    oc = cv2.resize(oc, (int(oc.shape[1] * s), int(oc.shape[0] * s)),
                                    interpolation=cv2.INTER_CUBIC)
                Image.fromarray(oc).save(ocr_fp, quality=94)
                ocr_path = str(ocr_fp.resolve())
            except Exception:
                ocr_path = ""
        entries.append(FrameEntry(
            frame_id=f"{chapter.tag}_frame_{counter:05d}",
            filename=fp.name, path=str(fp.resolve()), ocr_path=ocr_path,
            source_page=page_name, source_index=page_idx, frame_kind="panel",
        ))
        counter += 1

    def _page_is_backmatter(gray_pg) -> bool:
        # a title / "To Be Continued" / staff-credits page: overwhelmingly
        # white with only a little scattered ink (a logo + a few text lines),
        # never a big filled art region
        white = float((gray_pg >= 236).mean())
        ink = float((gray_pg < 120).mean())
        if white < 0.86 or ink > 0.06:
            return False
        row_ink = (gray_pg < 120).mean(axis=1)
        return float((row_ink >= 0.02).mean()) <= 0.35

    consumed_first = set()   # (page_idx) whose first panel was already merged upward
    for pi in range(len(pages)):
        page_idx, name, rgb, gray, dets = pages[pi]
        h, w = gray.shape
        pad_x, pad_y = round(w * 0.006), round(h * 0.004)
        if (page_idx <= 1 or page_idx >= total - 2) and _page_is_backmatter(gray):
            log.info("[%s] skipped front/back-matter page %d", chapter.tag, page_idx + 1)
            continue
        for di, (box, clip_top, clip_bot) in enumerate(dets):
            x1, y1, x2, y2 = box
            if di == 0 and pi in consumed_first:
                continue
            # --- seam stitch: last panel of this page is edge-flush and the
            #     next page opens with an edge-flush panel across a mid-art seam
            if (seam_stitch and di == len(dets) - 1 and clip_bot and pi + 1 < len(pages)
                    and _seam_is_midart(gray, pages[pi + 1][3])):
                nrgb, ndets = pages[pi + 1][2], pages[pi + 1][4]
                nh = nrgb.shape[0]
                # merge ONLY a genuine split — one side is a spillover fragment
                # (< 55% of its page). Two full-height panels that merely touch
                # the shared edge are separate beats; leave them per-page so
                # each OCRs on its own tight crop.
                frag = ndets and ndets[0][1] and (
                    (y2 - y1) < 0.55 * h or (ndets[0][0][3] - ndets[0][0][1]) < 0.55 * nh)
                if frag:
                    (nx1, ny1, nx2, ny2), _, n_clip_bot = ndets[0]
                    # union across the stitched pair (2nd half offset by page h)
                    ux1, uy1 = min(x1, nx1), y1
                    ux2 = max(x2, nx2)
                    stitched = np.concatenate([rgb, nrgb], axis=0)
                    uy2 = h + ny2
                    cx1 = max(0, ux1 - pad_x); cy1 = max(0, uy1 - pad_y)
                    cx2 = min(w, ux2 + pad_x); cy2 = min(stitched.shape[0], uy2 + pad_y)
                    merged_crop = stitched[cy1:cy2, cx1:cx2]
                    # only accept the merge if the two halves are truly one
                    # image across the seam — a wide near-white band right at
                    # the join means they are separate panels; emit apart.
                    seam_rows = cv2.cvtColor(
                        merged_crop[max(0, h - cy1 - 12):max(1, h - cy1 + 12)],
                        cv2.COLOR_RGB2GRAY) if 12 < h - cy1 < merged_crop.shape[0] else None
                    if seam_rows is None or (seam_rows >= 238).mean() < 0.75:
                        _emit(merged_crop, page_idx, name)
                        consumed_first.add(pi + 1)
                        continue
            cx1 = max(0, x1 - pad_x); cy1 = max(0, y1 - pad_y)
            cx2 = min(w, x2 + pad_x); cy2 = min(h, y2 + pad_y)
            if cx2 - cx1 < w * 0.12 or cy2 - cy1 < h * 0.02:
                continue
            _emit(rgb[cy1:cy2, cx1:cx2], page_idx, name)

    log.info("[%s] reference-style framing: %d pages -> %d panel frames",
             chapter.tag, total, len(entries))
    return entries


def _ocr_frames_into_narration_json(cfg: "PipelineConfig", chapter: "Chapter",
                                    frame_entries: List["FrameEntry"]) -> bool:
    """OCR each composed frame with the local PaddleOCR/RapidOCR service and
    rewrite narration.json keyed by frame filename, so downstream narration is
    exactly this panel's transcribed words (word-for-word, per panel) instead
    of a whole page's text split proportionally. Returns True if it ran.

    OCR'ing the small framed panel is also markedly more accurate than OCR'ing
    a 4000px webtoon page. Skipped (keeping any existing narration.json) if the
    service is unreachable."""
    import json as _json
    import urllib.request

    if not _OCR_FRAMES_ENABLED:
        return False
    base = os.environ.get("OCR_SERVICE_URL", "http://localhost:3002")
    # prefer the tight raw crop (see _emit) — falls back to the composed canvas
    paths = [(e.ocr_path or e.path) for e in frame_entries]
    if not paths:
        return False
    try:
        req = urllib.request.Request(
            f"{base}/ocr/batch",
            data=_json.dumps({"images": paths}).encode(),
            headers={"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=max(120, len(paths) * 8)) as r:
            results = _json.load(r).get("results", [])
    except Exception as e:
        log.warning("[%s] per-frame OCR unavailable (%s) — keeping existing narration.json", chapter.tag, e)
        return False

    by_index = {int(x.get("index", i)): x for i, x in enumerate(results)}
    texts = []
    for i, e in enumerate(frame_entries):
        item = by_index.get(i, {})
        text = (item.get("text") or "").strip()
        status = item.get("status") or ("SUCCESS" if text else "NO_TEXT")
        texts.append([text, status])

    # A cut that ran through a speech bubble makes the SAME words tail frame N
    # and head frame N+1 ("…IS THAT GUY A" / "IS THAT GUY A STRONG HUNTER") —
    # spoken twice, and the second panel's audio starts on stale words. Drop
    # the duplicated run from the later frame's start.
    def _norm(w):
        return re.sub(r"[^a-z0-9]", "", w.lower())

    for i in range(len(texts) - 1):
        a, b = texts[i][0], texts[i + 1][0]
        if not a or not b:
            continue
        aw, bw = a.split(), b.split()
        best = 0
        for k in range(min(8, len(aw), len(bw)), 2, -1):
            if [_norm(w) for w in aw[-k:]] == [_norm(w) for w in bw[:k]]:
                best = k
                break
        if best:
            texts[i + 1][0] = " ".join(bw[best:]).strip()

    narration = []
    for i, e in enumerate(frame_entries):
        text, status = texts[i]
        if not text and status == "SUCCESS":
            status = "NO_TEXT"
        e.ocr_text, e.ocr_status = text, status
        narration.append({"image": e.filename, "text": text, "status": status})

    (chapter.folder / "narration.json").write_text(_json.dumps(narration, indent=2), encoding="utf-8")
    chapter.image_narrations = {n["image"]: n for n in narration}
    got = sum(1 for n in narration if n["text"])
    log.info("[%s] per-frame OCR: %d/%d frames transcribed (RapidOCR)", chapter.tag, got, len(narration))

    # the upscaled raw-crop OCR images have served their purpose — reclaim the space
    for e in frame_entries:
        if e.ocr_path and e.ocr_path != e.path:
            try:
                Path(e.ocr_path).unlink()
            except OSError:
                pass
            e.ocr_path = ""
    return True


def slice_chapter_panels(cfg: PipelineConfig, chapter: Chapter) -> List[tuple]:
    """
    Slice each source image into individual panel frames.

    Default (RECAP_FRAME_MODE=page): one frame per source page, tall pages
    split on gutter rows — reproduces the reference recap style (whole
    panels with bubbles, blur-fill, no text-strip blow-ups).

    RECAP_FRAME_MODE=panel: the older contour/gutter-aware per-panel slicer.

    Each frame is composited onto a 1920x1080 canvas with blurred background
    fill (contain-fit).

    Returns list of (frame_path, source_panel_index) tuples in order.
    Resumable: if the chapter's slice folder has a valid manifest, reuse it.
    """
    from PIL import Image, ImageFilter

    out_dir = cfg.temp_slices_dir / chapter.tag
    manifest_path = out_dir / "manifest.json"

    is_valid, manifest, reason = validate_canonical_manifest(manifest_path, chapter, job_id=cfg.job_id)
    if is_valid and manifest:
        log.info("[%s] canonical manifest verified (%d frames, %s) — skipping slicing", chapter.tag, len(manifest.frames), reason)
        return [(Path(f.path if Path(f.path).exists() else out_dir / f.filename), f.source_index) for f in manifest.frames]

    log.info("[%s] manifest invalid or missing (%s) — slicing source pages into canonical frames", chapter.tag, reason)
    out_dir.mkdir(parents=True, exist_ok=True)

    if os.environ.get("RECAP_FRAME_MODE", "page").lower() != "panel":
        frame_entries = _frame_pages_reference_style(cfg, chapter, out_dir)
        _ocr_frames_into_narration_json(cfg, chapter, frame_entries)
        manifest = CanonicalManifest(
            manifest_version=MANIFEST_VERSION,
            job_id=cfg.job_id,
            chapter_tag=chapter.tag,
            source_pages=[p.name for p in chapter.panel_paths],
            frames=frame_entries,
        )
        manifest.save(manifest_path)
        return [(Path(f.path), f.source_index) for f in manifest.frames]

    frame_entries: List[FrameEntry] = []
    frame_counter = 0
    total_blank_skipped = 0
    detect_method_counts: Counter = Counter()

    for panel_idx, panel_path in enumerate(chapter.panel_paths):
        try:
            with Image.open(panel_path) as img:
                img = img.convert("RGB")
                w, h = img.size
                gray = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2GRAY)

                panels, detect_method = _detect_panels_for_page(gray)
                log.debug("[%s] img %d: detected %d panel(s) via %s", chapter.tag, panel_idx, len(panels), detect_method)
                detect_method_counts[detect_method] += 1

                content_mask = _build_dilated_content_mask(gray)
                content_mask = _add_text_boxes_to_mask(content_mask, gray)

                merged_panel_boxes = []
                for (px, py, pw, ph) in panels:
                    if ph < 50 or pw < 50:
                        continue

                    safe_top = _snap_cut_to_safe_row(content_mask, py)
                    safe_bot = _snap_cut_to_safe_row(content_mask, py + ph)
                    if safe_bot - safe_top >= 50:
                        py, ph = safe_top, safe_bot - safe_top

                    px, py, pw, ph = _apply_dynamic_padding((px, py, pw, ph), content_mask, (h, w), padding_px=30)

                    crop_candidate = img.crop((px, py, px + pw, py + ph))
                    crop_candidate_gray = cv2.cvtColor(np.array(crop_candidate), cv2.COLOR_RGB2GRAY)

                    if _is_blank_crop(crop_candidate_gray) or _is_lines_only_crop(crop_candidate_gray):
                        total_blank_skipped += 1
                        continue

                    if _is_featureless_vfx(crop_candidate_gray):
                        if merged_panel_boxes:
                            prev_x, prev_y, prev_w, prev_h = merged_panel_boxes[-1]
                            new_y1 = min(prev_y, py)
                            new_y2 = max(prev_y + prev_h, py + ph)
                            new_x1 = min(prev_x, px)
                            new_x2 = max(prev_x + prev_w, px + pw)
                            merged_panel_boxes[-1] = (new_x1, new_y1, new_x2 - new_x1, new_y2 - new_y1)
                        else:
                            merged_panel_boxes.append((px, py, pw, ph))
                    else:
                        prev_box = merged_panel_boxes[-1] if merged_panel_boxes else None
                        prev_crop_gray = None
                        if prev_box is not None:
                            prev_crop_gray = cv2.cvtColor(
                                np.array(img.crop((prev_box[0], prev_box[1], prev_box[0] + prev_box[2], prev_box[1] + prev_box[3]))),
                                cv2.COLOR_RGB2GRAY,
                            )
                        if prev_box is not None and _is_featureless_vfx(prev_crop_gray):
                            prev_x, prev_y, prev_w, prev_h = merged_panel_boxes.pop()
                            new_y1 = min(prev_y, py)
                            new_y2 = max(prev_y + prev_h, py + ph)
                            new_x1 = min(prev_x, px)
                            new_x2 = max(prev_x + prev_w, px + pw)
                            merged_panel_boxes.append((new_x1, new_y1, new_x2 - new_x1, new_y2 - new_y1))
                        elif prev_box is not None and _crops_are_near_duplicate(prev_crop_gray, crop_candidate_gray):
                            prev_x, prev_y, prev_w, prev_h = merged_panel_boxes.pop()
                            new_y1 = min(prev_y, py)
                            new_y2 = max(prev_y + prev_h, py + ph)
                            new_x1 = min(prev_x, px)
                            new_x2 = max(prev_x + prev_w, px + pw)
                            merged_panel_boxes.append((new_x1, new_y1, new_x2 - new_x1, new_y2 - new_y1))
                        else:
                            merged_panel_boxes.append((px, py, pw, ph))

                # Fold detached caption/SFX strips into their panels and enforce
                # the per-page frame budget, so one source page can't explode
                # into a dozen frames (which the audio-timing floor then pads
                # into many seconds of near-silent, near-empty video).
                pre_consolidation = len(merged_panel_boxes)
                merged_panel_boxes = _consolidate_panel_boxes(
                    merged_panel_boxes, w, h, MAX_FRAMES_PER_PANEL
                )
                if len(merged_panel_boxes) != pre_consolidation:
                    log.debug("[%s] img %d: consolidated %d panel box(es) -> %d",
                              chapter.tag, panel_idx, pre_consolidation, len(merged_panel_boxes))

                for (px, py, pw, ph) in merged_panel_boxes:
                    crop = img.crop((px, py, px + pw, py + ph))
                    crop_arr = np.array(crop)
                    crop_gray = cv2.cvtColor(crop_arr, cv2.COLOR_RGB2GRAY)

                    # Clean stray boundary-edge fragments bleeding in from an
                    # adjacent panel (a solid near-black or near-white row
                    # within the first/last ~15px of the crop) BEFORE the
                    # blank-crop check and canvas composition. This is a
                    # narrower, distinct case from _compose_canvas's own
                    # whole-crop white-margin trim below: it catches a thin
                    # bleed-through strip (including dark border lines,
                    # which a white-only threshold can't catch), not a large
                    # accumulated gutter margin. Was implemented and tested
                    # (tests/test_image_slicing.py) but its only caller
                    # (_trim_white_borders) was dead code removed in an
                    # earlier cleanup pass, orphaning this function entirely
                    # -- rewiring it here instead of leaving it dead.
                    crop_arr, crop_gray = _clean_panel_boundary_edges(crop_arr, crop_gray)
                    crop = Image.fromarray(crop_arr)

                    if _is_blank_crop(crop_gray):
                        total_blank_skipped += 1
                        log.debug("[%s] img %d: skipping blank panel", chapter.tag, panel_idx)
                        continue

                    cw, ch = crop.size
                    # Threshold raised from 1.8 -- mathematically confirmed
                    # this was firing on ordinary tall panels, not just the
                    # "system/quest UI card" content it was meant for.
                    # _generate_ui_card_scroll_frames's own internal early
                    # return (`if window_h >= ch: return one frame`) can
                    # NEVER trigger for any crop that reaches it, because
                    # window_h is always crop_width * 0.5625 (a 16:9 ratio)
                    # and the caller only invokes it when ch/cw already
                    # exceeds this threshold -- so with the old 1.8 gate,
                    # every merged caption/panel crop with a remotely tall
                    # aspect ratio (extremely common in vertical webtoon
                    # scroll format, e.g. a standing character shot or a
                    # caption merged with the panel above/below it) was
                    # unconditionally sliced into 4 overlapping panning
                    # windows down its height instead of shown as one
                    # correctly-composited frame.
                    #
                    # Even at 3.0, real jobs kept showing the same bug for
                    # crops that legitimately exceed that ratio -- so
                    # _should_scroll_fragment additionally gates this on
                    # the text detector's own judgment: if a single
                    # detected text box already covers most of this
                    # crop's area, it IS essentially one caption/dialogue
                    # block, not a multi-element scrollable UI list,
                    # regardless of raw aspect ratio. See that function's
                    # own docstring for the full reasoning.
                    if _should_scroll_fragment(cw, ch, crop):
                        from PIL import Image as PILImage
                        # Tall UI/quest cards get sliced into several panning
                        # sub-frames for display. They all show fragments of
                        # ONE piece of text, so tag them with a shared
                        # scroll_group — OCR'ing (and narrating) each window
                        # separately would chop sentences at arbitrary pixel
                        # boundaries and read them as N disjoint, garbled
                        # clips instead of one continuous line.
                        group_id = f"{chapter.tag}_grp{frame_counter:05d}"
                        scroll_frames = _generate_ui_card_scroll_frames(crop, num_scroll_frames=4)
                        for s_frame in scroll_frames:
                            fp = out_dir / f"frame_{frame_counter:05d}.jpg"
                            s_frame.save(fp, quality=92)
                            frame_id = f"{chapter.tag}_frame_{frame_counter:05d}"
                            frame_entries.append(
                                FrameEntry(
                                    frame_id=frame_id,
                                    filename=fp.name,
                                    path=str(fp.resolve()),
                                    source_page=panel_path.name,
                                    source_index=panel_idx,
                                    frame_kind="scroll_frame",
                                    scroll_group=group_id,
                                )
                            )
                            frame_counter += 1
                    else:
                        from PIL import Image as PILImage
                        frame = _compose_canvas(PILImage.fromarray(crop_arr))
                        fp = out_dir / f"frame_{frame_counter:05d}.jpg"
                        frame.save(fp, quality=92)
                        frame_id = f"{chapter.tag}_frame_{frame_counter:05d}"
                        frame_entries.append(
                            FrameEntry(
                                frame_id=frame_id,
                                filename=fp.name,
                                path=str(fp.resolve()),
                                source_page=panel_path.name,
                                source_index=panel_idx,
                                frame_kind="panel",
                            )
                        )
                        frame_counter += 1
        except Exception as exc:
            log.warning("[%s] Skipping unreadable/corrupt image %s: %s", chapter.tag, panel_path.name, exc)
            continue

    if total_blank_skipped > 0:
        log.info("[%s] skipped %d blank panel(s) during slicing", chapter.tag, total_blank_skipped)

    manifest = CanonicalManifest(
        manifest_version=MANIFEST_VERSION,
        job_id=cfg.job_id,
        chapter_tag=chapter.tag,
        source_pages=[p.name for p in chapter.panel_paths],
        frames=frame_entries,
    )
    manifest.save(manifest_path)
    # Accurate summary of which detector(s) actually ran across this
    # chapter's pages -- previously hardcoded to always claim
    # "(contour-based detection)" regardless of what really happened,
    # which was actively misleading (e.g. showed that label even when
    # every page went through the gutter-aware or YOLO path instead).
    method_summary = ", ".join(f"{count}x {name}" for name, count in detect_method_counts.most_common())
    log.info("[%s] sliced %d source pages into %d canonical frames (detection: %s)",
             chapter.tag, len(chapter.panel_paths), len(frame_entries), method_summary or "none")
    return [(Path(f.path), f.source_index) for f in manifest.frames]


SCROLL_FRAGMENT_ASPECT_RATIO = 3.0  # raised from 1.8 -- see _should_scroll_fragment
SCROLL_FRAGMENT_ONE_CAPTION_AREA_RATIO = 0.6  # a single text box covering more than
# this fraction of the crop's area means the crop is essentially one
# caption, not a multi-element UI card -- see _should_scroll_fragment.


def _should_scroll_fragment(cw: int, ch: int, crop) -> bool:
    """Decide whether a tall crop should be panned through as several
    overlapping video frames (see _generate_ui_card_scroll_frames) or
    shown as a single, correctly-composited frame.

    Two-part gate: the crop must first be tall enough
    (height/width > SCROLL_FRAGMENT_ASPECT_RATIO) to even be considered,
    then the text detector (see _detect_text_boxes,
    ogkalu/comic-text-and-bubble-detector) gets the final say -- if a
    single detected text box already covers most of the crop's area, the
    crop IS essentially one caption/dialogue block, not a multi-element
    scrollable UI list, regardless of raw aspect ratio.

    This matters beyond just visual correctness: researched, established
    practice for image+narration video sync (the pattern used across
    MoviePy/ffmpeg slideshow-narration tooling generally) is "one image,
    one audio clip, no internal subdivision" -- fragmenting a single
    caption into multiple video frames is what forces the downstream
    code to split one TTS segment's audio across multiple frames at all,
    which is the structural root of audio/panel sync issues for this
    class of content, not just a cosmetic slicing problem.

    Falls back to the plain aspect-ratio gate alone if the detector is
    unavailable (returns no boxes), same "degrade, don't crash" pattern
    as everywhere else it's used -- a real production job kept showing
    the fragmentation bug even after raising the aspect-ratio threshold
    alone, from crops that legitimately exceed it (e.g. a caption merged
    with panel content above/below it during boundary detection).
    """
    if (ch / max(1, cw)) <= SCROLL_FRAGMENT_ASPECT_RATIO:
        return False
    crop_gray = cv2.cvtColor(np.array(crop), cv2.COLOR_RGB2GRAY)
    crop_area = max(1, cw * ch)
    for (tx1, ty1, tx2, ty2) in _detect_text_boxes(crop_gray):
        box_area = max(0, tx2 - tx1) * max(0, ty2 - ty1)
        if box_area / crop_area > SCROLL_FRAGMENT_ONE_CAPTION_AREA_RATIO:
            return False  # one big caption -- don't fragment it
    return True


def _generate_ui_card_scroll_frames(crop, num_scroll_frames: int = 4) -> List["Image.Image"]:
    """Generate a sequence of linear vertical scroll sub-frames for tall rectangular system/quest UI cards.
    Maintains full resolution width and generates vertical panning steps down the UI card rather than squishing or cropping.
    """
    from PIL import Image

    cw, ch = crop.size
    # Visible window height in source space to match 16:9 ratio at full width cw
    window_h = int(cw * CANVAS_H / CANVAS_W)
    if window_h >= ch:
        return [_compose_canvas(crop)]

    scroll_frames = []
    max_top = ch - window_h
    step = max_top / max(1, num_scroll_frames - 1)

    for i in range(num_scroll_frames):
        top = int(round(i * step))
        bot = min(ch, top + window_h)
        sub_crop = crop.crop((0, top, cw, bot))

        # Scale sub_crop to 1920x1080 canvas preserving aspect ratio
        canvas = Image.new("RGB", (CANVAS_W, CANVAS_H), (0, 0, 0))
        fg = sub_crop.resize((CANVAS_W, CANVAS_H), Image.LANCZOS)
        canvas.paste(fg, (0, 0))
        scroll_frames.append(canvas)

    return scroll_frames


def _compose_canvas(crop):
    """Composite `crop` onto a 1920x1080 canvas with a blurred, cover-fit
    copy of the same panel as the background (instead of plain black bars).
    Uses CONTAIN-FIT for the foreground: scales the panel to fit ENTIRELY
    within the canvas, showing the complete panel — including character
    head and feet — with the blurred backdrop filling the rest of the
    frame. This ensures NO content is ever cut off while avoiding the
    dead-black letterbox bars that plain contain-fit leaves on portrait
    panels.
    Also trims white borders from the source panel first."""
    from PIL import Image, ImageFilter
    import numpy as np

    # Trim white borders from the crop (manhwa pages have white margins)
    crop_arr = np.array(crop)
    gray = np.mean(crop_arr, axis=2)
    h, w = gray.shape

    # A row/column counts as real content only if a meaningful FRACTION of
    # its pixels are non-white, not merely one. Using np.any() here let a
    # single stray pixel -- e.g. JPEG compression-ringing noise in an
    # otherwise blank webtoon margin, which real exported pages always
    # have -- flag the entire row as "content" and defeat the trim, so a
    # large near-white gutter margin survived uncut into the final frame
    # (the visible white gap in the bad output). 1% is a deliberately
    # small majority-style threshold: real content (text, line art) lights
    # up far more than 1% of a row/column's pixels, while margin noise
    # from compression artifacts does not.
    NON_WHITE_ROW_FRACTION = 0.01
    non_white_rows = (gray < 240).mean(axis=1) > NON_WHITE_ROW_FRACTION
    non_white_cols = (gray < 240).mean(axis=0) > NON_WHITE_ROW_FRACTION
    rows = np.where(non_white_rows)[0]
    cols = np.where(non_white_cols)[0]

    if len(rows) > 10 and len(cols) > 10:
        top = max(0, rows[0] - 5)
        bot = min(h, rows[-1] + 5)
        left = max(0, cols[0] - 5)
        right = min(w, cols[-1] + 5)
        if (bot - top) > 20 and (right - left) > 20:
            crop = crop.crop((left, top, right, bot))

    cw, ch = crop.size

    # Blurred, cover-fit background: scales the SAME panel up until it fully
    # covers the canvas (cropping the overflow, never the foreground), then
    # blurs + darkens it. Fills the whole frame — no black bars — while the
    # sharp foreground panel below still shows every pixel of the source.
    bg_scale = max(CANVAS_W / cw, CANVAS_H / ch)
    bw, bh = max(1, int(cw * bg_scale)), max(1, int(ch * bg_scale))
    bg = crop.resize((bw, bh), Image.LANCZOS)
    bx = (bw - CANVAS_W) // 2
    by = (bh - CANVAS_H) // 2
    bg = bg.crop((bx, by, bx + CANVAS_W, by + CANVAS_H))
    bg = bg.filter(ImageFilter.GaussianBlur(40))
    # Adaptive tone: a flat p*0.66 turns an already-dark panel's backdrop into
    # a pure-black void (a very common look in the old output). Instead pull
    # the blurred backdrop's mean toward a fixed dark tone (~46) — bright
    # backdrops get darkened, near-black ones get lifted off zero — then a
    # gentle radial vignette so the sharp panel still reads as the subject.
    _b = np.asarray(bg).astype(np.float32)
    _m = float(_b.mean())
    _b *= float(np.clip(48.0 / max(_m, 1.0), 0.40, 4.5))
    _b = _b * 0.9 + 16.0
    yy, xx = np.mgrid[0:CANVAS_H, 0:CANVAS_W].astype(np.float32)
    _r = (((xx - CANVAS_W / 2) / (CANVAS_W / 2)) ** 2 + ((yy - CANVAS_H / 2) / (CANVAS_H / 2)) ** 2)
    _b *= (1.0 - 0.22 * np.clip(_r, 0, 1))[..., None]
    canvas = Image.fromarray(np.clip(_b, 0, 255).astype(np.uint8)).convert("RGB")

    # Contain-fit: scale to fit ENTIRELY within canvas, centered — the whole
    # panel (bubbles, character head and feet) always visible, over the
    # blurred backdrop. This is how the reference recap frames each view.
    # NOTE: NO cover-crop for tall panels — cropping a tall webtoon panel to
    # fill more width was clipping speech bubbles ("text sliced through").
    # A tall panel letterboxes on its own blurred backdrop; that is the
    # reference look and it never loses a word.
    fg_scale = min(CANVAS_W / cw, CANVAS_H / ch) * PANEL_FIT_MARGIN

    fw, fh = max(1, int(cw * fg_scale)), max(1, int(ch * fg_scale))
    fg = crop.resize((fw, fh), Image.LANCZOS)
    fx = (CANVAS_W - fw) // 2
    fy = (CANVAS_H - fh) // 2
    # Crop any residual overflow so the pasted foreground never exceeds canvas.
    if fw > CANVAS_W or fh > CANVAS_H:
        left = max(0, (fw - CANVAS_W) // 2)
        top = max(0, (fh - CANVAS_H) // 2)
        fg = fg.crop((left, top, left + min(fw, CANVAS_W), top + min(fh, CANVAS_H)))
        fw, fh = fg.size
        fx = (CANVAS_W - fw) // 2
        fy = (CANVAS_H - fh) // 2
    canvas.paste(fg, (fx, fy))

    return canvas


