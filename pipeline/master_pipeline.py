# 2. UNIFORM CANVAS SLICING ENGINE (gutter-aware + inpainting)
# ---------------------------------------------------------------------------

# Inpainting toggle — disabled by default to avoid OOM on large webtoon strips.
# The VLM narration focuses on describing the scene rather than reading dialogue,
# which achieves a similar effect without the memory cost of CV2 inpainting.
INPAINT_BUBBLES = False
INPAINT_MIN_BUBBLE_AREA = 800   # px² — ignore tiny text fragments
INPAINT_MAX_BUBBLE_AREA = 150000  # px² — ignore huge regions (whole panels)


# ---------------------------------------------------------------------------
# 2a. BUBBLE-SAFE GUTTER DETECTION
#
# Guarantee: a horizontal cut is only ever placed on a row that is 100%
# free of "content" (art, line-work, text glyphs, bubble borders) across
# the ENTIRE width of the page, measured on a lightly-dilated content mask.
# Dilation bridges anti-aliasing gaps in bubble outlines and the small gaps
# between individual glyphs/letters so a bubble or text line is always seen
# as one solid blob — it is structurally impossible for a cut chosen this
# way to slice through the middle of a bubble, a line of text, or artwork,
# because any row that touches such a blob anywhere along its width is
# disqualified as a cut candidate.
# ---------------------------------------------------------------------------

def _build_dilated_content_mask(img_gray, dark_thresh: int = 200) -> "np.ndarray":
    """Binary mask (255 = content) of everything that isn't near-white
    background, lightly dilated/closed so speech-bubble outlines, thin text
    strokes, and screentone dots merge into solid blobs instead of leaving
    tiny gaps that a naive row-scan could mistake for a safe gutter."""
    _, mask = cv2.threshold(img_gray, dark_thresh, 255, cv2.THRESH_BINARY_INV)
    # Bridge small horizontal gaps (letter spacing, bubble outline breaks)
    # without merging across a real gutter — kernel stays modest vertically.
    close_kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 5))
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, close_kernel, iterations=1)
    mask = cv2.dilate(mask, np.ones((3, 3), np.uint8), iterations=1)
    return mask


def _label_content_components(mask) -> List[tuple]:
    """Connected components of a content mask → list of (y1, y2, x1, x2, area)
    bounding boxes, used to sanity-check that no cut straddles a real blob
    (bubble, text line, character, etc.)."""
    n, _labels, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
    comps = []
    for i in range(1, n):
        x, y, w, h, area = stats[i]
        if area < 6:
            continue
        comps.append((int(y), int(y + h), int(x), int(x + w), int(area)))
    return comps


def _detect_panels_gutter_aware(img_gray) -> List[tuple]:
    """Bubble-safe panel detector for webtoon-style tall strips.

    Unlike percentage/variance-based gutter heuristics, a row is only ever
    classified as a valid cut if it is checked across N independent
    width-slices of the DILATED content mask and is completely empty in
    every one of them. This is a strictly stronger guarantee than "mostly
    white" — a bubble tail, a caption box, or a stray character sitting in
    an otherwise-white gap will keep that row (and the whole band around it,
    once merged with neighbours) out of consideration.

    Returns list of (x1, y1, x2, y2) tuples, full page width, sorted by y.
    """
    h, w = img_gray.shape
    if h < 10 or w < 10:
        return [(0, 0, w, h)]

    mask = _build_dilated_content_mask(img_gray)
    components = _label_content_components(mask)

    n_slices = 8
    slice_w = max(1, w // n_slices)
    row_has_any_content = np.any(mask > 0, axis=1)
    is_gutter_row = np.zeros(h, dtype=bool)
    for y in range(h):
        if not row_has_any_content[y]:
            is_gutter_row[y] = True
            continue
        clear = True
        for s in range(n_slices):
            x0 = s * slice_w
            x1 = w if s == n_slices - 1 else (s + 1) * slice_w
            if np.any(mask[y, x0:x1] > 0):
                clear = False
                break
        is_gutter_row[y] = clear

    # Smooth to reject single-row noise (e.g. one stray dead pixel briefly
    # flipping a row to "gutter" inside dense artwork), but never smooth
    # enough to let a real gutter get swallowed.
    is_gutter_row = cv2.blur(
        is_gutter_row.astype(np.float32).reshape(-1, 1), (5, 1)
    ).flatten() > 0.6

    min_band_h = max(12, h // 350)
    bands: List[tuple] = []
    run_start = None
    for i, g in enumerate(is_gutter_row):
        if g and run_start is None:
            run_start = i
        elif not g and run_start is not None:
            if i - run_start >= min_band_h:
                bands.append((run_start, i))
            run_start = None
    if run_start is not None and h - run_start >= min_band_h:
        bands.append((run_start, h))

    if not bands:
        return [(0, 0, w, h)]

    # Cut at the safest row within each band — the row farthest from any
    # component that comes close to (but, by construction, never crosses)
    # the band's edges — then double-checked against every component so a
    # cut can never land inside a bbox that happens to graze the band.
    cut_points: List[int] = []
    for (s, e) in bands:
        cut = (s + e) // 2
        for (cy1, cy2, _cx1, _cx2, area) in components:
            if area < 40 or cy2 <= s or cy1 >= e:
                continue
            top_gap, bot_gap = cy1 - s, e - cy2
            if top_gap > bot_gap and top_gap > 4:
                cut = min(cut, s + max(2, top_gap // 2))
            elif bot_gap > 4:
                cut = max(cut, e - max(2, bot_gap // 2))
        cut_points.append(cut)

    boundaries = [0] + cut_points + [h]
    min_panel_h = max(30, h // 100)
    raw_panels = []
    for i in range(len(boundaries) - 1):
        top, bot = boundaries[i], boundaries[i + 1]
        if bot - top >= min_panel_h:
            raw_panels.append((0, top, w, bot))

    content_panels = [p for p in raw_panels if np.any(mask[p[1]:p[3], :] > 0)]
    if not content_panels:
        return [(0, 0, w, h)]

    # Merge runs of small adjacent fragments (e.g. a caption strip that got
    # isolated by a thin gutter) so they read as one coherent frame.
    merged = [list(content_panels[0])]
    for (x1, y1, x2, y2) in content_panels[1:]:
        prev = merged[-1]
        if (y2 - y1) < 150 and (prev[3] - prev[1]) < 200:
            prev[2], prev[3] = x2, y2
        else:
            merged.append([x1, y1, x2, y2])

    return [(p[0], p[1], p[2], p[3]) for p in merged if (p[3] - p[1]) >= min_panel_h]


def _check_bubble_union(mask, cut_y: int, img_shape: tuple) -> int:
    """Bubble Union Check:
    If a horizontal cut line intersects a content blob (speech bubble, text glyph, ascender, descender, or sound effect tail),
    move the cut line below (or above) the entire speech bubble component to keep dialogue intact in a single frame.
    """
    h, w = img_shape[:2]
    cut_y = max(0, min(h - 1, cut_y))
    if not np.any(mask[cut_y, :] > 0):
        return cut_y

    # Label connected components directly on binary mask
    n_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(mask, connectivity=8)
    intersected_bottoms = []
    intersected_tops = []
    for i in range(1, n_labels):
        cy1 = stats[i, cv2.CC_STAT_TOP]
        ch = stats[i, cv2.CC_STAT_HEIGHT]
        cy2 = cy1 + ch
        area = stats[i, cv2.CC_STAT_AREA]
        if area < 6:
            continue
        if cy1 <= cut_y < cy2:
            intersected_bottoms.append(cy2)
            intersected_tops.append(cy1)

    if intersected_bottoms:
        # Move cut line below the max bottom of intersected speech bubbles
        target_y = max(intersected_bottoms) + 5
        if target_y < h:
            return target_y
        # If moving below exceeds image height, move above the min top
        target_y = max(0, min(intersected_tops) - 5)
        return target_y

    return cut_y


def _apply_dynamic_padding(panel_box: tuple, mask, img_shape: tuple, padding_px: int = 30) -> tuple:
    """Minimum Vertical Padding & Speech Bubble Protection:
    When a panel slice contains text contours or speech bubbles near its top or bottom borders,
    automatically expand the slice bounding box by 30 pixels vertically (clamped to image height).
    """
    x1, y1, w, h = panel_box
    img_h, img_w = img_shape[:2]
    y2 = y1 + h

    # Check top boundary region (y1 to y1 + padding_px)
    top_region = mask[max(0, y1):min(img_h, y1 + padding_px), max(0, x1):min(img_w, x1 + w)]
    # Check bottom boundary region (y2 - padding_px to y2)
    bot_region = mask[max(0, y2 - padding_px):min(img_h, y2), max(0, x1):min(img_w, x1 + w)]

    new_y1 = y1
    new_y2 = y2

    if np.any(top_region > 0):
        new_y1 = max(0, y1 - padding_px)
    if np.any(bot_region > 0):
        new_y2 = min(img_h, y2 + padding_px)

    return (x1, new_y1, w, new_y2 - new_y1)


def _snap_cut_to_safe_row(mask, y: int, window: int = 24) -> int:
    """Nudge a candidate horizontal edge to the nearest row that is
    completely clear of content across the full width, within +/- window
    px. Applied as a final safety net to panel boxes from ANY detector
    (YOLO, contour, gutter-aware) so an edge can never clip a bubble tail
    or a line of text even if the upstream detector placed it a few pixels
    off. Returns the original y if no safe row is found nearby (better to
    keep the original box than snap arbitrarily far away)."""
    h = mask.shape[0]
    y = max(0, min(h - 1, y))

    # Perform Bubble Union check if cut intersects speech bubble
    y = _check_bubble_union(mask, y, (h, mask.shape[1]))

    if not np.any(mask[y, :] > 0):
        return y
    for d in range(1, window + 1):
        for cand in (y + d, y - d):  # Prefer moving down below text
            if 0 <= cand < h and not np.any(mask[cand, :] > 0):
                return cand
    return y


def _detect_panels_for_page(img_gray) -> List[tuple]:
    """Top-level panel detector for one source page/strip image.

    Webtoon/manhwa raws are dominated by tall, single-column strips — for
    those, the bubble-safe gutter-aware detector gives the strongest
    guarantee (cuts can never cross a content pixel). For roughly
    page-shaped images (traditional multi-panel grid layouts), fall back to
    the existing YOLO/contour auto-detector, which understands multi-column
    layouts that a pure horizontal-gutter scan can't.

    Returns list of (x, y, w, h) tuples, matching _detect_panels_auto's
    contract.
    """
    h, w = img_gray.shape
    if h / max(w, 1) > 1.3:
        strip_panels = _detect_panels_gutter_aware(img_gray)
        if strip_panels:
            return [(x1, y1, x2 - x1, y2 - y1) for (x1, y1, x2, y2) in strip_panels]
    return _detect_panels_auto(img_gray)


def _detect_panel_gutters(img_gray, y_offset: int = 0) -> List[int]:
    """Detect horizontal gutter lines (panel separators) in a webtoon strip.

    Uses a multi-signal approach:
      1. Row variance (flat/uniform rows = gutters)
      2. Row brightness (white gaps have high mean, black borders have low mean)
      3. Full-width check — a real gutter must be uniform across the ENTIRE
         row width, not just part of it. This prevents false cuts through
         panels that have a white region on one side (e.g. sky/speech bubbles).

    A row is classified as gutter if it satisfies EITHER:
      - Low variance (uniform color) AND (very bright OR very dark)
      - Very low variance (nearly uniform regardless of color)
    AND the row is uniformly gutter-like across ≥80% of its width (so we
    don't cut through a panel that happens to have a flat region).

    Returns sorted list of ABSOLUTE y-coordinates for cuts.
    """

    h, w = img_gray.shape
    if h < 10:
        return []

    row_means = np.mean(img_gray, axis=1).astype(np.float32)
    row_stds = np.std(img_gray, axis=1).astype(np.float32)

    # Smooth both signals to avoid single-row noise.
    kernel = max(3, min(7, h // 300))
    row_means = cv2.blur(row_means.reshape(-1, 1), (kernel, 1)).flatten()
    row_stds = cv2.blur(row_stds.reshape(-1, 1), (kernel, 1)).flatten()

    # Classify each row as gutter or not.
    is_bright_gutter = (row_stds < 12) & (row_means > 200)
    is_dark_gutter = (row_stds < 12) & (row_means < 60)
    is_flat_gutter = row_stds < 3
    is_gutter = is_bright_gutter | is_dark_gutter | is_flat_gutter

    # FULL-WIDTH VALIDATION: a real gutter must be uniform across the whole row.
    n_slices = 5
    slice_w = max(1, w // n_slices)
    for i in range(h):
        if not is_gutter[i]:
            continue
        gutter_slices = 0
        for s in range(n_slices):
            x0 = s * slice_w
            x1 = min(w, (s + 1) * slice_w)
            sl = img_gray[i, x0:x1]
            sl_mean = float(np.mean(sl))
            sl_std = float(np.std(sl))
            if (sl_std < 12 and (sl_mean > 200 or sl_mean < 60)) or sl_std < 3:
                gutter_slices += 1
        if gutter_slices < 4:
            is_gutter[i] = False

    # Extract gutter runs (consecutive gutter rows).
    cuts: List[int] = []
    run_start = None
    min_gutter_height = max(4, h // 400)
    min_panel_height = max(40, h // 80)

    for i, g in enumerate(is_gutter):
        if g and run_start is None:
            run_start = i
        elif not g and run_start is not None:
            if i - run_start >= min_gutter_height:
                cut_pos = y_offset + (run_start + i) // 2
                if not cuts or (cut_pos - cuts[-1]) >= min_panel_height:
                    cuts.append(cut_pos)
            run_start = None
    if run_start is not None and h - run_start >= min_gutter_height:
        cut_pos = y_offset + (run_start + h) // 2
        if not cuts or (cut_pos - cuts[-1]) >= min_panel_height:
            cuts.append(cut_pos)

    return cuts


def _detect_vertical_gutters(img_gray) -> List[int]:
    """Detect vertical gutter lines (column separators) in a manga row.

    Scans columns for uniform vertical bands — blank white gaps or thin
    black borders between side-by-side panels. Returns sorted list of
    absolute x-coordinates where the row should be cut vertically.
    """

    h, w = img_gray.shape
    if w < 10:
        return []

    col_stds = np.std(img_gray, axis=0).astype(np.float32)
    # Smooth to avoid single-column noise spikes.
    kernel = max(1, min(5, w // 500))
    if kernel > 1:
        col_stds = cv2.blur(col_stds.reshape(1, -1), (1, kernel)).flatten()

    # Adaptive threshold for vertical gutters.
    gutter_threshold = float(min(14.0, max(6.0, np.percentile(col_stds, 20))))
    is_gutter = col_stds < gutter_threshold

    cuts: List[int] = []
    run_start = None
    min_gutter_width = max(2, w // 800)
    for i, g in enumerate(is_gutter):
        if g and run_start is None:
            run_start = i
        elif not g and run_start is not None:
            if i - run_start >= min_gutter_width:
                cuts.append((run_start + i) // 2)
            run_start = None
    if run_start is not None and w - run_start >= min_gutter_width:
        cuts.append((run_start + w) // 2)
    return cuts


def _subsplit_tall_panel(img_gray, x1, y1, x2, y2) -> List[tuple]:
    """Sub-split a very tall panel (aspect > 2.5) into smaller frames using
    row-scan gutter detection within the sub-region.

    Returns list of (x1, y1, x2, y2) sub-regions. If no internal gutters are
    found, returns the original region unchanged.
    """
    sub_gray = img_gray[y1:y2, x1:x2]
    sh, sw = sub_gray.shape
    if sh < 100:
        return [(x1, y1, x2, y2)]

    row_means = np.mean(sub_gray, axis=1).astype(np.float32)
    row_stds = np.std(sub_gray, axis=1).astype(np.float32)
    k = max(3, min(7, sh // 300))
    row_means = cv2.blur(row_means.reshape(-1, 1), (k, 1)).flatten()
    row_stds = cv2.blur(row_stds.reshape(-1, 1), (k, 1)).flatten()

    is_g = ((row_stds < 12) & ((row_means > 200) | (row_means < 60))) | (row_stds < 3)
    # Full-width check
    sl_w = max(1, sw // 5)
    for i in range(sh):
        if not is_g[i]:
            continue
        gs = 0
        for s in range(5):
            sl = sub_gray[i, s * sl_w:min(sw, (s + 1) * sl_w)]
            if (np.std(sl) < 12 and (np.mean(sl) > 200 or np.mean(sl) < 60)) or np.std(sl) < 3:
                gs += 1
        if gs < 4:
            is_g[i] = False

    cuts = []
    rs = None
    min_gh = max(4, sh // 400)
    min_ph = max(50, sh // 8)
    for i, g in enumerate(is_g):
        if g and rs is None:
            rs = i
        elif not g and rs is not None:
            if i - rs >= min_gh:
                cp = (rs + i) // 2
                if not cuts or (cp - cuts[-1]) >= min_ph:
                    cuts.append(cp)
            rs = None
    if rs is not None and sh - rs >= min_gh:
        cp = (rs + sh) // 2
        if not cuts or (cp - cuts[-1]) >= min_ph:
            cuts.append(cp)

    if not cuts:
        return [(x1, y1, x2, y2)]

    boundaries = [0] + cuts + [sh]
    subs = []
    for j in range(len(boundaries) - 1):
        sub_h = boundaries[j + 1] - boundaries[j]
        if sub_h >= 50:
            subs.append((x1, y1 + boundaries[j], x2, y1 + boundaries[j + 1]))
    return subs if subs else [(x1, y1, x2, y2)]


def _inpaint_bubbles(img) -> "object":
    """Detect and inpaint speech bubbles/text in a panel image.

    Uses OpenCV to find text regions (light blobs with borders), then fills
    them with surrounding pixels via OpenCV's inpainting (Telea algorithm —
    a free, fast content-aware fill that reconstructs background art).
    """
    from PIL import Image

    arr = np.array(img)  # RGB
    gray = cv2.cvtColor(arr, cv2.COLOR_RGB2GRAY)

    # Detect text/bubbles: white-ish blobs (speech bubbles are usually white).
    # Threshold to find bright regions.
    _, bright = cv2.threshold(gray, 240, 255, cv2.THRESH_BINARY)
    # Morphological close to merge nearby text into blob masks.
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (15, 15))
    bright = cv2.morphologyEx(bright, cv2.MORPH_CLOSE, kernel)
    # Find contours that look like text/bubbles (area in range).
    contours, _ = cv2.findContours(bright, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    mask = np.zeros(gray.shape, dtype=np.uint8)
    for c in contours:
        area = cv2.contourArea(c)
        if INPAINT_MIN_BUBBLE_AREA < area < INPAINT_MAX_BUBBLE_AREA:
            cv2.drawContours(mask, [c], -1, 255, -1)
            # Dilate the mask slightly so inpainting covers edges cleanly.
    if mask.any():
        mask = cv2.dilate(mask, kernel, iterations=2)
        # Inpaint using the Telea algorithm (fast, free, content-aware).
        arr = cv2.inpaint(arr, mask, 5, cv2.INPAINT_TELEA)
    return Image.fromarray(arr)


def _is_blank_crop(arr_gray) -> bool:
    """Check if a cropped panel image is blank (no real content).

    A panel is considered blank if it's nearly uniform — e.g. pure white,
    pure black, or a flat color with no artwork. We use pixel standard
    deviation: a real manga/manhwa panel has lots of detail (lines, shading,
    text) so its std is high (>15). Blank panels have std < 8.

    Also catches near-white panels (mean > 245 AND std < 15) which are the
    most common blank type in webtoons (white gutters caught as "panels").
    """
    if arr_gray is None or arr_gray.size == 0:
        return True
    mean_val = float(np.mean(arr_gray))
    std_val = float(np.std(arr_gray))
    # Very low std = uniform/blank regardless of color.
    if std_val < 8.0:
        return True
    # Near-white with low detail = blank white panel.
    if mean_val > 245.0 and std_val < 15.0:
        return True
    return False


def _is_lines_only_crop(arr_gray) -> bool:
    """Check if a cropped panel contains ONLY lines/borders (no text, no art).

    These are panels that have some content (so they pass the blank check) but
    the content is just thin lines, borders, dividers, or frame outlines — no
    actual text or artwork. These should be removed from the video because they
    add no narrative value.

    Detection method: analyze connected components of dark pixels.
    - TEXT = many small, non-elongated components (characters)
    - ART = large components with high pixel area (artwork, shading)
    - LINES = medium components that are very elongated (high aspect ratio)

    A panel is "lines only" if it has NO text-like components AND NO art-like
    components, but DOES have line-like components.

    Returns True if the panel should be REMOVED (lines/borders only).
    """
    if arr_gray is None or arr_gray.size == 0:
        return False  # let _is_blank_crop handle empty

    h, w = arr_gray.shape
    if h < 5 or w < 5:
        return False

    # Threshold to find dark pixels (content)
    _, binary = cv2.threshold(arr_gray, 180, 255, cv2.THRESH_BINARY_INV)
    n_labels, labels, stats, _ = cv2.connectedComponentsWithStats(binary, connectivity=8)

    if n_labels <= 1:
        return False  # no content at all (blank check handles this)

    text_components = 0
    art_components = 0
    line_components = 0

    for i in range(1, n_labels):
        area = int(stats[i, cv2.CC_STAT_AREA])
        cw = int(stats[i, cv2.CC_STAT_WIDTH])
        ch = int(stats[i, cv2.CC_STAT_HEIGHT])
        min_dim = max(1, min(cw, ch))
        max_dim = max(cw, ch)
        aspect = max_dim / min_dim

        # Skip tiny noise (< 5px)
        if area < 5:
            continue

        # TEXT-like: small area, low aspect ratio (roughly square = characters)
        # Characters are typically 5-500px and aspect < 3.5
        if area < 600 and aspect < 3.5:
            text_components += 1
        # ART-like: large area (big artwork blobs, shading regions)
        elif area > 1500:
            art_components += 1
        # LINE-like: very elongated (aspect > 4) — borders, dividers, frame outlines
        elif aspect > 4.0:
            line_components += 1
        else:
            # Medium, non-elongated — could be text or small art, count as text
            if area < 600:
                text_components += 1

    # The panel is "lines only" if it has line-like components but
    # NO text and NO art. We require at least 1 line component to classify
    # as lines-only (otherwise it's just a sparse panel).
    has_text = text_components >= 8  # need at least 8 char-like blobs for real text
    has_art = art_components >= 1
    has_lines = line_components >= 1

    return has_lines and not has_text and not has_art


def _calc_image_entropy(arr_gray) -> float:
    """Calculate Shannon entropy of a grayscale panel slice (0 to 8)."""
    if arr_gray is None or arr_gray.size == 0:
        return 0.0
    hist, _ = np.histogram(arr_gray, bins=256, range=(0, 256))
    prob = hist / float(arr_gray.size)
    prob = prob[prob > 0]
    return float(-np.sum(prob * np.log2(prob)))


def _is_featureless_vfx(arr_gray) -> bool:
    """Check if a panel slice candidate is a featureless background, visual effect,
    gradient, speed line, ice shard, or light aura region lacking character faces,
    dialogue bubbles, or structural story focal points.

    Detection criteria:
    - Structural contour density (Canny edges)
    - Presence of text glyphs (small bounded edge components) or distinct story focal points
    """
    if arr_gray is None or arr_gray.size == 0:
        return True

    h, w = arr_gray.shape
    if h < 20 or w < 20:
        return True

    edges = cv2.Canny(arr_gray, 50, 150)
    edge_density = float(np.count_nonzero(edges)) / float(arr_gray.size)

    # Analyze connected components of Canny edge contours
    n_labels, labels, stats, _ = cv2.connectedComponentsWithStats(edges, connectivity=8)

    text_components = 0
    substantive_contours = 0

    for i in range(1, n_labels):
        area = int(stats[i, cv2.CC_STAT_AREA])
        cw = int(stats[i, cv2.CC_STAT_WIDTH])
        ch = int(stats[i, cv2.CC_STAT_HEIGHT])

        if area < 10:
            continue
        # Text characters in edge domain are small bounded glyph components (e.g. 5 <= cw, ch <= 60)
        if 5 <= cw <= 60 and 5 <= ch <= 60 and area >= 15:
            text_components += 1
        elif area > 800 and (cw > 80 or ch > 80):
            substantive_contours += 1

    # Featureless visual effects (ice shards, speed lines, light aura) have < 4 text glyphs and low substantive contours
    if text_components < 4 and substantive_contours == 0:
        return True
    if text_components < 4 and edge_density < 0.02:
        return True

    return False


def _should_skip_panel(arr_gray) -> bool:
    """Determine if a panel should be skipped (not included in the video).

    A panel is skipped if:
    1. It's blank (all-white, uniform, no content) — _is_blank_crop
    2. It contains ONLY lines/borders (no text, no art) — _is_lines_only_crop
    3. It is a featureless visual effect frame (speed lines, ice shards, light aura) — _is_featureless_vfx
    """
    if _is_blank_crop(arr_gray):
        return True
    if _is_lines_only_crop(arr_gray):
        return True
    if _is_featureless_vfx(arr_gray):
        return True
    return False


def _clean_panel_boundary_edges(arr_rgb, arr_gray, max_scan_px: int = 15):
    """Clean panel boundary edge fragments (dual-panel overlap bug fix).

    Enhances horizontal gutter detection by looking for continuous black/white pixel rows
    or distinct edge color transitions between adjacent panels. Trims stray top/bottom edge fragments
    from adjacent panels (such as fire panel top bleed) before finalizing slice output.
    """
    h, w = arr_gray.shape
    if h < 30 or w < 30:
        return arr_rgb, arr_gray

    # Scan top rows for stray edge fragments from previous panel
    top_trim = 0
    for y in range(min(max_scan_px, h // 4)):
        row = arr_gray[y, :]
        mean_v = float(np.mean(row))
        # Continuous black border row (<10) or white gutter row (>245)
        if mean_v > 245 or mean_v < 10:
            top_trim = y + 1
        else:
            break

    # Scan bottom rows for stray edge fragments from next panel
    bot_trim = h
    for y in range(h - 1, max(h - max_scan_px - 1, h - h // 4), -1):
        row = arr_gray[y, :]
        mean_v = float(np.mean(row))
        if mean_v > 245 or mean_v < 10:
            bot_trim = y
        else:
            break

    if top_trim > 0 or bot_trim < h:
        if (bot_trim - top_trim) >= 20:
            arr_rgb = arr_rgb[top_trim:bot_trim, :]
            arr_gray = arr_gray[top_trim:bot_trim, :]

    return arr_rgb, arr_gray


def _trim_white_borders(arr_gray, arr_rgb, margin: int = 2):
    """Trim white/uniform borders from a cropped panel.

    Scans from each edge inward and crops away rows/columns that are
    nearly white (mean > 240, std < 10). Returns (trimmed_rgb, trimmed_gray)
    or the original arrays if no trimming was needed. Always keeps at least
    `margin` pixels of border so we don't clip artwork.
    Also applies edge fragment cleaning (_clean_panel_boundary_edges).
    """
    arr_rgb, arr_gray = _clean_panel_boundary_edges(arr_rgb, arr_gray)

    h, w = arr_gray.shape
    if h < 20 or w < 20:
        return arr_rgb, arr_gray

    def is_white_row(y):
        row = arr_gray[y, :]
        return float(np.mean(row)) > 240 and float(np.std(row)) < 10

    def is_white_col(x):
        col = arr_gray[:, x]
        return float(np.mean(col)) > 240 and float(np.std(col)) < 10

    # Trim top
    top = 0
    while top < h - margin - 1 and is_white_row(top):
        top += 1
    top = max(0, top - margin)
    # Trim bottom
    bot = h - 1
    while bot > top + margin and is_white_row(bot):
        bot -= 1
    bot = min(h - 1, bot + margin)
    # Trim left
    left = 0
    while left < w - margin - 1 and is_white_col(left):
        left += 1
    left = max(0, left - margin)
    # Trim right
    right = w - 1
    while right > left + margin and is_white_col(right):
        right -= 1
    right = min(w - 1, right + margin)

    # Only trim if we're removing a meaningful amount (≥5% from any side).
    min_trim = max(4, h // 20)
    min_trim_w = max(4, w // 20)
    if top < min_trim and (h - 1 - bot) < min_trim and left < min_trim_w and (w - 1 - right) < min_trim_w:
        return arr_rgb, arr_gray

    trimmed_rgb = arr_rgb[top:bot + 1, left:right + 1]
    trimmed_gray = arr_gray[top:bot + 1, left:right + 1]
    if trimmed_rgb.shape[0] < 20 or trimmed_rgb.shape[1] < 20:
        return arr_rgb, arr_gray
    return trimmed_rgb, trimmed_gray


def _detect_panels_yolo(img_gray) -> List[tuple]:
    """Detect panels using YOLOv5/v8 comic panel detection model.

    Uses a pretrained YOLO model (mosesb/best-comic-panel-detection) that
    was trained specifically on comic/manga panels. This is more accurate
    than CV-based detection for pages with complex layouts, splash panels,
    and non-rectangular panel shapes.

    Falls back gracefully if the model or torch is unavailable.

    Returns list of (x, y, w, h) tuples sorted by y position.
    """
    try:
        from ultralytics import YOLO
    except ImportError:
        return []

    model_path = str(Path(__file__).parent / "models" / "comic-panel-yolo" / "best.pt")
    if not Path(model_path).exists():
        return []

    try:
        model = YOLO(model_path)
        # Convert grayscale to 3-channel for YOLO (it expects BGR)
        if img_gray.ndim == 2:
            img_bgr = cv2.cvtColor(img_gray, cv2.COLOR_GRAY2BGR)
        else:
            img_bgr = img_gray

        results = model.predict(img_bgr, conf=0.25, iou=0.45, verbose=False)
        if not results or results[0].boxes is None:
            return []

        h, w = img_gray.shape[:2]
        page_area = w * h
        panels = []
        for box in results[0].boxes:
            x1, y1, x2, y2 = box.xyxy[0].cpu().numpy()
            x1, y1, x2, y2 = int(x1), int(y1), int(x2), int(y2)
            bw, bh = x2 - x1, y2 - y1
            area = bw * bh
            # Filter: min 2% area, max 98% area (looser than CV)
            if area < 0.02 * page_area or area > 0.98 * page_area:
                continue
            # Expand by 10px margin to avoid tight crops that clip artwork
            margin = 10
            x1 = max(0, x1 - margin)
            y1 = max(0, y1 - margin)
            bw = min(w - x1, bw + 2 * margin)
            bh = min(h - y1, bh + 2 * margin)
            panels.append((x1, y1, bw, bh))

        # NMS to remove near-duplicates (keep insets)
        panels = _suppress_nested(panels, iou_thresh=0.65)
        panels = _order_panels_reading_order(panels)
        return panels
    except Exception as e:
        log.warning("YOLO panel detection failed: %s", e)
        return []


def _order_panels_reading_order(panels: List[tuple]) -> List[tuple]:
    """Order panel boxes (x, y, w, h) into natural top-to-bottom,
    left-to-right reading order for LTR-read manhwa/comic grid pages.

    A naive sort purely by top-y coordinate (p[1], p[0]) breaks whenever
    panels in the same visual row are staggered or have different heights
    — extremely common in dynamic comic layouts with diagonal panel cuts
    or a tall splash panel next to two stacked smaller ones. That naive
    sort can place a panel from the NEXT row before the second panel of
    the CURRENT row, silently narrating story events out of order. This
    clusters panels into rows by vertical overlap first, then sorts each
    row left-to-right, before ordering rows top-to-bottom.
    """
    if not panels:
        return panels

    remaining = sorted(panels, key=lambda p: p[1])
    rows: List[List[tuple]] = []
    for p in remaining:
        x, y, w, h = p
        y2 = y + h
        placed = False
        for row in rows:
            ry1 = min(rp[1] for rp in row)
            ry2 = max(rp[1] + rp[3] for rp in row)
            overlap = min(y2, ry2) - max(y, ry1)
            min_h = min(h, ry2 - ry1)
            if min_h > 0 and overlap / min_h > 0.4:
                row.append(p)
                placed = True
                break
        if not placed:
            rows.append([p])

    rows.sort(key=lambda row: min(rp[1] for rp in row))
    ordered: List[tuple] = []
    for row in rows:
        row.sort(key=lambda rp: rp[0])
        ordered.extend(row)
    return ordered


def _detect_panels_auto(img_gray) -> List[tuple]:
    """Auto-mode panel detection: run YOLO first, fall back to CV if weak.

    This is the cbxy "auto" engine approach:
    1. Run YOLO (most accurate for complex layouts)
    2. If YOLO returns 0 panels or 1 panel covering ≥70% of page (weak),
       run CV detection and use whichever produced more panels.
    3. If CV also looks weak, use the whole page as one panel.

    Returns list of (x, y, w, h) tuples sorted by y position.
    """
    h, w = img_gray.shape
    page_area = w * h

    # Try YOLO first
    yolo_panels = _detect_panels_yolo(img_gray)

    # Check if YOLO looks weak
    yolo_weak = (
        len(yolo_panels) == 0
        or (len(yolo_panels) == 1 and yolo_panels[0][2] * yolo_panels[0][3] >= 0.70 * page_area)
    )

    if not yolo_weak and len(yolo_panels) >= 2:
        # YOLO found multiple panels — use it
        log.debug("YOLO detected %d panels (strong)", len(yolo_panels))
        return yolo_panels

    # YOLO was weak — try CV
    cv_panels = _detect_panels_contour(img_gray)

    # Use whichever found more panels
    if len(cv_panels) > len(yolo_panels):
        log.debug("CV fallback: %d panels (YOLO found %d)", len(cv_panels), len(yolo_panels))
        return cv_panels

    # Both weak — use whole page
    if not yolo_panels and not cv_panels:
        return [(0, 0, w, h)]

    return yolo_panels if yolo_panels else cv_panels


def _suppress_nested(panels: List[tuple], iou_thresh: float = 0.55) -> List[tuple]:
    """Drop boxes mostly contained in a larger panel (from cbxy).

    Greedy by descending area: a candidate is dropped if >=55% of its
    own area is contained in an already-kept larger panel. This removes
    speech bubbles and small insets that survived the area filter.
    """
    if not panels:
        return panels

    kept: List[tuple] = []
    by_area = sorted(panels, key=lambda p: p[2] * p[3], reverse=True)
    for candidate in by_area:
        cx, cy, cw, ch = candidate
        cx2, cy2 = cx + cw, cy + ch
        is_nested = False
        for kept_panel in kept:
            kx, ky, kw, kh = kept_panel
            kx2, ky2 = kx + kw, ky + kh
            # Compute containment: fraction of candidate inside kept_panel
            ix1 = max(cx, kx)
            iy1 = max(cy, ky)
            ix2 = min(cx2, kx2)
            iy2 = min(cy2, ky2)
            if ix2 <= ix1 or iy2 <= iy1:
                continue
            inter = (ix2 - ix1) * (iy2 - iy1)
            candidate_area = max(cw * ch, 1)
            if inter / candidate_area >= iou_thresh:
                is_nested = True
                break
        if not is_nested:
            kept.append(candidate)
    return kept


def _detect_panels_contour(img_gray) -> List[tuple]:
    """Detect panels using improved contour-based detection (CV fallback).

    This is the CV fallback used when YOLO is unavailable or returns weak
    results. Combines techniques from comic-manga-narrator + cbxy.
    """
    h, w = img_gray.shape
    page_area = w * h

    # Step 1: threshold (gutters are white ≥200, panels are dark <200)
    _, binary = cv2.threshold(img_gray, 200, 255, cv2.THRESH_BINARY)

    # Step 2: morphological close to bridge text/art gaps within panels
    # Invert so panels are white blobs on black background
    panels_mask = cv2.bitwise_not(binary)
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (5, 5))
    panels_mask = cv2.morphologyEx(panels_mask, cv2.MORPH_CLOSE, kernel, iterations=2)

    # Step 3: flood-fill from 4 corners to mark page background (cbxy technique)
    # This prevents the entire page from being detected as one giant panel
    gutters = binary.copy()
    ff_mask = np.zeros((h + 2, w + 2), np.uint8)
    for seed in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
        if gutters[seed[1], seed[0]] > 0:
            cv2.floodFill(gutters, ff_mask, seed, 128)

    # Step 4: subtract background
    background = gutters == 128
    content = panels_mask.copy()
    content[background] = 0

    # Step 5: find external contours
    contours, _ = cv2.findContours(content, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    # Step 6-7: filter by area, dimensions, and aspect ratio
    panels = []
    for cnt in contours:
        area = cv2.contourArea(cnt)
        if area < 0.03 * page_area or area > 0.85 * page_area:
            continue
        x, y, bw, bh = cv2.boundingRect(cnt)
        # Reject thin slivers (cbxy thresholds)
        if bw < 0.08 * w or bh < 0.05 * h:
            continue
        ar = bw / max(bh, 1)
        if ar > 8.0 or ar < 0.15:
            continue
        # Small margin expansion
        margin = 5
        x = max(0, x - margin)
        y = max(0, y - margin)
        bw = min(w - x, bw + 2 * margin)
        bh = min(h - y, bh + 2 * margin)
        panels.append((x, y, bw, bh))

    # Step 8: nested suppression (cbxy technique)
    panels = _suppress_nested(panels, iou_thresh=0.55)

    # Step 9: weak detection fallback (cbxy heuristic)
    # If 0 panels or 1 panel covering ≥70% of page, use whole page
    if not panels:
        return [(0, 0, w, h)]
    if len(panels) == 1 and panels[0][2] * panels[0][3] >= 0.70 * page_area:
        return [(0, 0, w, h)]

    # Sort into natural reading order: rows by vertical overlap (handles
    # staggered/diagonal layouts), then left-to-right within each row.
    panels = _order_panels_reading_order(panels)
    return panels


def slice_chapter_panels(cfg: PipelineConfig, chapter: Chapter) -> List[tuple]:
    """
    Slice each source image into individual panel frames using contour-based,
    gutter-aware panel detection.

    Each detected panel is composited onto a 1920x1080 canvas with
    blurred background fill (contain-fit).

    Returns list of (frame_path, source_panel_index) tuples in order.
    Resumable: if the chapter's slice folder has a valid manifest, reuse it.
    """
    from PIL import Image, ImageFilter

    out_dir = cfg.temp_slices_dir / chapter.tag
    manifest_path = out_dir / "manifest.json"

    is_valid, manifest, reason = validate_canonical_manifest(manifest_path, chapter, job_id=cfg.job_id)
    if is_valid and manifest:
        log.info("[%s] canonical manifest verified (%d frames, %s) — skipping slicing", chapter.tag, len(manifest.frames), reason)
        return [(Path(f.path if Path(f.path).exists() else out_dir / f.filename), f.source_index) for f in manifest.frames]

    log.info("[%s] manifest invalid or missing (%s) — slicing source pages into canonical frames", chapter.tag, reason)
    out_dir.mkdir(parents=True, exist_ok=True)
    frame_entries: List[FrameEntry] = []
    frame_counter = 0
    total_blank_skipped = 0

    for panel_idx, panel_path in enumerate(chapter.panel_paths):
        try:
            with Image.open(panel_path) as img:
                img = img.convert("RGB")
                w, h = img.size
                gray = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2GRAY)

                panels = _detect_panels_for_page(gray)
                log.debug("[%s] img %d: detected %d panel(s)", chapter.tag, panel_idx, len(panels))

                content_mask = _build_dilated_content_mask(gray)

                merged_panel_boxes = []
                for (px, py, pw, ph) in panels:
                    if ph < 50 or pw < 50:
                        continue

                    safe_top = _snap_cut_to_safe_row(content_mask, py)
                    safe_bot = _snap_cut_to_safe_row(content_mask, py + ph)
                    if safe_bot - safe_top >= 50:
                        py, ph = safe_top, safe_bot - safe_top

                    px, py, pw, ph = _apply_dynamic_padding((px, py, pw, ph), content_mask, (h, w), padding_px=30)

                    crop_candidate = img.crop((px, py, px + pw, py + ph))
                    crop_candidate_gray = cv2.cvtColor(np.array(crop_candidate), cv2.COLOR_RGB2GRAY)

                    if _is_blank_crop(crop_candidate_gray) or _is_lines_only_crop(crop_candidate_gray):
                        total_blank_skipped += 1
                        continue

                    if _is_featureless_vfx(crop_candidate_gray):
                        if merged_panel_boxes:
                            prev_x, prev_y, prev_w, prev_h = merged_panel_boxes[-1]
                            new_y1 = min(prev_y, py)
                            new_y2 = max(prev_y + prev_h, py + ph)
                            new_x1 = min(prev_x, px)
                            new_x2 = max(prev_x + prev_w, px + pw)
                            merged_panel_boxes[-1] = (new_x1, new_y1, new_x2 - new_x1, new_y2 - new_y1)
                        else:
                            merged_panel_boxes.append((px, py, pw, ph))
                    else:
                        if merged_panel_boxes and _is_featureless_vfx(
                            cv2.cvtColor(np.array(img.crop((merged_panel_boxes[-1][0], merged_panel_boxes[-1][1], merged_panel_boxes[-1][0] + merged_panel_boxes[-1][2], merged_panel_boxes[-1][1] + merged_panel_boxes[-1][3]))), cv2.COLOR_RGB2GRAY)
                        ):
                            prev_x, prev_y, prev_w, prev_h = merged_panel_boxes.pop()
                            new_y1 = min(prev_y, py)
                            new_y2 = max(prev_y + prev_h, py + ph)
                            new_x1 = min(prev_x, px)
                            new_x2 = max(prev_x + prev_w, px + pw)
                            merged_panel_boxes.append((new_x1, new_y1, new_x2 - new_x1, new_y2 - new_y1))
                        else:
                            merged_panel_boxes.append((px, py, pw, ph))

                for (px, py, pw, ph) in merged_panel_boxes:
                    crop = img.crop((px, py, px + pw, py + ph))
                    crop_arr = np.array(crop)
                    crop_gray = cv2.cvtColor(crop_arr, cv2.COLOR_RGB2GRAY)

                    if _is_blank_crop(crop_gray):
                        total_blank_skipped += 1
                        log.debug("[%s] img %d: skipping blank panel", chapter.tag, panel_idx)
                        continue

                    cw, ch = crop.size
                    if (ch / max(1, cw)) > 1.8:
                        from PIL import Image as PILImage
                        # Tall UI/quest cards get sliced into several panning
                        # sub-frames for display. They all show fragments of
                        # ONE piece of text, so tag them with a shared
                        # scroll_group — OCR'ing (and narrating) each window
                        # separately would chop sentences at arbitrary pixel
                        # boundaries and read them as N disjoint, garbled
                        # clips instead of one continuous line.
                        group_id = f"{chapter.tag}_grp{frame_counter:05d}"
                        scroll_frames = _generate_ui_card_scroll_frames(crop, num_scroll_frames=4)
                        for s_frame in scroll_frames:
                            fp = out_dir / f"frame_{frame_counter:05d}.jpg"
                            s_frame.save(fp, quality=92)
                            frame_id = f"{chapter.tag}_frame_{frame_counter:05d}"
                            frame_entries.append(
                                FrameEntry(
                                    frame_id=frame_id,
                                    filename=fp.name,
                                    path=str(fp.resolve()),
                                    source_page=panel_path.name,
                                    source_index=panel_idx,
                                    frame_kind="scroll_frame",
                                    scroll_group=group_id,
                                )
                            )
                            frame_counter += 1
                    else:
                        from PIL import Image as PILImage
                        frame = _compose_canvas(PILImage.fromarray(crop_arr))
                        fp = out_dir / f"frame_{frame_counter:05d}.jpg"
                        frame.save(fp, quality=92)
                        frame_id = f"{chapter.tag}_frame_{frame_counter:05d}"
                        frame_entries.append(
                            FrameEntry(
                                frame_id=frame_id,
                                filename=fp.name,
                                path=str(fp.resolve()),
                                source_page=panel_path.name,
                                source_index=panel_idx,
                                frame_kind="panel",
                            )
                        )
                        frame_counter += 1
        except Exception as exc:
            log.warning("[%s] Skipping unreadable/corrupt image %s: %s", chapter.tag, panel_path.name, exc)
            continue

    if total_blank_skipped > 0:
        log.info("[%s] skipped %d blank panel(s) during slicing", chapter.tag, total_blank_skipped)

    manifest = CanonicalManifest(
        manifest_version=MANIFEST_VERSION,
        job_id=cfg.job_id,
        chapter_tag=chapter.tag,
        source_pages=[p.name for p in chapter.panel_paths],
        frames=frame_entries,
    )
    manifest.save(manifest_path)
    log.info("[%s] sliced %d source pages into %d canonical frames (contour-based detection)",
             chapter.tag, len(chapter.panel_paths), len(frame_entries))
    return [(Path(f.path), f.source_index) for f in manifest.frames]


def _generate_ui_card_scroll_frames(crop, num_scroll_frames: int = 4) -> List["Image.Image"]:
    """Generate a sequence of linear vertical scroll sub-frames for tall rectangular system/quest UI cards.
    Maintains full resolution width and generates vertical panning steps down the UI card rather than squishing or cropping.
    """
    from PIL import Image

    cw, ch = crop.size
    # Visible window height in source space to match 16:9 ratio at full width cw
    window_h = int(cw * CANVAS_H / CANVAS_W)
    if window_h >= ch:
        return [_compose_canvas(crop)]

    scroll_frames = []
    max_top = ch - window_h
    step = max_top / max(1, num_scroll_frames - 1)

    for i in range(num_scroll_frames):
        top = int(round(i * step))
        bot = min(ch, top + window_h)
        sub_crop = crop.crop((0, top, cw, bot))

        # Scale sub_crop to 1920x1080 canvas preserving aspect ratio
        canvas = Image.new("RGB", (CANVAS_W, CANVAS_H), (0, 0, 0))
        fg = sub_crop.resize((CANVAS_W, CANVAS_H), Image.LANCZOS)
        canvas.paste(fg, (0, 0))
        scroll_frames.append(canvas)

    return scroll_frames


def _compose_canvas(crop):
    """Composite `crop` onto a 1920x1080 canvas with a blurred, cover-fit
    copy of the same panel as the background (instead of plain black bars).
    Uses CONTAIN-FIT for the foreground: scales the panel to fit ENTIRELY
    within the canvas, showing the complete panel — including character
    head and feet — with the blurred backdrop filling the rest of the
    frame. This ensures NO content is ever cut off while avoiding the
    dead-black letterbox bars that plain contain-fit leaves on portrait
    panels.
    Also trims white borders from the source panel first."""
    from PIL import Image, ImageFilter
    import numpy as np

    # Trim white borders from the crop (manhwa pages have white margins)
    crop_arr = np.array(crop)
    gray = np.mean(crop_arr, axis=2)
    h, w = gray.shape

    non_white_rows = np.any(gray < 240, axis=1)
    non_white_cols = np.any(gray < 240, axis=0)
    rows = np.where(non_white_rows)[0]
    cols = np.where(non_white_cols)[0]

    if len(rows) > 10 and len(cols) > 10:
        top = max(0, rows[0] - 5)
        bot = min(h, rows[-1] + 5)
        left = max(0, cols[0] - 5)
        right = min(w, cols[-1] + 5)
        if (bot - top) > 20 and (right - left) > 20:
            crop = crop.crop((left, top, right, bot))

    cw, ch = crop.size

    # Blurred, cover-fit background: scales the SAME panel up until it fully
    # covers the canvas (cropping the overflow, never the foreground), then
    # blurs + darkens it. Fills the whole frame — no black bars — while the
    # sharp foreground panel below still shows every pixel of the source.
    bg_scale = max(CANVAS_W / cw, CANVAS_H / ch)
    bw, bh = max(1, int(cw * bg_scale)), max(1, int(ch * bg_scale))
    bg = crop.resize((bw, bh), Image.LANCZOS)
    bx = (bw - CANVAS_W) // 2
    by = (bh - CANVAS_H) // 2
    bg = bg.crop((bx, by, bx + CANVAS_W, by + CANVAS_H))
    bg = bg.filter(ImageFilter.GaussianBlur(40))
    canvas = Image.eval(bg, lambda p: int(p * 0.55)).convert("RGB")

    # Contain-fit: scale to fit ENTIRELY within canvas, centered.
    # This shows the COMPLETE panel — nothing is ever cut off.
    fg_scale = min(CANVAS_W / cw, CANVAS_H / ch)
    fw, fh = max(1, int(cw * fg_scale)), max(1, int(ch * fg_scale))
    fg = crop.resize((fw, fh), Image.LANCZOS)
    fx = (CANVAS_W - fw) // 2
    fy = (CANVAS_H - fh) // 2
    canvas.paste(fg, (fx, fy))

    return canvas


