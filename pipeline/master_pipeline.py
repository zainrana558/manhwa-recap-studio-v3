def render_chapter(
    cfg: PipelineConfig,
    chapter: Chapter,
    frame_paths: List[Path],
    frame_durations: List[float],
    audio_path: Optional[Path],
) -> Optional[Path]:
    """Render a chapter's static panel frames + per-frame narration into an MP4.

    FAST approach: uses ffmpeg concat demuxer with image durations, so a single
    ffmpeg call creates the entire chapter video (instead of N separate processes).
    This is dramatically faster than the old per-segment approach.

    Each frame is held on screen for exactly its own audio segment's duration
    (frame_durations), so image swaps line up precisely with the narration.
    RESUME: skip entirely if chap_XXX.mp4 already exists on disk."""
    out_path = cfg.temp_chapters_dir / f"{chapter.tag}.mp4"
    if out_path.exists():
        log.info("[%s] chapter video already rendered — skipping (resume)", chapter.tag)
        return out_path

    if not frame_paths:
        log.warning("[%s] no frames to render — skipping chapter", chapter.tag)
        return None

    # Render to a temp path, never the resume-checked `out_path` directly.
    # If this process gets killed mid-ffmpeg-write (OOM, crash, manual
    # interrupt — all realistic on an unattended multi-day Oracle run),
    # `out_path` must NOT exist as a partial/corrupt file, or the next
    # resumed run's `out_path.exists()` check above would treat a broken
    # chapter as done and silently ship it in the final merge.
    tmp_path = cfg.temp_chapters_dir / f"{chapter.tag}.mp4.tmp"
    tmp_path.unlink(missing_ok=True)

    # Write a concat demuxer input file with per-image durations.
    # This lets a SINGLE ffmpeg call produce the whole slideshow video.
    #
    # ffmpeg's concat demuxer computes each entry's on-screen time from the
    # gap between consecutive `file` directives — the `duration` on the
    # FINAL entry has nothing after it to measure against, so ffmpeg drops
    # it and instead holds that last frame for exactly one output frame
    # (1/FPS s). Verified directly: a 2-entry list with durations 3.0/4.0s
    # renders as 3.04s, not 7.0s. Because render_chapter muxes audio with
    # `-shortest`, that truncated video length then cuts the tail off the
    # chapter's real narration audio too — every chapter's final segment
    # was losing its narration and getting frozen on ~1 frame. The
    # documented fix is to repeat the last file path once more with no
    # `duration` line, giving the demuxer an end marker for that segment
    # without adding a new one (it does not add an extra displayed frame).
    concat_list = cfg.temp_chapters_dir / f"{chapter.tag}_images.txt"
    with concat_list.open("w", encoding="utf-8") as f:
        for i, (fp, d) in enumerate(zip(frame_paths, frame_durations)):
            # Ensure the image exists (use absolute path for concat demuxer).
            abs_fp = fp.resolve().as_posix()
            f.write(f"file '{abs_fp}'\n")
            f.write(f"duration {d:.3f}\n")
        if frame_paths:
            # Trailing repeat of the last frame gives the concat demuxer an
            # end-marker for the final real entry (the demuxer ALWAYS drops
            # the last `duration` directive). This repeat MUST also carry its
            # own `duration` line: on ffmpeg 4.2's concat demuxer under
            # `-vsync vfr`, a bare trailing `file` with no duration is held
            # open for an unbounded time, inflating the whole video by
            # 5-15% (verified directly — a 170.24s timeline rendered as
            # 182.4s, which then fails render QA and forces a black-
            # placeholder fallback). With the duration line present the
            # demuxer drops only that one trailing directive and the video
            # renders to the intended length, staying in sync with the
            # audio track. The value is the one that gets dropped, so it's
            # cosmetic — mirror the real last-frame hold.
            last_d = frame_durations[-1] if frame_durations else SILENT_FRAME_DURATION
            f.write(f"file '{frame_paths[-1].resolve().as_posix()}'\n")
            f.write(f"duration {max(0.1, last_d):.3f}\n")

    log.info("[%s] rendering %d frames with concat demuxer", chapter.tag, len(frame_paths))

    # Single ffmpeg call: slideshow from concat demuxer + audio mux.
    # Frames are already 1920x1080 from _compose_canvas, but ensure exact size.
    #
    # The trailing `fps={FPS}` is load-bearing, not cosmetic. On ffmpeg 4.2's
    # concat image demuxer, `-vsync vfr` + an audio input + `-shortest`
    # interact so that the LAST image is held far past its declared duration
    # (verified: a 166.31s frame timeline rendered as 179.12s of video
    # against 166.31s of audio — a 13s progressive desync that also trips
    # render QA into a black-placeholder fallback). Normalising the concat
    # stream to a constant frame rate in the filter graph BEFORE encoding
    # removes that interaction: the same timeline then renders to 166.36s,
    # in sync with the audio. Confirmed to leave the correct no-audio and
    # short-clip ([3,4,5]s -> 12.0s) cases unchanged.
    video_filters = (
        f"scale={CANVAS_W}:{CANVAS_H}:force_original_aspect_ratio=decrease,"
        f"pad={CANVAS_W}:{CANVAS_H}:(ow-iw)/2:(oh-ih)/2,fps={FPS}"
    )
    if getattr(cfg, "watermark", None):
        wm = str(cfg.watermark).replace("\\", "").replace("'", "").replace(":", " ")
        video_filters += (
            f",drawtext=text='{wm}':fontcolor=white@0.55:fontsize=34:"
            f"shadowcolor=black@0.6:shadowx=2:shadowy=2:x=w-tw-32:y=h-th-28"
        )

    # NOTE on -vsync vfr (not "-r FPS"): forcing a constant output frame
    # rate makes ffmpeg duplicate frames to fill each image's declared
    # `duration`, and that duplication math compounds across multiple
    # concat-demuxer duration entries — verified directly: a 3-segment
    # (3.0/4.0/5.0s) concat list rendered as ~16.0s instead of 12.0s under
    # "-r 24", a ~33% overshoot. With has_audio + "-shortest" this overshoot
    # was silently absorbed (the real video track got clipped down to the
    # correct audio length), which is why it stayed hidden — but the
    # no-audio path has no "-shortest" to hide behind and shipped the
    # inflated-duration video as-is. "-vsync vfr" keeps each image's own
    # declared duration exactly (no forced duplication), which is also the
    # semantically correct representation for a static-panel slideshow.
    has_audio = bool(audio_path and audio_path.exists())
    if has_audio:
        cmd = [
            "ffmpeg", "-y",
            "-f", "concat", "-safe", "0",
            "-i", str(concat_list),
            "-i", str(audio_path),
            "-vf", video_filters,
            "-map", "0:v", "-map", "1:a",
            "-c:v", "libx264", "-preset", "veryfast", "-tune", "stillimage", "-crf", "20", "-pix_fmt", "yuv420p",
            "-vsync", "vfr",
            "-c:a", "aac", "-b:a", AUDIO_BITRATE, "-ar", str(AUDIO_SAMPLE_RATE),
            "-shortest",
            # Force the output muxer explicitly rather than letting ffmpeg
            # guess it from the output filename's extension. tmp_path ends
            # in ".mp4.tmp" (by design — see the atomic-write comment
            # above), so extension-sniffing sees ".tmp" as the extension
            # and fails with "Unable to find a suitable output format".
            # This bit the very first real render on production hardware.
            "-f", "mp4",
            str(tmp_path),
        ]
    else:
        cmd = [
            "ffmpeg", "-y",
            "-f", "concat", "-safe", "0",
            "-i", str(concat_list),
            "-vf", video_filters,
            "-c:v", "libx264", "-preset", "veryfast", "-tune", "stillimage", "-crf", "20", "-pix_fmt", "yuv420p",
            "-vsync", "vfr",
            "-f", "mp4",
            str(tmp_path),
        ]

    try:
        run_ffmpeg(cmd)
    except RuntimeError as e:
        log.error("[%s] concat render failed: %s", chapter.tag, e)
        tmp_path.unlink(missing_ok=True)
        return None

    concat_list.unlink(missing_ok=True)

    # Never mark a chapter complete before validation (loudnorm drift,
    # a killed ffmpeg process, or disk pressure can all leave a file that
    # opens but is truncated, has no audio stream, or is far shorter than
    # expected — ffmpeg exiting 0 is not sufficient proof of a good file).
    #
    # Tolerance scales with chapter length (5% of expected duration, floor
    # 5.0s) instead of a flat 5.0s regardless of length. A flat 5s cap is
    # ~1% margin on a long, many-frame chapter — far tighter than the real,
    # benign cumulative drift that legitimately accumulates from several
    # independent, small sources across dozens of frames/segments: the
    # loudnorm pass in build_chapter_audio_track shifting final audio
    # duration via its own lookahead/limiter buffering, ffmpeg's internal
    # frame-timebase rounding on each declared image duration, and the
    # MIN_FRAME_DURATION floor's per-frame stretching all being reconciled
    # independently rather than as one exact running total. None of that
    # is perceptible in the actual video — audio/video sync is governed by
    # the real rendered file, not this internal bookkeeping estimate — but
    # a real production run hit exactly this: a 66-frame, ~482s chapter's
    # actual rendered duration (496.36s, a 2.9% difference) tripped the old
    # flat 5.0s tolerance on all 3 retries, and every retry produces the
    # identical deterministic drift (it's not transient/flaky), so all 3
    # failed identically and the chapter's entire real, correct 66 panels
    # got thrown away for an 8-minute black "unavailable" placeholder.
    # A genuinely broken render (a chapter that comes out a few seconds
    # long instead of several minutes) still fails obviously under a
    # percentage check.
    qa_tolerance = float(os.environ.get("VIDEO_QA_TOLERANCE_SECONDS", "5.0"))
    expected_duration = sum(frame_durations)
    qa_tolerance = max(qa_tolerance, expected_duration * 0.05)
    qa = video_qa(tmp_path, audio_expected=has_audio, expected_duration=expected_duration, tolerance=qa_tolerance)
    if not qa.ok:
        quarantine_dir = cfg.temp_chapters_dir / "quarantine"
        quarantine_dir.mkdir(exist_ok=True)
        bad_path = quarantine_dir / f"{chapter.tag}.{int(time.time())}.{qa.reason}.bad"
        try:
            tmp_path.rename(bad_path)
        except OSError:
            tmp_path.unlink(missing_ok=True)
        log.error(
            "[%s] rendered video FAILED QA (%s) — quarantined",
            chapter.tag, qa.reason,
        )
        return None

    atomic_promote(tmp_path, out_path)
    log.info("[%s] chapter video rendered + QA-validated -> %s", chapter.tag, out_path.name)
    return out_path


def render_chapter_with_retry(
    cfg: PipelineConfig,
    chapter: Chapter,
    frame_paths: List[Path],
    frame_durations: List[float],
    audio_path: Optional[Path],
    max_retries: int = 2,
) -> Optional[Path]:
    """Render chapter with retries. If all retries fail, return None."""
    for attempt in range(1 + max_retries):
        if attempt > 0:
            log.warning("[%s] Retry rendering chapter (attempt %d/%d)...", chapter.tag, attempt + 1, 1 + max_retries)
            time.sleep(2.0)
        res = render_chapter(cfg, chapter, frame_paths, frame_durations, audio_path)
        if res and res.exists():
            return res
    return None


def generate_black_placeholder_chapter(
    cfg: PipelineConfig,
    chapter_tag: str,
    duration: float,
    overlay_text: str,
) -> Path:
    """Generate a silent black video placeholder of specified duration with a text overlay."""
    out_path = cfg.temp_chapters_dir / f"{chapter_tag}.mp4"
    if out_path.exists():
        return out_path

    tmp_path = cfg.temp_chapters_dir / f"{chapter_tag}.mp4.tmp"
    tmp_path.unlink(missing_ok=True)
    dur_str = f"{max(1.0, duration):.3f}"

    # Escape overlay text for ffmpeg drawtext filter
    escaped_text = overlay_text.replace("'", "'\\''").replace(":", "\\:")
    cmd = [
        "ffmpeg", "-y",
        "-f", "lavfi", "-i", f"color=c=black:s={CANVAS_W}x{CANVAS_H}:r={FPS}",
        "-f", "lavfi", "-i", f"anullsrc=r={AUDIO_SAMPLE_RATE}:cl=mono",
        "-t", dur_str,
        "-vf", f"drawtext=text='{escaped_text}':fontcolor=white:fontsize=48:x=(w-text_w)/2:y=(h-text_h)/2",
        "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", AUDIO_BITRATE, "-ar", str(AUDIO_SAMPLE_RATE),
        "-r", str(FPS),
        "-f", "mp4",
        str(tmp_path),
    ]

    try:
        run_ffmpeg(cmd)
        atomic_promote(tmp_path, out_path)
        log.info("[%s] generated black placeholder video (%.1fs) -> %s", chapter_tag, duration, out_path.name)
        return out_path
    except Exception as e:
        log.error("[%s] failed to generate black placeholder video: %s", chapter_tag, e)
        tmp_path.unlink(missing_ok=True)
        raise




