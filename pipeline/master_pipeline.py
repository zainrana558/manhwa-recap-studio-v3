# 6. FFMPEG ZERO-REENCODE STREAM MERGER & BGM OVERLAY
# ---------------------------------------------------------------------------

def run_ffmpeg(cmd: List[str]) -> None:
    log.debug("Running: %s", " ".join(cmd))
    result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=600)
    if result.returncode != 0:
        log.error("ffmpeg command failed (exit %d):\nCMD: %s\nSTDERR:\n%s\nSTDOUT:\n%s",
                  result.returncode, " ".join(cmd), result.stderr or "", result.stdout or "")
        err_msg = (result.stderr or result.stdout or "").strip()
        last_lines = "\n".join(err_msg.splitlines()[-20:])
        raise RuntimeError(f"ffmpeg failed (exit {result.returncode}):\n{last_lines}")


def _resolve_llm_client(cfg: "PipelineConfig"):
    """Return (client, model, provider) for one-off LLM calls (intro synopsis),
    reusing the same provider precedence as rephrase_text. (None, None, 'none')
    if nothing is available."""
    from openai import OpenAI
    provider = cfg.narration_provider
    openai_key = cfg.openai_api_key or os.environ.get("OPENAI_API_KEY")
    if provider in ("auto", "none"):
        if openai_key:
            provider = "openai"
        elif cfg.groq_api_key:
            provider = "groq"
        elif os.environ.get("OLLAMA_BASE_URL") or shutil.which("ollama"):
            provider = "ollama"
        else:
            return None, None, "none"
    try:
        if provider == "ollama":
            base = os.environ.get("OLLAMA_BASE_URL", "http://localhost:11434") + "/v1"
            return OpenAI(api_key="ollama", base_url=base), \
                   cfg.narration_model or os.environ.get("OLLAMA_TEXT_MODEL", "llama3.2:3b"), "ollama"
        if provider == "openai":
            return OpenAI(api_key=openai_key), cfg.narration_model or cfg.openai_model, "openai"
        if provider == "groq":
            return OpenAI(api_key=cfg.groq_api_key, base_url=GROQ_BASE_URL), \
                   cfg.narration_model or cfg.groq_model, "groq"
    except Exception as e:
        log.warning("intro LLM client init failed (%s)", e)
    return None, None, "none"


def _make_title_card(cfg: "PipelineConfig", chapters: "List[Chapter]", title: str) -> Path:
    """Blurred first-page art + darkening + big series title + chapter range."""
    from PIL import Image, ImageFilter, ImageDraw, ImageFont
    out = cfg.work_dir / "intro_card.jpg"
    # Pick the most colourful available page for the backdrop (page 1 of a
    # webtoon is often a dark title splash); fall back to the first page.
    pages = [p for ch in chapters for p in ch.panel_paths if p.exists()]
    bg_src = None
    if pages:
        best_sat = -1.0
        for p in pages[: min(len(pages), 8)]:
            try:
                with Image.open(p) as t:
                    sm = t.convert("HSV").resize((64, 64))
                    sat = float(np.array(sm)[:, :, 1].mean())
                if sat > best_sat:
                    best_sat, bg_src = sat, p
            except Exception:
                continue
        bg_src = bg_src or pages[0]
    if bg_src is not None:
        with Image.open(bg_src) as im:
            im = im.convert("RGB")
            sc = max(CANVAS_W / im.width, CANVAS_H / im.height)
            im = im.resize((int(im.width * sc), int(im.height * sc)), Image.LANCZOS)
            x = max(0, (im.width - CANVAS_W) // 2)
            y = max(0, (im.height - CANVAS_H) // 2)
            bg = im.crop((x, y, x + CANVAS_W, y + CANVAS_H)).filter(ImageFilter.GaussianBlur(26))
        bg = Image.eval(bg, lambda p: int(p * 0.52)).convert("RGB")
    else:
        bg = Image.new("RGB", (CANVAS_W, CANVAS_H), (12, 14, 22))

    draw = ImageDraw.Draw(bg)

    def _font(size: int):
        for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
                  "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"):
            if os.path.exists(p):
                return ImageFont.truetype(p, size)
        return ImageFont.load_default()

    # word-wrap the title to <= ~18 chars/line at a large size
    words, lines, cur = title.split(), [], ""
    for w in words:
        if len((cur + " " + w).strip()) <= 22:
            cur = (cur + " " + w).strip()
        else:
            lines.append(cur); cur = w
    if cur:
        lines.append(cur)
    tf = _font(96)
    total_h = sum(draw.textbbox((0, 0), ln, font=tf)[3] + 16 for ln in lines)
    y = (CANVAS_H - total_h) // 2 - 40
    for ln in lines:
        bb = draw.textbbox((0, 0), ln, font=tf)
        tw = bb[2] - bb[0]
        px = (CANVAS_W - tw) // 2
        for dx, dy in ((-3, -3), (3, -3), (-3, 3), (3, 3)):
            draw.text((px + dx, y + dy), ln, font=tf, fill=(0, 0, 0))
        draw.text((px, y), ln, font=tf, fill=(255, 255, 255))
        y += (bb[3] - bb[1]) + 28

    sub = "Chapter " + (chapters[0].name.split("_")[-1] if chapters else "1")
    n = len(chapters)
    if n > 1:
        sub = f"Chapters {chapters[0].name.split('_')[-1]}–{chapters[-1].name.split('_')[-1]}"
    sf = _font(56)
    bb = draw.textbbox((0, 0), sub, font=sf)
    px = (CANVAS_W - (bb[2] - bb[0])) // 2
    draw.text((px + 2, y + 22), sub, font=sf, fill=(0, 0, 0))
    draw.text((px, y + 20), sub, font=sf, fill=(255, 210, 90))

    bg.save(out, quality=92)
    return out


INTRO_MAX_SECONDS = 10.0


def build_intro_video(cfg: "PipelineConfig", chapters: "List[Chapter]") -> Optional[Path]:
    """Short spoken title drop over a title card (<= INTRO_MAX_SECONDS),
    prepended to the recap. Template-based — no LLM, no translation."""
    out_path = cfg.temp_chapters_dir / "chap_000_intro.mp4"
    if out_path.exists():
        log.info("intro video already built — reusing")
        return out_path

    title = cfg.recap_title or cfg.input_dir.name.replace("_", " ").replace("-", " ").strip().title()
    if chapters:
        first_n = chapters[0].name.split("_")[-1].lstrip("0") or "1"
        last_n = chapters[-1].name.split("_")[-1].lstrip("0") or "1"
        span = f"chapter {first_n}" if len(chapters) == 1 else f"chapters {first_n} to {last_n}"
    else:
        span = "chapter 1"
    channel = (cfg.watermark or "").strip()
    lead = f"Welcome to {channel}. " if channel else ""
    script = f"{lead}This is {title}, {span}. Let's get into it."
    (cfg.temp_scripts_dir / "chap_000_intro.txt").write_text(script, encoding="utf-8")
    log.info("intro line: %r", script)

    # TTS (Piper) -> loudnorm stereo
    raw_wav = cfg.temp_audio_dir / "intro_raw.wav"
    audio_wav = cfg.temp_audio_dir / "intro.wav"
    try:
        _synthesize_with_piper(script, raw_wav)
    except Exception as e:
        log.warning("intro TTS failed (%s) — skipping intro", e)
        return None
    try:
        run_ffmpeg([
            "ffmpeg", "-y", "-i", str(raw_wav),
            "-af", f"loudnorm=I={TARGET_LOUDNESS_LUFS}:TP=-1.5:LRA=11",
            "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "2", str(audio_wav),
        ])
    except RuntimeError:
        run_ffmpeg(["ffmpeg", "-y", "-i", str(raw_wav), "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "2", str(audio_wav)])
    dur = get_audio_duration(audio_wav)
    if dur < 1.5:
        log.warning("intro audio unexpectedly short (%.1fs) — skipping intro", dur)
        return None
    if dur > INTRO_MAX_SECONDS:
        trimmed = cfg.temp_audio_dir / "intro_trim.wav"
        run_ffmpeg(["ffmpeg", "-y", "-i", str(audio_wav), "-t", f"{INTRO_MAX_SECONDS:.2f}",
                    "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "2", str(trimmed)])
        audio_wav, dur = trimmed, INTRO_MAX_SECONDS

    card = _make_title_card(cfg, chapters, title)
    tmp = cfg.temp_chapters_dir / "chap_000_intro.mp4.tmp"
    tmp.unlink(missing_ok=True)
    vf = f"scale={CANVAS_W}:{CANVAS_H},format=yuv420p,fps={FPS}"
    if getattr(cfg, "watermark", None):
        wm = str(cfg.watermark).replace("\\", "").replace("'", "").replace(":", " ")
        vf += (f",drawtext=text='{wm}':fontcolor=white@0.55:fontsize=34:"
               f"shadowcolor=black@0.6:shadowx=2:shadowy=2:x=w-tw-32:y=h-th-28")
    run_ffmpeg([
        "ffmpeg", "-y",
        "-loop", "1", "-framerate", str(FPS), "-i", str(card),
        "-i", str(audio_wav),
        "-vf", vf,
        "-c:v", "libx264", "-preset", "veryfast", "-tune", "stillimage", "-crf", "20",
        "-c:a", "aac", "-b:a", AUDIO_BITRATE, "-ar", str(AUDIO_SAMPLE_RATE), "-ac", "2",
        "-shortest", "-t", f"{dur + 0.4:.3f}",
        "-f", "mp4", str(tmp),
    ])
    atomic_promote(tmp, out_path)
    log.info("intro video built (%.1fs) -> %s", dur, out_path.name)
    return out_path


def merge_chapters(cfg: PipelineConfig, chapter_videos: List[Path]) -> Path:
    """Zero-reencode concat of all chapter mp4s via ffmpeg's concat demuxer."""
    valid_videos: List[Path] = []
    for idx, cv in enumerate(chapter_videos, start=1):
        if cv and cv.exists() and cv.stat().st_size > 1024:
            valid_videos.append(cv)
        else:
            log.warning("Chapter video %s missing or corrupt during merge — substituting placeholder", cv)
            placeholder = generate_black_placeholder_chapter(
                cfg,
                f"chap_{idx:03d}_missing",
                SILENT_FRAME_DURATION,
                f"Chapter {idx} unavailable",
            )
            valid_videos.append(placeholder)

    chapter_videos = valid_videos

    concat_list = cfg.work_dir / "concat_list.txt"
    with concat_list.open("w", encoding="utf-8") as f:
        for cv in chapter_videos:
            f.write(f"file '{cv.resolve().as_posix()}'\n")

    merged_path = cfg.work_dir / "master_merged.mp4"
    if merged_path.exists():
        log.info("Merged master file already exists — skipping merge step (resume)")
        return merged_path

    # Individual chapters are already QA-validated on their own, but the
    # concat step itself (stream copy across N files) can still fail
    # partway through or get killed mid-write — write to a tmp path and
    # only promote to `merged_path` (the resume-checked path above) after
    # the merged file passes QA, for the same reason as render_chapter.
    tmp_path = cfg.work_dir / "master_merged.mp4.tmp"
    tmp_path.unlink(missing_ok=True)

    log.info("Merging %d chapter videos via ffmpeg stream copy...", len(chapter_videos))
    run_ffmpeg(
        [
            "ffmpeg", "-y", "-f", "concat", "-safe", "0",
            "-i", str(concat_list),
            "-c", "copy",
            # Same fix as render_chapter: force the output muxer instead of
            # relying on tmp_path's extension (".mp4.tmp" -> ffmpeg would
            # otherwise see ".tmp" and fail with "Unable to find a
            # suitable output format").
            "-f", "mp4",
            str(tmp_path),
        ]
    )

    qa = video_qa(tmp_path, audio_expected=True)
    if not qa.ok:
        quarantine_dir = cfg.work_dir / "quarantine"
        quarantine_dir.mkdir(exist_ok=True)
        bad_path = quarantine_dir / f"master_merged.{int(time.time())}.{qa.reason}.bad"
        try:
            tmp_path.rename(bad_path)
        except OSError:
            tmp_path.unlink(missing_ok=True)
        raise RuntimeError(f"merged master video failed QA ({qa.reason}) — see {bad_path}")

    atomic_promote(tmp_path, merged_path)
    log.info("Merge complete + QA-validated -> %s", merged_path.name)
    return merged_path


def finalize_output(cfg: PipelineConfig, merged_path: Path) -> Path:
    """Copy the merged video to the final output path, mixing in background
    music (sidechain-ducked under narration) when cfg.bgm_path is set.

    `merged_path` was already QA-validated by merge_chapters, but the tmp
    path + re-check + atomic rename dance below still applies either way: a
    crash or a full disk mid-copy/mid-encode can leave a truncated file
    sitting at cfg.output_path — the one path anything downstream (upload,
    YouTube metadata step, the person opening the file) actually trusts as
    "the finished video." That path must never be observably partial.
    """
    cfg.output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = cfg.output_path.with_suffix(cfg.output_path.suffix + ".tmp")
    tmp_path.unlink(missing_ok=True)

    if cfg.bgm_path and cfg.bgm_path.exists():
        log.info("Mixing background music (%s) into final output...", cfg.bgm_path.name)
        try:
            # -stream_loop -1 loops the BGM indefinitely; `-shortest` on the
            # output then trims everything to the (unchanged) video length,
            # so this works regardless of whether the track is shorter or
            # longer than the recap. sidechaincompress ducks the BGM
            # whenever narration is present, keyed off the narration track
            # itself; amix folds the ducked BGM back under the voice.
            # Video stream is copied untouched — only audio is re-encoded.
            duck_ratio = 8  # higher = more aggressive ducking under voice
            filter_complex = (
                f"[1:a]volume=0.35[bgm];"
                f"[bgm][0:a]sidechaincompress=threshold=0.05:ratio={duck_ratio}:"
                f"attack=20:release=400:makeup=1[ducked];"
                f"[0:a][ducked]amix=inputs=2:duration=first:dropout_transition=2:weights=1 1[aout]"
            )
            run_ffmpeg([
                "ffmpeg", "-y",
                "-i", str(merged_path),
                "-stream_loop", "-1", "-i", str(cfg.bgm_path),
                "-filter_complex", filter_complex,
                "-map", "0:v", "-map", "[aout]",
                "-c:v", "copy",
                "-c:a", "aac", "-b:a", AUDIO_BITRATE, "-ar", str(AUDIO_SAMPLE_RATE),
                "-shortest",
                "-f", "mp4",
                str(tmp_path),
            ])
        except RuntimeError as e:
            # BGM mixing is a nice-to-have, not worth failing a multi-hour
            # unattended job over — fall back to the clean narration-only cut.
            log.error("BGM mix failed (%s) — falling back to narration-only output", e)
            tmp_path.unlink(missing_ok=True)
            shutil.copy2(merged_path, tmp_path)
    else:
        log.info("Copying merged video to final output (no BGM configured)...")
        shutil.copy2(merged_path, tmp_path)

    qa = video_qa(tmp_path, audio_expected=True)
    if not qa.ok:
        tmp_path.unlink(missing_ok=True)
        raise RuntimeError(
            f"final output failed QA ({qa.reason}) — refusing to mark the job complete"
        )

    atomic_promote(tmp_path, cfg.output_path)
    log.info("Final master video written + QA-validated -> %s", cfg.output_path)
    return cfg.output_path


