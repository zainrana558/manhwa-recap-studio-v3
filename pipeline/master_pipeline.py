TRANSLATE_SYSTEM_PROMPT = (
    "You are a professional translator. If the given text is already in English, "
    "return it completely unchanged. Otherwise, translate it into natural, fluent "
    "English, preserving names, tone, and meaning as closely as possible. "
    "Output ONLY the resulting English text — no preamble, no notes, no language labels."
)


def translate_text(cfg: PipelineConfig, text: str, cache_tag: str) -> str:
    """Translate a block of text to English via Groq. Cached by cache_tag.
    Any API error falls back to raw text so the pipeline never crashes."""
    out_path = cfg.temp_scripts_dir / f"{cache_tag}_translated.txt"
    if out_path.exists():
        return out_path.read_text(encoding="utf-8")

    if not text:
        out_path.write_text("", encoding="utf-8")
        return ""

    if not cfg.translate:
        log.info("[%s] translation disabled — using raw text as-is", cache_tag)
        out_path.write_text(text, encoding="utf-8")
        return text

    # Try Groq first (fast, free tier available), then Ollama as fallback
    providers_tried = []

    if cfg.groq_api_key:
        try:
            from openai import OpenAI
            client = OpenAI(api_key=cfg.groq_api_key, base_url=GROQ_BASE_URL)
            resp = client.chat.completions.create(
                model=cfg.groq_model,
                messages=[
                    {"role": "system", "content": TRANSLATE_SYSTEM_PROMPT},
                    {"role": "user", "content": text},
                ],
                temperature=0.2,
                timeout=60,
            )
            translated = resp.choices[0].message.content.strip()
            if not translated:
                translated = text
            out_path.write_text(translated, encoding="utf-8")
            log.info("[%s] translated via Groq (%d chars)", cache_tag, len(translated))
            return translated
        except Exception as e:
            log.warning("[%s] Groq translation failed (%s)", cache_tag, e)
            providers_tried.append("Groq")

    # Fallback: Ollama (local, free)
    ollama_url = os.environ.get("OLLAMA_BASE_URL", "http://localhost:11434") + "/v1"
    ollama_model = os.environ.get("OLLAMA_TEXT_MODEL", "llama3.2:3b")
    try:
        from openai import OpenAI
        client = OpenAI(api_key="ollama", base_url=ollama_url)
        resp = client.chat.completions.create(
            model=ollama_model,
            messages=[
                {"role": "system", "content": TRANSLATE_SYSTEM_PROMPT},
                {"role": "user", "content": text},
            ],
            temperature=0.2,
            timeout=120,
        )
        translated = resp.choices[0].message.content.strip()
        if not translated:
            translated = text
        out_path.write_text(translated, encoding="utf-8")
        log.info("[%s] translated via Ollama/%s (%d chars)", cache_tag, ollama_model, len(translated))
        return translated
    except Exception as e:
        log.warning("[%s] Ollama translation also failed (%s) — using raw text", cache_tag, e)
        out_path.write_text(text, encoding="utf-8")
        return text


