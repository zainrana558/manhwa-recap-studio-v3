def run_ffmpeg(cmd: List[str]) -> None:
    log.debug("Running: %s", " ".join(cmd))
    result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=600)
    if result.returncode != 0:
        log.error("ffmpeg command failed (exit %d):\nCMD: %s\nSTDERR:\n%s\nSTDOUT:\n%s",
                  result.returncode, " ".join(cmd), result.stderr or "", result.stdout or "")
        err_msg = (result.stderr or result.stdout or "").strip()
        last_lines = "\n".join(err_msg.splitlines()[-20:])
        raise RuntimeError(f"ffmpeg failed (exit {result.returncode}):\n{last_lines}")


def merge_chapters(cfg: PipelineConfig, chapter_videos: List[Path]) -> Path:
    """Zero-reencode concat of all chapter mp4s via ffmpeg's concat demuxer."""
    valid_videos: List[Path] = []
    for idx, cv in enumerate(chapter_videos, start=1):
        if cv and cv.exists() and cv.stat().st_size > 1024:
            valid_videos.append(cv)
        else:
            log.warning("Chapter video %s missing or corrupt during merge — substituting placeholder", cv)
            placeholder = generate_black_placeholder_chapter(
                cfg,
                f"chap_{idx:03d}_missing",
                SILENT_FRAME_DURATION,
                f"Chapter {idx} unavailable",
            )
            valid_videos.append(placeholder)

    chapter_videos = valid_videos

    concat_list = cfg.work_dir / "concat_list.txt"
    with concat_list.open("w", encoding="utf-8") as f:
        for cv in chapter_videos:
            f.write(f"file '{cv.resolve().as_posix()}'\n")

    merged_path = cfg.work_dir / "master_merged.mp4"
    if merged_path.exists():
        log.info("Merged master file already exists — skipping merge step (resume)")
        return merged_path

    # Individual chapters are already QA-validated on their own, but the
    # concat step itself (stream copy across N files) can still fail
    # partway through or get killed mid-write — write to a tmp path and
    # only promote to `merged_path` (the resume-checked path above) after
    # the merged file passes QA, for the same reason as render_chapter.
    tmp_path = cfg.work_dir / "master_merged.mp4.tmp"
    tmp_path.unlink(missing_ok=True)

    log.info("Merging %d chapter videos via ffmpeg stream copy...", len(chapter_videos))
    run_ffmpeg(
        [
            "ffmpeg", "-y", "-f", "concat", "-safe", "0",
            "-i", str(concat_list),
            "-c", "copy",
            # Same fix as render_chapter: force the output muxer instead of
            # relying on tmp_path's extension (".mp4.tmp" -> ffmpeg would
            # otherwise see ".tmp" and fail with "Unable to find a
            # suitable output format").
            "-f", "mp4",
            str(tmp_path),
        ]
    )

    qa = video_qa(tmp_path, audio_expected=True)
    if not qa.ok:
        quarantine_dir = cfg.work_dir / "quarantine"
        quarantine_dir.mkdir(exist_ok=True)
        bad_path = quarantine_dir / f"master_merged.{int(time.time())}.{qa.reason}.bad"
        try:
            tmp_path.rename(bad_path)
        except OSError:
            tmp_path.unlink(missing_ok=True)
        raise RuntimeError(f"merged master video failed QA ({qa.reason}) — see {bad_path}")

    atomic_promote(tmp_path, merged_path)
    log.info("Merge complete + QA-validated -> %s", merged_path.name)
    return merged_path


def finalize_output(cfg: PipelineConfig, merged_path: Path) -> Path:
    """Copy the merged video to the final output path, mixing in background
    music (sidechain-ducked under narration) when cfg.bgm_path is set.

    `merged_path` was already QA-validated by merge_chapters, but the tmp
    path + re-check + atomic rename dance below still applies either way: a
    crash or a full disk mid-copy/mid-encode can leave a truncated file
    sitting at cfg.output_path — the one path anything downstream (upload,
    YouTube metadata step, the person opening the file) actually trusts as
    "the finished video." That path must never be observably partial.
    """
    cfg.output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = cfg.output_path.with_suffix(cfg.output_path.suffix + ".tmp")
    tmp_path.unlink(missing_ok=True)

    if cfg.bgm_path and cfg.bgm_path.exists():
        log.info("Mixing background music (%s) into final output...", cfg.bgm_path.name)
        try:
            # -stream_loop -1 loops the BGM indefinitely; `-shortest` on the
            # output then trims everything to the (unchanged) video length,
            # so this works regardless of whether the track is shorter or
            # longer than the recap. sidechaincompress ducks the BGM
            # whenever narration is present, keyed off the narration track
            # itself; amix folds the ducked BGM back under the voice.
            # Video stream is copied untouched — only audio is re-encoded.
            duck_ratio = 8  # higher = more aggressive ducking under voice
            filter_complex = (
                f"[1:a]volume=0.35[bgm];"
                f"[bgm][0:a]sidechaincompress=threshold=0.05:ratio={duck_ratio}:"
                f"attack=20:release=400:makeup=1[ducked];"
                f"[0:a][ducked]amix=inputs=2:duration=first:dropout_transition=2:weights=1 1[aout]"
            )
            run_ffmpeg([
                "ffmpeg", "-y",
                "-i", str(merged_path),
                "-stream_loop", "-1", "-i", str(cfg.bgm_path),
                "-filter_complex", filter_complex,
                "-map", "0:v", "-map", "[aout]",
                "-c:v", "copy",
                "-c:a", "aac", "-b:a", AUDIO_BITRATE, "-ar", str(AUDIO_SAMPLE_RATE),
                "-shortest",
                "-f", "mp4",
                str(tmp_path),
            ])
        except RuntimeError as e:
            # BGM mixing is a nice-to-have, not worth failing a multi-hour
            # unattended job over — fall back to the clean narration-only cut.
            log.error("BGM mix failed (%s) — falling back to narration-only output", e)
            tmp_path.unlink(missing_ok=True)
            shutil.copy2(merged_path, tmp_path)
    else:
        log.info("Copying merged video to final output (no BGM configured)...")
        shutil.copy2(merged_path, tmp_path)

    qa = video_qa(tmp_path, audio_expected=True)
    if not qa.ok:
        tmp_path.unlink(missing_ok=True)
        raise RuntimeError(
            f"final output failed QA ({qa.reason}) — refusing to mark the job complete"
        )

    atomic_promote(tmp_path, cfg.output_path)
    log.info("Final master video written + QA-validated -> %s", cfg.output_path)
    return cfg.output_path


