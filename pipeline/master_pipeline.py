def run_pipeline(cfg: PipelineConfig) -> None:
    start = time.time()
    cfg.ensure_dirs()
    # Ensure the output directory exists.
    cfg.output_path.parent.mkdir(parents=True, exist_ok=True)

    # Fail fast rather than start a doomed multi-day batch: on an Oracle
    # free-tier instance, running out of disk mid-encode is a much worse
    # failure mode than never starting (a partially-full disk from an
    # earlier crashed run, temp files from a different job, etc. are all
    # realistic on a small always-on box). This is a pre-flight check
    # only — the per-chapter check inside the loop below is what catches
    # resource pressure that builds up DURING a long run.
    # SQLiteStateStore gives every chapter's stage/state/error/retry history
    # a queryable, durable record (survives process restarts, unlike the
    # JSON progress file which the Node service just polls for the current
    # snapshot) — this is what turns "filesystem existence checks" into the
    # kind of real state tracking a multi-day unattended batch needs to be
    # debuggable after the fact.
    state_store = SQLiteStateStore(cfg.work_dir / "pipeline_state.sqlite3")
    state_store.record(cfg.job_id, Stage.JOB, State.RUNNING)

    resource_guard = ResourceGuard(
        min_free_disk_bytes=int(cfg.min_free_disk_gb * 1_000_000_000),
        min_available_ram_bytes=int(cfg.min_available_ram_mb * 1_000_000),
        state=state_store,
    )
    preflight = resource_guard.wait_for_resources(cfg.work_dir, job_id=cfg.job_id, stage=Stage.JOB, check_interval_sec=15, max_wait_sec=120, logger=log)
    if not preflight.ok:
        log.warning(
            f"Resource threshold not met at preflight: {preflight.reason} (free disk: "
            f"{preflight.free_disk_bytes / 1e9:.2f}GB, available RAM: "
            f"{preflight.available_ram_bytes / 1e6:.0f}MB). Proceeding best-effort."
        )

    chapters = discover_chapters(cfg)
    total = len(chapters)
    chapter_videos: List[Path] = []
    # Chapters that rendering genuinely failed for, where a black
    # "unavailable" placeholder was substituted so the merged video still
    # has a slot for every chapter instead of jump-cutting. Tracked
    # SEPARATELY from chapter_videos (which now includes placeholders) so
    # the end-of-run success/UNCERTAIN decision below can't be fooled by a
    # placeholder padding chapter_videos up to `total` and looking like a
    # clean run.
    placeholder_chapters: List[str] = []
    prev_tail = ""

    cfg.write_progress("render", 0, total, f"Starting pipeline over {total} chapters")

    for chapter in chapters:
        t0 = time.time()
        log.info("=== Chapter %d/%d (%s) ===", chapter.index, total, chapter.name)
        cfg.write_progress("render", chapter.index - 1, total, f"Chapter {chapter.index}/{total}: {chapter.name}")

        # Resource pressure on a long batch typically builds up over time
        # (temp files accumulating, other processes on the same small
        # instance) rather than being present at startup — wait for
        # resources before each chapter's ffmpeg/TTS/OCR work.
        resource_status = resource_guard.wait_for_resources(
            cfg.work_dir, job_id=cfg.job_id, stage=Stage.CHAPTER, check_interval_sec=60, max_wait_sec=600, logger=log
        )
        if not resource_status.ok:
            log.warning(
                "[%s] resource guard threshold still not met after pause: %s (free disk: %.2fGB, "
                "available RAM: %.0fMB) — attempting chapter best-effort",
                chapter.tag, resource_status.reason,
                resource_status.free_disk_bytes / 1e9, resource_status.available_ram_bytes / 1e6,
            )
            cfg.write_progress(
                "render", chapter.index - 1, total,
                f"Resource warning: {resource_status.reason}", status="warning",
            )

        existing_video = cfg.temp_chapters_dir / f"{chapter.tag}.mp4"
        if existing_video.exists():
            log.info("[%s] fully rendered already — resuming past this chapter", chapter.tag)
            chapter_videos.append(existing_video)
            state_store.record(cfg.job_id, Stage.CHAPTER, State.COMPLETE, chapter_id=chapter.tag, artifact_path=existing_video)
            # Keep narrative continuity even when resuming: pull tail from cached script.
            script_cache = cfg.temp_scripts_dir / f"{chapter.tag}.txt"
            if script_cache.exists():
                prev_tail = last_sentences(script_cache.read_text(encoding="utf-8"))
            continue

        state_store.record(cfg.job_id, Stage.CHAPTER, State.RUNNING, chapter_id=chapter.tag)
        try:
            cfg.write_progress("slice", chapter.index - 1, total,
                               f"Chapter {chapter.index}/{total}: slicing panels...")
            frame_data = slice_chapter_panels(cfg, chapter)

            manifest_path = cfg.temp_slices_dir / chapter.tag / "manifest.json"
            manifest = load_or_migrate_manifest(manifest_path, chapter=chapter, job_id=cfg.job_id)
            if manifest and manifest.frames:
                frame_paths = [Path(f.path) if Path(f.path).exists() else cfg.temp_slices_dir / chapter.tag / f.filename for f in manifest.frames]
                frame_sources = [f.source_index for f in manifest.frames]
            else:
                frame_paths = [fp for fp, _ in frame_data]
                frame_sources = [si for _, si in frame_data]

            log.info("[%s] %d canonical frames from %d source pages", chapter.tag, len(frame_paths), len(chapter.panel_paths))
            cfg.write_progress("slice", chapter.index - 1, total,
                               f"Chapter {chapter.index}/{total}: sliced {len(frame_paths)} frames")

            # Build an ordered list of (tag, text, frame_positions) "segments" —
            # each one gets exactly ONE continuous edge-tts synthesis call, then
            # real word timestamps from that single clip drive per-frame timing.
            segments: List[tuple] = []  # (tag, text, positions)

            if chapter.image_narrations:
                frame_keyed = any(
                    k.startswith("frame_") or (manifest and k in [f.frame_id for f in manifest.frames])
                    for k in chapter.image_narrations.keys()
                )

                if frame_keyed:
                    log.info("[%s] per-frame narration mode: %d frames (canonical frame transcriptions)",
                             chapter.tag, len(frame_paths))

                    # One segment per frame, EXCEPT scroll_frame siblings
                    # (the panning sub-frames sliced from one tall UI card)
                    # which share a scroll_group and are collapsed into ONE
                    # segment. OCR'ing/narrating each panning window on its
                    # own would chop one card's text at arbitrary pixel
                    # boundaries into several disjoint, garbled clips.
                    position_groups: List[List[int]] = []
                    pos = 0
                    while pos < len(frame_paths):
                        f_entry = manifest.frames[pos] if (manifest and pos < len(manifest.frames)) else None
                        group_key = f_entry.scroll_group if f_entry else None
                        if group_key:
                            group = [pos]
                            pos += 1
                            while pos < len(frame_paths):
                                next_entry = manifest.frames[pos] if (manifest and pos < len(manifest.frames)) else None
                                if next_entry and next_entry.scroll_group == group_key:
                                    group.append(pos)
                                    pos += 1
                                else:
                                    break
                            position_groups.append(group)
                        else:
                            position_groups.append([pos])
                            pos += 1

                    for positions in position_groups:
                        fragments: List[str] = []
                        statuses: List[str] = []
                        for gpos in positions:
                            fp = frame_paths[gpos]
                            f_entry = manifest.frames[gpos] if (manifest and gpos < len(manifest.frames)) else None
                            raw_narr_entry = None
                            if f_entry:
                                raw_narr_entry = (
                                    chapter.image_narrations.get(f_entry.frame_id)
                                    or chapter.image_narrations.get(f_entry.filename)
                                    or chapter.image_narrations.get(fp.name)
                                )
                            else:
                                raw_narr_entry = chapter.image_narrations.get(fp.name)

                            parsed = parse_narration_item(raw_narr_entry)
                            raw_text, ocr_status = parsed["text"], parsed["status"]
                            if f_entry:
                                f_entry.ocr_status = ocr_status
                                f_entry.ocr_text = raw_text
                            if raw_text.strip():
                                fragments.append(raw_text.strip())
                            statuses.append(ocr_status)

                        img_tag = f"{chapter.tag}_frm{positions[0] + 1:04d}"
                        frame_names = [frame_paths[p].name for p in positions]

                        if not fragments:
                            if statuses and all(s == OcrStatus.FAILED for s in statuses):
                                log.warning("[%s] [%s] OCR FAILED for frame(s) %s — retaining FAILED status, producing silent frame(s)",
                                            chapter.tag, img_tag, frame_names)
                                segments.append((f"frm{positions[0] + 1:04d}", "", positions, OcrStatus.FAILED))
                            else:
                                log.info("[%s] [%s] NO_TEXT confirmed for frame(s) %s", chapter.tag, img_tag, frame_names)
                                segments.append((f"frm{positions[0] + 1:04d}", "", positions, OcrStatus.NO_TEXT))
                        else:
                            combined_text = _join_scroll_fragments(fragments) if len(positions) > 1 else fragments[0]
                            overall_status = OcrStatus.UNCERTAIN if OcrStatus.UNCERTAIN in statuses else OcrStatus.SUCCESS
                            if overall_status == OcrStatus.UNCERTAIN:
                                log.warning("[%s] [%s] OCR UNCERTAIN for frame(s) %s — using available text", chapter.tag, img_tag, frame_names)
                            translated = translate_text(cfg, combined_text, img_tag)
                            rephrased = rephrase_text(cfg, translated, img_tag, prev_tail)
                            if rephrased:
                                prev_tail = last_sentences(rephrased)
                            segments.append((f"frm{positions[0] + 1:04d}", rephrased, positions, overall_status))
                else:
                    log.info("[%s] per-image narration mode: %d source images, %d frames",
                             chapter.tag, len(chapter.panel_paths), len(frame_paths))
                    # Legacy: translate + rephrase each source image's narration.
                    panel_narrations: dict = {}  # panel_index -> (rephrased_text, status)
                    for idx, panel_path in enumerate(chapter.panel_paths):
                        parsed = parse_narration_item(chapter.image_narrations.get(panel_path.name))
                        raw_text, ocr_status = parsed["text"], parsed["status"]
                        img_tag = f"{chapter.tag}_img{idx + 1:03d}"

                        if ocr_status == OcrStatus.FAILED:
                            log.warning("[%s] [%s] OCR FAILED for source panel %s", chapter.tag, img_tag, panel_path.name)
                            panel_narrations[idx] = ("", OcrStatus.FAILED)
                        elif ocr_status == OcrStatus.NO_TEXT:
                            panel_narrations[idx] = ("", OcrStatus.NO_TEXT)
                        elif ocr_status == OcrStatus.UNCERTAIN:
                            log.warning("[%s] [%s] OCR UNCERTAIN for source panel %s (confidence=%.2f)", chapter.tag, img_tag, panel_path.name, parsed["confidence"])
                            translated = translate_text(cfg, raw_text, img_tag)
                            rephrased = rephrase_text(cfg, translated, img_tag, prev_tail)
                            if rephrased:
                                prev_tail = last_sentences(rephrased)
                            panel_narrations[idx] = (rephrased, OcrStatus.UNCERTAIN)
                        else:
                            translated = translate_text(cfg, raw_text, img_tag)
                            rephrased = rephrase_text(cfg, translated, img_tag, prev_tail)
                            if rephrased:
                                prev_tail = last_sentences(rephrased)
                            panel_narrations[idx] = (rephrased, OcrStatus.SUCCESS)

                    # Group frame positions by source panel (preserving timeline order).
                    from collections import defaultdict as _dd
                    panel_frame_positions = _dd(list)  # panel_index -> [frame_positions]
                    for pos, si in enumerate(frame_sources):
                        panel_frame_positions[si].append(pos)

                    for si, positions in panel_frame_positions.items():
                        narr, st = panel_narrations.get(si, ("", OcrStatus.NO_TEXT))
                        segments.append((f"img{si + 1:03d}", narr, positions, st))
            else:
                # No narration.json — all frames are silent (no text to narrate).
                log.warning("[%s] no narration.json — producing silent video for this chapter", chapter.tag)
                for pos in range(len(frame_paths)):
                    segments.append((f"frm{pos + 1:04d}", "", [pos], OcrStatus.NO_TEXT))

            # Pre-synthesize every segment's audio CONCURRENTLY into the
            # per-segment cache. TTS is dominated by the edge-tts network
            # round-trip (~1s each) which is pure I/O — running them in a
            # small thread pool turns ~40s of sequential waiting into ~5s.
            # The sequential loop below then hits each cached {tag}.wav
            # instantly, so its stateful timing math is untouched.
            _prewarm_segment_audio(cfg, chapter, segments)

            # Synthesize one continuous clip per segment and derive per-frame timing.
            # No whisper transcription — timing is derived purely from proportional
            # word-count splits, with a MIN_FRAME_DURATION floor so panels don't flash by.
            frame_timing = [None] * len(frame_paths)  # position -> (start, end) clip-local to its segment
            segment_audio_paths: List[Path] = []
            chapter_offset = 0.0
            tts_attempted = 0   # segments that HAD text (i.e. were supposed to produce real speech)
            tts_failed = 0      # of those, how many fell back to silence due to a real failure

            consecutive_silent = 0
            for seg_idx, seg_item in enumerate(segments):
                tag, text, positions = seg_item[0], seg_item[1], seg_item[2]
                ocr_st = seg_item[3] if len(seg_item) > 3 else (OcrStatus.SUCCESS if text.strip() else OcrStatus.NO_TEXT)

                cfg.write_progress("render", chapter.index - 1, total,
                                   f"Chapter {chapter.index}/{total}: TTS {seg_idx+1}/{len(segments)}")

                is_silent_segment = not text.strip() or ocr_st in (OcrStatus.NO_TEXT, OcrStatus.FAILED)
                if not is_silent_segment:
                    consecutive_silent = 0
                    tts_attempted += 1
                else:
                    consecutive_silent += 1

                audio_path_seg, seg_tts_failed, word_boundaries = synthesize_segment_audio(cfg, chapter, tag, text)
                if not is_silent_segment and seg_tts_failed:
                    tts_failed += 1

                duration = get_audio_duration(audio_path_seg)

                if is_silent_segment:
                    # Pacing safeguard: apply shortened duration for silent frames, and compress if consecutive > 2
                    base_silent_dur = 1.0 if consecutive_silent > 2 else SILENT_FRAME_DURATION
                    target_dur = max(0.5, len(positions) * base_silent_dur)
                    if abs(duration - target_dur) > 0.05:
                        audio_path_seg = cfg.temp_audio_dir / chapter.tag / f"{tag}_silent_paced.wav"
                        _generate_silence(audio_path_seg, target_dur)
                        duration = target_dur
                else:
                    min_total = len(positions) * MIN_FRAME_DURATION
                    if duration < min_total:
                        audio_path_seg = pad_audio_with_silence(audio_path_seg, min_total)
                        duration = min_total

                timings = split_frame_timings(text, positions, duration, is_silent=is_silent_segment, word_boundaries=word_boundaries)
                for pos in positions:
                    frame_timing[pos] = timings[pos]
                # The frame timings now include FRAME_HOLD_PADDING (0.5s per frame)
                # so the total visual duration is longer than the raw audio. Pad the
                # audio with trailing silence so the audio track matches the video.
                last_end = max((timings[p][1] for p in positions), default=duration)
                if last_end > duration:
                    audio_path_seg = pad_audio_with_silence(audio_path_seg, last_end)
                    duration = last_end
                segment_audio_paths.append(audio_path_seg)
                chapter_offset += duration

            # If most/all segments that HAD real dialogue to speak ended up
            # falling back to silence, this isn't "a quiet chapter" — it's a
            # broken TTS pipeline (most commonly: edge-tts's endpoint,
            # speech.platform.bing.com, is unreachable from this network —
            # firewall/security-list egress rules on cloud hosts are a common
            # cause). Every prior signal along the way (translation, rephrase,
            # loudnorm, mux) looks completely normal even when this has happened,
            # because each stage just sees "silence" as valid audio input and
            # passes it through without error. Surface it loudly here instead of
            # letting the job report success with a genuinely silent video.
            if tts_attempted > 0:
                tts_fail_ratio = tts_failed / tts_attempted
                if tts_fail_ratio >= 0.9:
                    log.error(
                        "[%s] TTS FAILED for %d/%d narrated segments (%.0f%%) — "
                        "edge-tts is not producing audio. Check network access to "
                        "speech.platform.bing.com from this host (firewall/security-"
                        "list egress rules are a common cause on cloud VMs). The "
                        "output video for this chapter will be SILENT.",
                        chapter.tag, tts_failed, tts_attempted, tts_fail_ratio * 100,
                    )
                elif tts_fail_ratio > 0.2:
                    log.warning(
                        "[%s] TTS failed for %d/%d narrated segments (%.0f%%) — "
                        "partial audio dropout, check edge-tts connectivity",
                        chapter.tag, tts_failed, tts_attempted, tts_fail_ratio * 100,
                    )

            # Build final per-frame durations from the timings.
            # Guard against None entries (can happen if a segment had no positions
            # or an error left a frame_timing slot unpopulated). Default to
            # MIN_FRAME_DURATION so the video never has a zero-duration frame.
            frame_durations = []
            for t in frame_timing:
                if t is not None:
                    frame_durations.append(t[1] - t[0])
                else:
                    frame_durations.append(MIN_FRAME_DURATION)
                    log.warning("[%s] frame_timing had None entry — using MIN_FRAME_DURATION (%.1fs)", chapter.tag, MIN_FRAME_DURATION)

            if manifest and manifest.frames:
                for pos, f_entry in enumerate(manifest.frames):
                    if pos < len(frame_durations):
                        f_entry.duration = frame_durations[pos]
                # Map each frame to ITS segment's narration text via the
                # segment's own `positions` list. `segments` is one entry per
                # source panel / scroll-group (~12), NOT one per frame (~40),
                # so the previous `segments[pos]` indexing silently pulled the
                # wrong panel's text onto every frame past the first dozen and
                # left the rest blank — a manifest-metadata desync (it does
                # not affect the rendered A/V, which is driven by
                # frame_durations + the assembled audio track).
                for seg in segments:
                    seg_text = seg[1] if len(seg) > 1 else ""
                    for sp in (seg[2] if len(seg) > 2 else []):
                        if 0 <= sp < len(manifest.frames):
                            manifest.frames[sp].narration_text = seg_text
                manifest.save(manifest_path)

            cfg.write_progress("render", chapter.index - 1, total,
                               f"Chapter {chapter.index}/{total}: building audio track")
            audio_path = build_chapter_audio_track(
                cfg, chapter, segment_audio_paths, narration_expected=tts_attempted > 0,
            ) if segment_audio_paths else None

            # The video timeline (frame_durations) was built to match the RAW,
            # pre-loudnorm segment audio exactly. But build_chapter_audio_track's
            # loudnorm pass (a single-pass/dynamic normalization, not two-pass
            # "measured" mode) can shift the final audio's duration by a small
            # but real amount due to its internal lookahead/limiter buffering.
            # render_chapter muxes with `-shortest`, so if the post-loudnorm
            # audio ends up LONGER than the video timeline, the tail of the
            # narration gets silently cut off mid-sentence. Re-probe the actual
            # final audio duration here and extend the last frame's hold time
            # to cover it, so narration is never truncated.
            if audio_path and audio_path.exists():
                try:
                    final_audio_duration = get_audio_duration(audio_path)
                    video_duration = sum(frame_durations)
                    if final_audio_duration > video_duration + 0.05 and frame_durations:
                        shortfall = final_audio_duration - video_duration
                        frame_durations[-1] += shortfall
                        log.info(
                            "[%s] extended last frame by %.3fs to cover loudnorm "
                            "duration drift (audio %.3fs vs video %.3fs) — "
                            "prevents narration from being cut off",
                            chapter.tag, shortfall, final_audio_duration, video_duration,
                        )
                except RuntimeError as e:
                    log.warning("[%s] could not verify final audio duration: %s", chapter.tag, e)

            cfg.write_progress("render", chapter.index - 1, total,
                               f"Chapter {chapter.index}/{total}: rendering {len(frame_paths)} frames")
            video_path = render_chapter_with_retry(cfg, chapter, frame_paths, frame_durations, audio_path)

            if not video_path:
                log.warning("[%s] rendering failed after retries — substituting silent black placeholder video", chapter.tag)
                expected_chap_dur = sum(frame_durations) if frame_durations else SILENT_FRAME_DURATION
                video_path = generate_black_placeholder_chapter(
                    cfg,
                    chapter.tag,
                    expected_chap_dur,
                    f"Chapter {chapter.index} unavailable",
                )
                placeholder_chapters.append(chapter.tag)
                state_store.record(
                    cfg.job_id, Stage.CHAPTER, State.RETRYABLE, chapter_id=chapter.tag,
                    error_code="RENDER_FAILED_PLACEHOLDER_USED", retry_category=classify_retry("render failed, placeholder used"),
                )
            else:
                state_store.record(
                    cfg.job_id, Stage.CHAPTER, State.COMPLETE, chapter_id=chapter.tag,
                    artifact_path=video_path, duration=time.time() - t0,
                )

            chapter_videos.append(video_path)

            log.info("[%s] done in %.1fs", chapter.tag, time.time() - t0)
            cfg.write_progress("render", chapter.index, total, f"Chapter {chapter.index}/{total} rendered")
        except Exception as e:
            # One chapter failing (TTS totally unavailable, a corrupt
            # source image, an OCR/ffmpeg crash, etc.) must not take
            # down the rest of a multi-day batch. Log it loudly, skip
            # this chapter (it's naturally retried on the next resumed
            # run since it never wrote a completed chapter video), and
            # keep processing the remaining chapters.
            log.error(
                "[%s] chapter FAILED and will be skipped this run: %s",
                chapter.tag, e, exc_info=True,
            )
            state_store.record(cfg.job_id, Stage.CHAPTER, State.RETRYABLE, chapter_id=chapter.tag,
                                error_message=str(e)[:500], retry_category=classify_retry(e))
            cfg.write_progress(
                "render", chapter.index, total,
                f"Chapter {chapter.index}/{total} FAILED: {e}", status="warning",
            )
            continue

    if not chapter_videos:
        state_store.record(cfg.job_id, Stage.JOB, State.FAILED, error_code="NO_CHAPTERS")
        cfg.write_progress("render", total, total, "No chapter videos produced", status="error")
        raise RuntimeError("No chapter videos were produced — nothing to merge.")

    dropped_chapters = total - len(chapter_videos)
    if dropped_chapters > 0:
        log.warning(
            "%d/%d chapters were skipped this run due to failures — job will "
            "complete with a video MISSING that content. Check pipeline_state.sqlite3 "
            "for RETRYABLE chapters and rerun the same --work-dir to fill them in.",
            dropped_chapters, total,
        )
    if placeholder_chapters:
        log.warning(
            "%d/%d chapters rendered as black \"unavailable\" placeholders "
            "after render retries failed (%s) — job will complete but is NOT "
            "a clean success. Check pipeline_state.sqlite3 for RETRYABLE "
            "chapters and rerun the same --work-dir to fill them in.",
            len(placeholder_chapters), total, ", ".join(placeholder_chapters),
        )

    if cfg.intro:
        try:
            cfg.write_progress("merge", total, total, "Building intro")
            intro_video = build_intro_video(cfg, chapters)
            if intro_video and intro_video.exists():
                chapter_videos = [intro_video, *chapter_videos]
        except Exception as e:
            log.warning("intro build failed (%s) — continuing without it", e)

    cfg.write_progress("merge", total, total, "Merging chapter videos")
    state_store.record(cfg.job_id, Stage.MERGE, State.RUNNING)
    try:
        merged = merge_chapters(cfg, chapter_videos)
        state_store.record(cfg.job_id, Stage.MERGE, State.COMPLETE, artifact_path=merged)
    except Exception as e:
        state_store.record(cfg.job_id, Stage.MERGE, State.FAILED, error_message=str(e)[:500],
                            retry_category=classify_retry(e))
        state_store.record(cfg.job_id, Stage.JOB, State.FAILED, error_code="MERGE_FAILED")
        raise

    cfg.write_progress("bgm", total, total, "Finalizing output")
    state_store.record(cfg.job_id, Stage.FINAL_QA, State.RUNNING)
    try:
        finalize_output(cfg, merged)
        state_store.record(cfg.job_id, Stage.FINAL_QA, State.COMPLETE, artifact_path=cfg.output_path)
    except Exception as e:
        state_store.record(cfg.job_id, Stage.FINAL_QA, State.FAILED, error_message=str(e)[:500],
                            retry_category=classify_retry(e))
        state_store.record(cfg.job_id, Stage.JOB, State.FAILED, error_code="FINAL_QA_FAILED")
        raise

    elapsed = time.time() - start
    # A placeholder chapter pads chapter_videos up to `total`, so
    # dropped_chapters alone would read as 0 for a run that actually has a
    # black "unavailable" screen standing in for real content — check both,
    # or a placeholder-only run would be misreported as a clean COMPLETE.
    final_state = State.UNCERTAIN if (dropped_chapters > 0 or placeholder_chapters) else State.COMPLETE
    state_store.record(cfg.job_id, Stage.JOB, final_state,
                        duration=elapsed, artifact_path=cfg.output_path,
                        metadata={
                            "chapters_total": total,
                            "chapters_dropped": dropped_chapters,
                            "chapters_placeholder": len(placeholder_chapters),
                        })

    # cleanup_temp() deletes cfg.work_dir, which is also where
    # pipeline_state.sqlite3 lives (see `state_store` above) — it must run
    # LAST, after every state_store.record() call, or the final JOB-COMPLETE
    # write above hits "unable to open database file" on its own now-deleted
    # directory and the process exits as if a fully successful render had
    # crashed (cfg.output_path itself lives outside work_dir and is already
    # safely written by this point either way).
    cleanup_temp(cfg)

    cfg.write_progress("done", total, total, f"Pipeline complete in {elapsed/60:.1f} min", status="done")
    log.info("PIPELINE COMPLETE in %.1f minutes. Output: %s", elapsed / 60, cfg.output_path)
    if dropped_chapters > 0 or placeholder_chapters:
        log.warning(
            "Job marked UNCERTAIN (not COMPLETE): %d/%d chapters missing, "
            "%d/%d chapters are black \"unavailable\" placeholders. This is "
            "not a silent success.",
            dropped_chapters, total, len(placeholder_chapters), total,
        )


